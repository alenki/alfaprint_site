/**
 * Префикс площадки для ссылок, написанных РУКАМИ.
 *
 * Сайт стоит в подкаталоге (`/alfaprint` на lumako.ru). Next подставляет этот
 * префикс сам во всё, что собирает он: `_next/static`, шрифты, иконку, `<Link>`.
 * Но строка `url(/logos/…)` в инлайновом стиле для него — просто строка, и
 * маска клиентской марки без префикса уедет в корень домена, где её нет.
 *
 * Значение приходит из `next.config.ts` (`env.NEXT_PUBLIC_BASE_PATH`) и
 * подставляется на сборке, так что в бандле остаётся литерал. Переезд сайта в
 * корень домена делается одной правкой конфига: пустая строка здесь законна.
 */
export const BASE_PATH = process.env.NEXT_PUBLIC_BASE_PATH ?? '';

/** Путь к файлу из `public/`, готовый к вставке в разметку или в CSS. */
export const asset = (path: string) => `${BASE_PATH}${path}`;
