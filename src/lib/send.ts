import { text, type BlankState } from '@/lib/blank';

/**
 * ОТПРАВКА ОБРАЩЕНИЯ. ОДИН ШОВ, И ЗА НИМ ПОКА НИЧЕГО НЕТ.
 *
 * ПОЧЕМУ ФАЙЛ СУЩЕСТВУЕТ РАНЬШЕ ПРИЁМЩИКА. Бланк умеет собирать сообщение
 * (`lib/blank.ts`) и умеет его показывать (`ui/Blank.tsx`); третьего умения,
 * «отдать кому-то», у него не было вовсе, и добавлять его прямо в разметку
 * значило бы размазать выбор транспорта по кнопке. Здесь он в одном месте, и
 * когда приёмщик появится, правки будет ровно две строки ниже.
 *
 * ДВА РЕЖИМА, И РАЗНИЦА НЕ В КНОПКЕ, А В ОБЕЩАНИИ.
 *
 * `messenger` это то, как лист работал с первого дня: страница собирает
 * текст, отдаёт его ссылке `wa.me`, и отправляет человек своей рукой. Ничего
 * подтверждать не нужно, потому что страница ничего и не отправляла.
 *
 * `auto` это то, к чему лист готов сейчас: обращение уходит само, и с этим
 * приходит всё, чего у листа никогда не было. Экран «отправлено», потому что
 * теперь есть что подтверждать. Экран «не ушло», потому что отправка умеет не
 * доходить. И возврат к `wa.me` в самом этом экране, потому что упавшая
 * автоотправка обязана опускаться ровно до того, что работало раньше, а не до
 * пустого места.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. Ни токена, ни адреса бота, ни чужого ключа. Сайт
 * собран `output: 'export'` и лежит файлами на `lumako.ru`: закрытого места
 * для ключа у него нет ни одного, и класть ключ в бандл нельзя, потому что
 * бандл читается из devtools кем угодно. Разбор всех четырёх мест, где ключ
 * может лежать по-настоящему, записан в `docs/kontakty.md`, в «Открытом».
 */

export type SendMode = 'messenger' | 'auto';

/**
 * РЕЖИМ ЛИСТА. Одно слово, и оно решает всё: лид полосы, надпись на кнопке,
 * оговорку под ней и то, что вообще происходит по нажатию.
 *
 * СЕЙЧАС `auto`, И ЭТО СОЗНАТЕЛЬНО ОПЕРЕЖАЕТ ПРИЁМЩИКА. Форма со всеми
 * четырьмя состояниями собрана и смотрится вживую; в разработке отправка
 * ИМИТИРУЕТСЯ (см. ниже), в сборке для площадки при пустом `SEND_ENDPOINT`
 * она честно падает в «не ушло» и отдаёт человека WhatsApp.
 *
 * ПЕРЕД ВЫКЛАДКОЙ, ПОКА ПРИЁМЩИКА НЕТ, ЗДЕСЬ ДОЛЖНО СТОЯТЬ `messenger`.
 */
export const SEND_MODE: SendMode = 'auto';

/**
 * Адрес приёмщика. Пустая строка значит, что приёмщика ещё нет, и это НЕ
 * заглушка на будущее, а честное «пока некуда»: код ниже на неё смотрит.
 */
export const SEND_ENDPOINT = '';

/** Сколько ждём приёмщика, прежде чем считать, что не дождались. */
const TIMEOUT_MS = 12000;

export class SendError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'SendError';
  }
}

/**
 * ОТДАЁТ ОБРАЩЕНИЕ ПРИЁМЩИКУ. Кидает `SendError`, если не дошло.
 *
 * УСПЕХ НЕ ПОДДЕЛЫВАЕТСЯ В СБОРКЕ ДЛЯ ПЛОЩАДКИ, и это главная строчка файла.
 * Имитация живёт под `NODE_ENV !== 'production'`, то есть в разработке, где
 * состояния листа и смотрят. Отдай мы «отправлено» на живом сайте с пустым
 * адресом, каждое обращение молча пропадало бы, а человек уходил бы уверенный,
 * что его прочитали: это худшее, чем такая форма может кончиться, и хуже, чем
 * не иметь её вовсе.
 */
export async function send(s: BlankState): Promise<void> {
  if (!SEND_ENDPOINT) {
    if (process.env.NODE_ENV === 'production') {
      throw new SendError('Приёмщик не настроен');
    }
    await new Promise((r) => setTimeout(r, 1100));
    return;
  }

  /* Обрыв связи в метро это не ошибка приёмщика, но человеку разницы нет:
     ждать бесконечно нельзя, иначе кнопка остаётся в «отправляем» навсегда. */
  const ac = new AbortController();
  const timer = setTimeout(() => ac.abort(), TIMEOUT_MS);

  try {
    const res = await fetch(SEND_ENDPOINT, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      /* Уходит и готовый текст, и поля по отдельности. Текст затем, что
         приёмщику его не пересобирать: что человек видел на листе, то и
         придёт. Поля затем, что по ним потом можно считать, а по склеенной
         строке нельзя. */
      body: JSON.stringify({ text: text(s), fields: s }),
      signal: ac.signal,
    });
    if (!res.ok) throw new SendError(`Приёмщик ответил ${res.status}`);
  } catch (e) {
    throw e instanceof SendError ? e : new SendError('Связь оборвалась');
  } finally {
    clearTimeout(timer);
  }
}
