/**
 * ЦЕНА РАЗРЯДАМИ, НЕРАЗРЫВНО: «42 800 ₽». Оба пробела U+00A0.
 *
 * Руками, а не через `Intl.NumberFormat`: разделитель разрядов у русской
 * локали зависит от версии ICU (у одних это U+00A0, у других узкий U+202F), и
 * сервер с браузером могут набрать одно и то же число разными знаками. Тогда
 * гидратация ругается на расхождение, а строка на листе меняет ширину.
 */
export function rub(n: number): string {
  return `${String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ' ')} ₽`;
}
