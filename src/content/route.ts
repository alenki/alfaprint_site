export type Frame = {
  /** Номер кадра. Строкой, потому что он печатается как есть, с нулём. */
  n: string;
  /** Подпись на плашке. Прописными её делает набор, а не эта строка. */
  title: string;
  /**
   * Что на снимке. Это не подпись и не повтор подписи: подпись называет
   * ШАГ пути, а описание называет ВИД, по которому шаг узнают на местности.
   * Читает его и скринридер, и тот, у кого снимки не пришли.
   */
  alt: string;
  /**
   * Кадрирование по горизонтали для закрытого кадра: в полосе он сжат до
   * узкой вертикали, и «по центру» не всегда показывает то, по чему кадр
   * узнают. Значение идёт прямо в object-position.
   */
  focus?: string;
};

