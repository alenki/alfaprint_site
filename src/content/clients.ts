export type ClientMark = {
  /** Имя файла маски в /logos, без расширения. */
  slug: string;
  /** Как знак читается вслух. Единственное, что достаётся скринридеру. */
  name: string;
  /** Ширина маски ÷ 300 px. */
  ar: number;
  /**
   * Изделие, на котором знак снят в работах агентства. Не выводится: это
   * ссылка на источник. `null` стоит только у заглушки: такой знак вымышлен
   * и не напечатан ни на чём.
   */
  seen: string | null;
};

