/**
 * КАТАЛОГ: десять направлений, разложенных не по прайсу, а по природе
 * изображения.
 *
 * ФОРМА K · КРАСКА    изображение делает краска.
 * ФОРМА R · МАТЕРИАЛ  изображение делает сам материал: рез, гравировка,
 *                       стежок. Краски там нет вовсе.
 *
 * Это единственное деление каталога, и оно же служит концепцией страницы.
 *
 * priceFrom заполняет клиент. Три цены в строке 09 это единственные реальные
 * цифры, опубликованные самой «Альфой». Остальные слоты пустые: цену,
 * которой мы не знаем, выдумывать нельзя.
 */

export type Forme = 'k' | 'r';

export type CatalogueRow = {
  id: string;
  forme: Forme;
  n: string;
  /**
   * ПОЛНОЕ ТОРГОВОЕ ИМЯ. Уходит в JSON-LD (lib/schema.ts), в aria-label строки
   * и печатается видимой шапкой оттиска. Сокращать нельзя: «широкоформатная
   * печать» это то, что люди набирают в поиске.
   */
  title: string;
  /**
   * ИМЯ НА ФОРМЕ: то, что стоит в строке крупным кеглем.
   *
   * Замер: ширина самого широкого имени («Интерьерная печать») равна
   * 10,57 × кегль при трекинге −0,026em. Мера строки это ширина полосы
   * (доли 7…12) минус гнездо кнопки: 438 px на 1024, 628 px на 1440.
   * Полные имена туда не встают: «Брендированные сувениры» потребовали бы
   * кегля 33 на 1024, и четыре имени из десяти ломались бы на две строки,
   * а одна сломанная строка в столбце из десяти убивает весь его ритм.
   * Короткое имя поднимает кегль до 39 / 55 px, и не переносится ни одно.
   *
   * Это НЕ цеховой жаргон: «Лазер» и «Интерьерка» на полосу не выйдут.
   * Слово всегда остаётся нормальным русским, а полное имя не прячется в
   * sr-only: оно стоит шапкой оттиска, видимым текстом, на всех форматах.
   */
  word: string;
  /**
   * ОПИСАНИЕ ПРОЦЕССА: две строки в раскрытой строке §03.
   *
   * Говорит, ЧТО делает машина, а не что можно заказать: перечень изделий
   * стоит рядом, на самом оттиске, и повторять его здесь нечем. Ни одного
   * факта сверх того, что уже сказано в items и spec: цену, срок и свойство,
   * которых мы не знаем, выдумывать нельзя.
   *
   * У позиций формы R описание обязано быть верным их природе: изображение
   * там делает материал, и слово «краска» в нём стоять не может.
   */
  blurb: string;
  items: string[];
  /**
   * Техническая метка справа это реальное свойство услуги, не украшение.
   * Печатается в раскрытой строке §03, по правому краю панели, на оси
   * короткой линейки.
   */
  spec: string;
  /** «от N ₽»: CONFIRM WITH CLIENT. Если пусто, справа стоит только spec. */
  priceFrom?: string;
};

