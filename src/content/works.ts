export type Archetype =
  | 'vizitka'
  | 'flag'
  | 'futbolka'
  | 'sticker'
  | 'kruzhka'
  | 'pechat'
  | 'ezhednevnik'
  | 'tablichka'
  | 'banner';

export type Work = {
  id: string;
  archetype: Archetype;
  /** Строки, которые набираются внутри самого изделия. */
  content: string[];
  /** Две строки подписной планки: что это и к какой услуге относится. */
  caption: [string, string];
  /**
   * Та же подпись на узкую меру. Ставится не по ширине экрана, а по ширине
   * самой плитки, см. `WorkTile`. Обе строки держатся короче семнадцати
   * знаков: на телефоне плитке достаётся около 195 px, и переносить тут уже
   * нечего.
   */
  short: [string, string];
  /** Ширина в колонках спуска: 1 или 2. */
  span: 1 | 2;
  /** CONFIRM WITH CLIENT: путь к реальной съёмке. */
  photo: string | null;
};

