import { Noto_Serif, Golos_Text, Martian_Mono, Montserrat } from 'next/font/google';

/**
 * ТРИ ГАРНИТУРЫ И ЧЕТЫРЕ РОЛИ
 *
 * ИМЕНИ ФИРМЫ СРЕДИ НИХ НЕТ, и это по-прежнему главное про этот файл.
 *
 * Имя стоит на листе дважды, в шапке §01 и на вылете §08, и оба раза оно
 * ПЕЧАТАЕТСЯ формами логотипа, а не набирается никакой гарнитурой: пять
 * букв «LeGko» обведены с логотипа агентства, см. `ALPHABET` в `Mark.tsx`.
 * Смена текстовой гарнитуры этого места не касается и касаться не может.
 *
 * ── NOTO SERIF: форма K, и дисплей, и голос.
 *    Антиква, и это ВЫБОР САЙТА, а не повтор знака. Логотип Legko это
 *    тяжёлый геометрический гротеск, и строка «РЕКЛАМНОЕ АГЕНТСТВО» под ним
 *    тоже гротеск. Лист же набран как печатный оттиск, и антиква держит его
 *    голос: крупный набор полос, корпус, подписи. Имя фирмы при этом стоит
 *    своими формами и с набором не спорит.
 *
 *    ШИРИНА 87.5 НА ДИСПЛЕЕ ОСТАВЛЕНА. Её когда-то сняли обмером с узкой
 *    антиквы прежнего знака, и с тех пор на ней замерено всё, что на листе
 *    считает строки: две строки спецификации §03, одна строка слова формы,
 *    авторские переносы заголовков. Сменить ширину значило бы переснять все
 *    эти законы, а причины менять её нет: у нового знака антиквы нет вовсе,
 *    и подгонять её не к чему. Отсюда `font-stretch: 87.5%` на дисплейной
 *    роли в `globals.css` и полная ширина на корпусе.
 *
 *    ОСЬ wght 100…900 ВЗЯТА РАДИ РОЛЕЙ: 800/700 на дисплее против 400/500
 *    в тексте это две ступени, а не оттенок. PT Serif, «Паратайп», была бы
 *    роднее по происхождению и ближе Golos Text по крови, но у неё только
 *    400 и 700, а при `font-synthesis: none` промежуточные веса молча
 *    съехали бы к соседним и серость полосы поехала бы с ними.
 *
 * ── GOLOS TEXT: ОСНАСТКА, и ровно пять ссылок.
 *    «Паратайп», Москва. Держала обе роли формы K до 12.09, ушла с листа
 *    вместе со сменой антиквы и вернулась обратно ТОЛЬКО в шапку: токен
 *    `--font-nav` стоит у `.navlink` и у `.menu-row-word`, то есть у одних и
 *    тех же пяти ссылок разделов в двух их видах, настольном и телефонном.
 *
 *    ДОВОД НЕ «ТАК БЫЛО», А ЧТО ЭТО ЗА ТЕКСТ. Шапка не набор, а оснастка:
 *    она стоит НАД листом, липнет к верху, ездит с прокруткой и к полосе не
 *    относится. Ей не обязательно быть одной породы с тем, что под ней, и
 *    гротеск в ней читается как надпись на приборе, а не как чужая антиква.
 *    Кнопка «Заказать», телефон меню и каналы под ним НЕ ССЫЛКИ РАЗДЕЛОВ и
 *    остаются на антикве: это действия, а не навигация.
 *
 * ── MARTIAN MONO: форма R, машина.
 *    Evil Martians. Кириллица родная, цифры табличные по природе: счётчик
 *    и часы не дёргаются. Взята вместо JetBrains Mono сознательно:
 *    JetBrains тянет за собой семантику «редактор кода».
 *
 * ── ЧТО СТОЯЛО ЗДЕСЬ ДО ЭТОЙ ПРАВКИ
 *    Ещё раньше дисплейную роль держала Noto Serif Display, антиква той же
 *    надсемьи. Её вертикальные метрики, прописная 714 и строчная 536, и её
 *    ось ширины 62.5…100 в ТОЧНОСТИ совпадают с нынешними, поэтому ни один
 *    кегль в `globals.css` не двинулся ни при одной из двух смен подряд.
 *    Поправка по прописной у `.kp-arrow` при этом константа метрическая и
 *    пересчитана: ((1069−293)/2 − 714/2)/1000 = 0,031, было 0,030.
 *
 * ── MONTSERRAT 900: ЧЕТВЁРТАЯ ГАРНИТУРА ПОД ОДНУ РОЛЬ.
 *    Только цифры и только приладочный лист. Четвёртая гарнитура это
 *    отступление от записанного решения («четвёртой гарнитуры на сайте нет»,
 *    `docs/design-spec.md`), и оно осознанное: на листе просили голос ЗНАКА,
 *    а знаком считать нечем.
 *
 *    ПОЧЕМУ НЕ ЛОГОТИП. В `ALPHABET` пять букв, L e G k o, и цифр среди них
 *    нет ни одной; `setLogotype` на всём прочем бросает. Напечатать «047»
 *    формами знака физически нечем.
 *
 *    ПОЧЕМУ ИМЕННО ОНА. Логотип Legko геометрический: круглые «e», «G», «o»
 *    почти циркульные, штрих постоянный, окончания плоские. Montserrat
 *    рисует цифры той же породой, circle-and-stem, и на нуле это видно
 *    сразу.
 *
 *    ПОЧЕМУ ВЕС 900. ОБМЕРОМ, как и всё в этом файле. У логотипа стойка
 *    около 31,9 % роста прописной (стойки «L» и «k» на прописной 100). У
 *    Montserrat замер стойки нуля по растру даёт:
 *
 *        500 → 13,99 %   600 → 18,06 %   700 → 22,41 %   750 → 24,83 %
 *        800 → 27,24 %   850 → 29,79 %   900 → 32,19 %
 *
 *    Ближайший к 31,9 это 900, промах 0,29. Прежний знак был вдвое легче,
 *    и под него здесь стоял вес 700; тяжёлое слово Legko его перевесило.
 *
 *    ОПТИЧЕСКАЯ СЕРЕДИНА ОТ СМЕНЫ ВЕСА НЕ СДВИНУЛАСЬ. Контур нуля на 900
 *    занимает от −16 до 716 единиц, на 700 от −12 до 712: вырос на четыре
 *    единицы в обе стороны, и середина осталась на 350. Поправка
 *    `translateY` у `.mk-num` и осадка запасной, снятые на 700, верны и
 *    здесь (замер по контурам файла Google Fonts, версия 31).
 *
 *    ЧЕСТНАЯ ФОРМУЛИРОВКА: это ПОХОЖЕСТЬ, а не родство. Совпали ПОРОДА и
 *    ТОЛЩИНА ШТРИХА, а не рисунок, и выдавать Montserrat за гарнитуру знака
 *    нельзя.
 *
 *    ЦЕНА СНИЖЕНА ДО ПРЕДЕЛА: латиница, один вес, и на листе десять знаков.
 *    Кириллица не берётся: на приладочном листе букв нет вовсе.
 *
 *    ПО ПРОВОДУ ЭТО ОДИН ФАЙЛ БАЗОВОЙ ЛАТИНИЦЫ. В сборку `next/font` кладёт
 *    все диапазоны из ответа Google, а не только заказанный, но берётся из
 *    них РОВНО ОДИН: в остальных на листе нет ни знака, и браузер за ними не
 *    ходит. Google отдаёт на любой вес один и тот же переменный файл, так что
 *    смена 700 на 900 провод не утяжелила. Плюс `preload: false`, то есть и
 *    этот файл идёт не в старте, а под самим листом.
 *
 *    ЦИФРЫ РАВНОШИРОКИЕ ТОЛЬКО С `tnum`. Без него у Montserrat цифры
 *    пропорциональные, с ним все десять по 0,70 кегля на 900. `.mk-num`
 *    табличные включает, и счётчик от этого не дёргается.
 *
 * У всех гарнитур с кириллицей она нарисована, а не добрана подстановкой.
 */

export const notoSerif = Noto_Serif({
  subsets: ['cyrillic', 'latin'],
  axes: ['wdth'],
  display: 'swap',
  preload: true,
  variable: '--font-noto-serif',
  fallback: ['Georgia', 'Times New Roman', 'serif'],
  adjustFontFallback: false,
});

export const golos = Golos_Text({
  subsets: ['cyrillic', 'latin'],
  display: 'swap',
  preload: true,
  variable: '--font-golos',
  fallback: ['Segoe UI', 'system-ui', 'sans-serif'],
  adjustFontFallback: false,
});

export const martian = Martian_Mono({
  subsets: ['cyrillic', 'latin'],
  axes: ['wdth'],
  display: 'swap',
  preload: true,
  variable: '--font-martian',
  fallback: ['ui-monospace', 'monospace'],
  adjustFontFallback: false,
});

/**
 * Один вес и одна письменность: на приладочном листе десять знаков, и все
 * они цифры. `preload` здесь ВЫКЛЮЧЕН намеренно: лист ждёт гарнитуры не
 * дольше 250 мс и умеет считать в запасной, а предзагрузка ради счётчика
 * отодвигала бы шрифты, которыми набран сам сайт.
 */
export const montserrat = Montserrat({
  subsets: ['latin'],
  weight: '900',
  display: 'swap',
  preload: false,
  variable: '--font-montserrat',
  fallback: ['Arial Black', 'Helvetica', 'system-ui', 'sans-serif'],
  adjustFontFallback: false,
});

export const fontVariables = `${notoSerif.variable} ${golos.variable} ${martian.variable} ${montserrat.variable}`;
