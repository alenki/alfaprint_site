import { Noto_Serif, Golos_Text, Martian_Mono, Montserrat } from 'next/font/google';

/**
 * ТРИ ГАРНИТУРЫ И ЧЕТЫРЕ РОЛИ
 *
 * ИМЕНИ ФИРМЫ СРЕДИ НИХ НЕТ, и это по-прежнему главное про этот файл.
 *
 * Имя стоит на листе дважды, в шапке §01 и на вылете §08, и оба раза оно
 * ПЕЧАТАЕТСЯ формами логотипа, а не набирается никакой гарнитурой: четыре
 * буквы обведены с оригинала в 1599 px, пять построены в его же системе, см.
 * `ALPHABET` в `Mark.tsx`. Смена текстовой гарнитуры этого места не касается
 * и касаться не может.
 *
 * ── NOTO SERIF ─ форма K, и дисплей, и голос.
 *    Антиква. Взята с логотипа, но не с той его строки, на которую смотрят.
 *    В знаке ДВЕ ПОРОДЫ: «АЛЬФА» гротеск, «РЕКЛАМНОЕ АГЕНТСТВО» антиква.
 *    Лист повторял первую строку, теперь повторяет вторую.
 *
 *    ВЫБОР СДЕЛАН ОБМЕРОМ, как и всё в этом файле. Строка «РЕКЛАМНОЕ
 *    АГЕНТСТВО» в оригинале занимает 239 px при росте прописной 14 px, то
 *    есть 17.07 роста на всю строку. Это узко: из системных антикв с
 *    кириллицей ближайшая, Cambria, даёт 17.69, Times New Roman 19.44,
 *    Bookman 19.83. Ось ширины Noto Serif закрывает разрыв ровно, на
 *    wdth 87.5 выходит 17.05. Отсюда `font-stretch: 87.5%` на дисплейной
 *    роли в `globals.css` и полная ширина на корпусе.
 *
 *    ТОЧНО ОПОЗНАТЬ ГАРНИТУРУ ЛОГОТИПА НЕЛЬЗЯ, и делать вид, что можно, не
 *    стоит: 14 px роста прописной это не тот материал, по которому отличают
 *    брусковую засечку от скруглённой. Совпала ПРОПОРЦИЯ, а не рисунок, и
 *    честная формулировка тут именно такая. Судя по всему, в оригинале
 *    стояла системная антиква из тех, что были у рисовавшего знак под рукой,
 *    и ни одну из них всё равно нельзя отдать в веб как шрифт.
 *
 *    ОСЬ wght 100…900 ВЗЯТА РАДИ РОЛЕЙ: 800/700 на дисплее против 400/500
 *    в тексте это две ступени, а не оттенок. PT Serif, «Паратайп», была бы
 *    роднее по происхождению и ближе Golos Text по крови, но у неё только
 *    400 и 700, а при `font-synthesis: none` промежуточные веса молча
 *    съехали бы к соседним и серость полосы поехала бы с ними.
 *
 * ── GOLOS TEXT ─ ОСНАСТКА, и ровно пять ссылок.
 *    «Паратайп», Москва. Держала обе роли формы K до 12.09, ушла с листа
 *    вместе со сменой антиквы и вернулась обратно ТОЛЬКО в шапку: токен
 *    `--font-nav` стоит у `.navlink` и у `.menu-row-word`, то есть у одних и
 *    тех же пяти ссылок разделов в двух их видах, настольном и телефонном.
 *
 *    ДОВОД НЕ «ТАК БЫЛО», А ЧТО ЭТО ЗА ТЕКСТ. Шапка не набор, а оснастка:
 *    она стоит НАД листом, липнет к верху, ездит с прокруткой и к полосе не
 *    относится. Ей не обязательно быть одной породы с тем, что под ней, и
 *    гротеск в ней читается как надпись на приборе, а не как чужая антиква.
 *    Кнопка «Заказать», телефон меню и каналы под ним НЕ ССЫЛКИ РАЗДЕЛОВ и
 *    остаются на антикве: это действия, а не навигация.
 *
 * ── MARTIAN MONO ─ форма R, машина.
 *    Evil Martians. Кириллица родная, цифры табличные по природе: счётчик
 *    и часы не дёргаются. Взята вместо JetBrains Mono сознательно:
 *    JetBrains тянет за собой семантику «редактор кода».
 *
 * ── ЧТО СТОЯЛО ЗДЕСЬ ДО ЭТОЙ ПРАВКИ
 *    Ещё раньше дисплейную роль держала Noto Serif Display, антиква той же
 *    надсемьи. Её вертикальные метрики, прописная 714 и строчная 536, и её
 *    ось ширины 62.5…100 в ТОЧНОСТИ совпадают с нынешними, поэтому ни один
 *    кегль в `globals.css` не двинулся ни при одной из двух смен подряд.
 *    Поправка по прописной у `.kp-arrow` при этом константа метрическая и
 *    пересчитана: ((1069−293)/2 − 714/2)/1000 = 0,031, было 0,030.
 *
 *    ЧЕТВЁРТАЯ ГАРНИТУРА, Ysabeau Infant 850, здесь тоже жила и снята давно.
 *    ЕЁ ОБМЕР РАБОТАЕТ ДО СИХ ПОР: ширины построенных букв «Принта» выведены
 *    переносом ПРОСВЕТОВ Ysabeau Infant 850, см. `WHITE` и `SUB_WHITE` в
 *    `Mark.tsx`. Подобрана она была по «Л»: у логотипа это ТРЕУГОЛЬНИК без
 *    стойки, так её рисуют 32 начертания из 393 с кириллицей и весом от 700,
 *    и только у Ysabeau Infant при этом ещё и широкая «Ф». Числа сняты и
 *    записаны, самой гарнитуры для этого больше не нужно.
 *
 * ── MONTSERRAT 700 ─ ЧЕТВЁРТАЯ ГАРНИТУРА, И ОНА ВЕРНУЛАСЬ ПОД ОДНУ РОЛЬ.
 *    Только цифры и только приладочный лист. Возврат четвёртой гарнитуры это
 *    отступление от записанного решения («четвёртой гарнитуры на сайте нет»,
 *    `docs/design-spec.md`), и оно осознанное: на листе просили голос ЗНАКА,
 *    а знаком считать нечем.
 *
 *    ПОЧЕМУ НЕ ЛОГОТИП. В `ALPHABET` девять букв, А Л Ь Ф Р П И Н Т, и цифр
 *    среди них нет ни одной; `setLogotype` на всём прочем бросает. Напечатать
 *    «047» формами знака физически нечем, пока цифры не построены.
 *
 *    ПОЧЕМУ НЕ YSABEAU, хотя она и есть записанная замена. Её подбирали по
 *    «Л» и «Ф», а про ЦИФРЫ ни одна из этих букв не говорит ничего: у
 *    Ysabeau они гуманистические, с расширением штриха и с флажком у
 *    единицы. Логотип же геометрический: circle-and-stem, штрих постоянный,
 *    окончания плоские. Проверено рендером обеих против настоящих контуров
 *    знака.
 *
 *    ПОЧЕМУ ВЕС 700, А НЕ 900. ОБМЕРОМ, как и всё в этом файле, и обмер тут
 *    решает против глаза: на 900 полоса выглядела «в тон знаку», а замер
 *    показал перегруз в полтора раза. У логотипа стойка задана константой,
 *    `STEM = 22.9` на прописной 100 (`Mark.tsx`), то есть 22,9 % роста.
 *    У Montserrat замер стойки нуля по растру даёт:
 *
 *        500 → 13,99 %   600 → 18,06 %   700 → 22,41 %   750 → 24,83 %
 *        800 → 27,24 %   850 → 29,79 %   900 → 32,19 %
 *
 *    Ближайший к 22,9 это 700 (промах 0,49); точное попадание пришлось бы на
 *    710, и разница с семисотым на полном кегле меньше половины пикселя, то
 *    есть не стоит переменной оси в сборке. На 900 штрих был бы на 40 %
 *    толще знака.
 *
 *    ЧЕСТНАЯ ФОРМУЛИРОВКА: это ПОХОЖЕСТЬ, а не родство. Совпали ПОРОДА и
 *    ТОЛЩИНА ШТРИХА, а не рисунок, и выдавать Montserrat за гарнитуру знака
 *    нельзя ровно так же, как нельзя было выдавать Ysabeau.
 *
 *    ЦЕНА СНИЖЕНА ДО ПРЕДЕЛА: латиница, один статический вес, и на листе
 *    десять знаков. Кириллица не берётся — на приладочном листе букв нет
 *    вовсе.
 *
 *    ПО ПРОВОДУ ЭТО 16,1 КБ, и цифра замерена, а не прикинута. В сборку
 *    `next/font` кладёт пять файлов на 70 КБ (он выписывает все диапазоны из
 *    ответа Google, а не только заказанный), но берётся из них РОВНО ОДИН,
 *    базовая латиница: в остальных диапазонах на листе нет ни знака, и
 *    браузер за ними не ходит. Плюс `preload: false`, то есть и эти 16 КБ
 *    идут не в старте, а под самим листом.
 *
 *    ЦИФРЫ У НЕЁ РАВНОШИРОКИЕ САМИ ПО СЕБЕ: замер даёт 0,5 кегля на разряд
 *    и нулевой разброс по всем десяти И БЕЗ `tnum`. Счётчик не дёрнется,
 *    даже если табличные цифры однажды отключат.
 *
 * У всех гарнитур с кириллицей она нарисована, а не добрана подстановкой.
 */

export const notoSerif = Noto_Serif({
  subsets: ['cyrillic', 'latin'],
  axes: ['wdth'],
  display: 'swap',
  preload: true,
  variable: '--font-noto-serif',
  fallback: ['Georgia', 'Times New Roman', 'serif'],
  adjustFontFallback: false,
});

export const golos = Golos_Text({
  subsets: ['cyrillic', 'latin'],
  display: 'swap',
  preload: true,
  variable: '--font-golos',
  fallback: ['Segoe UI', 'system-ui', 'sans-serif'],
  adjustFontFallback: false,
});

export const martian = Martian_Mono({
  subsets: ['cyrillic', 'latin'],
  axes: ['wdth'],
  display: 'swap',
  preload: true,
  variable: '--font-martian',
  fallback: ['ui-monospace', 'monospace'],
  adjustFontFallback: false,
});

/**
 * Один вес и одна письменность: на приладочном листе десять знаков, и все
 * они цифры. `preload` здесь ВЫКЛЮЧЕН намеренно — лист ждёт гарнитуры не
 * дольше 350 мс и умеет считать в запасной, а предзагрузка ради счётчика
 * отодвигала бы шрифты, которыми набран сам сайт.
 */
export const montserrat = Montserrat({
  subsets: ['latin'],
  weight: '700',
  display: 'swap',
  preload: false,
  variable: '--font-montserrat',
  fallback: ['Arial Black', 'Helvetica', 'system-ui', 'sans-serif'],
  adjustFontFallback: false,
});

export const fontVariables = `${notoSerif.variable} ${golos.variable} ${martian.variable} ${montserrat.variable}`;
