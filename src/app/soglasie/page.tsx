import type { Metadata } from 'next';
import './soglasie.css';
import { SITE_URL } from '@/app/layout';
import { Section, Sheet } from '@/components/layout/Sheet';
import { VykhodnyeDannye } from '@/components/sections/VykhodnyeDannye';
import { COMPANY } from '@/content/site';
import { SOGLASIE, S_PATH } from '@/content/soglasie';
import { SEND_MODE } from '@/lib/send';

/**
 * ЛИСТ «СОГЛАСИЕ НА ОБРАБОТКУ ПЕРСОНАЛЬНЫХ ДАННЫХ».
 *
 * ТРЕТИЙ МАРШРУТ САЙТА И ПЕРВЫЙ, У КОТОРОГО НЕТ НИ ОДНОЙ ПОЛОСЫ. Главная
 * идёт восемью, «Контакты» четырьмя, и обе объявляют их в реестре раскладки,
 * чтобы хрома и указатель раздела шли за прокруткой. Здесь объявлять нечего:
 * лист это один разворот на один вопрос. `PlateProvider` ищет полосы по `id`
 * в самом документе и, не найдя ни одной, оставляет странице грунт бумаги,
 * см. разбор при `SECTION_META` в раскладке. Правок в раскладке лист не
 * требует ни одной.
 *
 * СВОЙ ХВОСТ У ЛИСТА КОНЧАЕТСЯ КОЛОФОНОМ, А ДАЛЬШЕ ИДЁТ §08. Первая редакция
 * закрывала лист сама, одним рядом разделов под волосяной, и довод был тот
 * же, что у «Контактов»: не оставить лист тупиком для пришедшего из поиска.
 * Довод остался верен, а ряд оказался мал: на бумаге во весь формат одна
 * строка машинного голоса читается не закрытием листа, а обрывом с подписью.
 * Выходные данные это то, чем кончается всякий печатный лист, и третий лист
 * не исключение.
 *
 * СТАТЬЯ 6 ДОГОВАРИВАЕТСЯ РЕЖИМОМ ОТПРАВКИ, А НЕ РУКОЙ. Хвост её берётся из
 * `SEND_MODE`, и это не украшение: при `messenger` лист утверждает, что до
 * нажатия в самом мессенджере у нас нет ничего, а такое утверждение обязано
 * перестать печататься в тот же день, когда бланк начнёт отправлять себя
 * сам. Здесь оно перестанет печататься само.
 */
export const metadata: Metadata = {
  title: SOGLASIE.title,
  /* Имя фирмы берётся из `COMPANY`, а не набрано здесь: в заголовке вкладки
     его дописывает шаблон раскладки, и две правды об одном имени разошлись
     бы при первой же правке. */
  description: `Какие данные записывает ${COMPANY.name}, зачем, на сколько и как их удалить. Коротко и без юридического языка. Счётчиков и cookie слежения на сайте нет.`,
  /* Адрес абсолютный и собран из двух источников: площадка из раскладки, путь
     из таблицы адресов. Тем же способом собраны оба других листа. */
  alternates: { canonical: `${SITE_URL}${S_PATH}` },
  openGraph: {
    type: 'website',
    locale: 'ru_RU',
    title: `${SOGLASIE.title} | ${COMPANY.name}`,
    description: `Какие данные записывает ${COMPANY.name}, зачем, на сколько и как их удалить. Без юридического языка.`,
  },
};

export default function SoglasiePage() {
  const articles = SOGLASIE.articles.map((a) =>
    /* Хвост последней статьи дописывается режимом отправки, а не лежит в
       содержании готовым: см. шапку файла. */
    a.n === '06' ? { ...a, body: [...a.body, SOGLASIE.siteSend[SEND_MODE]] } : a,
  );

  return (
    <main id="main">
      <Section
        id="soglasie"
        ground="paper"
        gain={0.6}
        className="pt-[clamp(88px,9.4vw,208px)] pb-[var(--section-pad)]"
      >
        <Sheet>
          <h1 className="t-h2 measure-tight">{SOGLASIE.title}</h1>
          <p className="t-lead fg-70 measure mt-[clamp(20px,2vw,38px)]">{SOGLASIE.lead}</p>
        </Sheet>

        {/* СПИСОК НУМЕРОВАННЫЙ РАЗМЕТКОЙ, А НЕ ТОЛЬКО НА ВИД. Номер статьи в
            юридическом тексте это адрес, по которому на неё ссылаются вслух
            («по пункту пятому»), и скринридер обязан его называть. Своё
            перечисление `<ol>` при этом снято: номера печатаются набором из
            содержания, потому что они двузначные с нулём («01»), а такого
            счётчика у списка нет. */}
        <Sheet as="div" className="mt-[clamp(56px,6vw,132px)]">
          <ol className="space-y-[clamp(34px,3.6vw,68px)]">
            {articles.map((a) => (
              <li key={a.n} className="sg-art">
                <span className="t-micro sg-art-n">{a.n}</span>
                <h2 className="sg-art-h">{a.heading}</h2>
                {a.body.map((p) => (
                  <p key={p} className="sg-art-p">
                    {p}
                  </p>
                ))}
              </li>
            ))}
          </ol>
        </Sheet>

        {/* ── Колофон ───────────────────────────────────────────────────────
            Реквизиты печатаются ТОЛЬКО заполненными. Пустой слот не оставляет
            здесь ни строки, ни отбивки: подпись «Реквизиты» без реквизитов
            говорит, что их скрыли, тогда как их просто ещё не дали. */}
        <Sheet className="mt-[clamp(56px,6vw,132px)]">
          <dl className="sg-colophon rule-t pt-[clamp(14px,1.4vw,26px)]">
            <div>
              <dt className="t-micro">{SOGLASIE.revisedLabel}</dt>
              <dd className="t-mono">{SOGLASIE.revised}</dd>
            </div>
            {SOGLASIE.legal ? (
              <div>
                <dt className="t-micro">{SOGLASIE.legalLabel}</dt>
                <dd className="t-mono">{SOGLASIE.legal}</dd>
              </div>
            ) : null}
          </dl>
        </Sheet>

      </Section>

      {/* ЛИСТ КОНЧАЕТСЯ ВЫХОДНЫМИ ДАННЫМИ, КАК ГЛАВНАЯ И КАК «РАСЧЁТ».
          Стоял здесь свой закрывающий ряд, разделы волосяной в одну строку,
          и довод был тот же, что у «Контактов»: не оставить лист тупиком.
          Довод верен, а ряд оказался мал. На бумаге во весь формат одна
          строка машинного голоса под волосяной это не закрытие листа, а
          обрыв с подписью, и полторы тысячи точек пустого грунта под ней
          читались недоделкой.

          §08 закрывает лист тем же, чем закрывает всякий печатный лист:
          заявлением, двумя плашками заказа, справочником и тиснением.
          Разделы в нём те же самые, только колонкой и вместе с адресом,
          часами и каналами, и «Согласие» в колонке разделов тоже на месте:
          ссылка на себя в подвале это норма листа, ровно как «Заказ» в
          подвале самого «Расчёта».

          ОТБИВКУ СНИЗУ СЧИТАЕТ ТЕПЕРЬ §08, а не эта страница: тиснение
          несёт свой запас под липкую полосу. */}
      <VykhodnyeDannye />
    </main>
  );
}
