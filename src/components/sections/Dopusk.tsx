'use client';

import { Fragment } from 'react';
import { PrintReveal } from '@/components/type/PrintReveal';
import { RegisterPatch } from '@/components/print/RegisterPatch';
import { Registry } from '@/components/ui/Registry';
import { Section, Sheet, Grid } from '@/components/layout/Sheet';
import { useMediaQuery } from '@/lib/hooks';
import { DOPUSK, SECTIONS } from '@/content/site';

/**
 * §02 · ДОПУСК
 *
 * Полоса построена на трёх ходах и ни на одном лишнем.
 *
 *   1. ЗАЯВЛЕНИЕ во весь формат. Не заголовок в колонке на пять долей плюс
 *      три абзаца рядом, а один блок дисплейного набора от реза до реза.
 *      На переломе фразы стоит приводочный шильд: чёрный крест и рубиновая
 *      точка. Фраза обещает, что фирма делает бизнес заметнее, а шильд
 *      держит её на листе прибором, а не картинкой.
 *   2. КОРПУС у правого края, один абзац, и АДРЕСАТ у левого, второй. Справа
 *      сказано, что цех делает, слева для кого он это делает. Ссылок на
 *      полосе нет ни одной.
 *   3. РЕЕСТР одной строкой во весь формат под единственной линейкой.
 *
 * Что убрано и почему: столбец из четырёх строк с волосяной линией под
 * каждой (читался таблицей характеристик), сносочная линейка в 38 %
 * колонки (линия, которая ничего не отделяла), два абзаца корпуса из трёх
 * (то же самое, сказанное трижды). Линейки на полосе теперь ровно две:
 * шмуцтитул сверху и реестр снизу.
 *
 * ВЕСЬ ТЕКСТ ПОЛОСЫ ПЕРЕПИСАН 22.09.2026, И ПЕРЕПИСАН НЕ НАМИ. Заказчик снял
 * здесь всё до последнего слова и отдал взамен первый экран прежнего сайта
 * агентства: строку «Рекламное производство, которое делает бизнес заметнее»
 * и две карточки под ней. Заявление, корпус и левая половина взяты оттуда
 * слово в слово; вся разметка ниже осталась прежней, потому что старая копия
 * укладывалась ровно в эти же три слота. См. `DOPUSK` в content/site.ts.
 *
 * ЛЕВОЕ ПОЛЕ ЗАНЯТО ПОСЛЕДНИМ, И ЗАНЯТО ТРЕТЬИМ ПО СЧЁТУ ЖИЛЬЦОМ. В колонках
 * 1–4 стояла сперва заметка о механике самого листа (то есть о сайте, а не о
 * деле фирмы), потом цена. Теперь там вторая карточка прежнего сайта: для
 * кого этот цех работает. Голосов на полосе по-прежнему два, линеек
 * по-прежнему две.
 *
 * ЛЕВЫЙ БЛОК СТУПЕНЬЮ НИЖЕ, НО НЕ КЕГЛЕМ. Кегль у обеих половин один
 * (`t-lead`), и от этого их строки стоят на общих базовых линиях: полоса
 * читается разворотом, а не двумя врезками рядом. Вторую роль левому даёт
 * одна только краска, `fg-56` против `fg-70`. Меньший кегль пробовался и
 * отставлен: в четыре доли он читается сноской, а сноску на этой полосе уже
 * один раз сняли.
 *
 * Обе колонки стоят в первом ряду сетки (`md:row-start-1`), поэтому порядок
 * в разметке свободен, и на телефоне адресат встаёт ПОД корпусом, как он и
 * читается.
 */
export function Dopusk() {
  const S = SECTIONS[1];
  const isMobile = useMediaQuery('(width < 768px)');

  const { desktop, mobile, markAfter } = DOPUSK.statement;
  const lines = isMobile ? mobile : desktop;
  const mark = isMobile ? markAfter.mobile : markAfter.desktop;

  return (
    <Section id={S.id} ground="paper" gain={0.8} className="py-[var(--section-pad)]">
      <Sheet>
        {/* ── ЗАЯВЛЕНИЕ ────────────────────────────────────────────────────
            Ракель проходит по строке за строкой: сначала предмет, следом
            то, что он делает. Стагер 55 мс это ритм листа, выходящего из
            машины, а не каскад «эффектов». */}
        <h2 className="t-statement">
          {lines.map((line, i) => (
            <PrintReveal as="span" key={line} className="block" delay={i * 0.055}>
              {line}
              {i === mark && (
                <Fragment>
                  {/* Неразрывный пробел: шильд это часть фразы, он не имеет
                      права перескочить на следующую строку. */}
                  {' '}
                  <RegisterPatch />
                </Fragment>
              )}
              {/* Строки это блоки, но доступное имя заголовка склеивается из
                  текстовых узлов: без этого пробела скринридер прочтёт
                  «производство,которое». */}
              {' '}
            </PrintReveal>
          ))}
        </h2>

        {/* ── КОРПУС И АДРЕСАТ ────────────────────────────────────────────
            Две половины одного разворота: корпус в колонках 7–12, адресат в
            1–4, между ними две доли воздуха. Расстояние от заявления до них
            здесь такой же размер, как кегль. */}
        <Grid className="mt-[clamp(56px,6.4vw,140px)] gap-y-[clamp(42px,8vw,56px)]">
          <div className="col-span-4 md:col-span-6 md:col-start-7">
            <PrintReveal as="p" delay={0.28} className="t-lead fg-70 measure">
              {DOPUSK.body}
            </PrintReveal>
          </div>

          {/* ── АДРЕСАТ ─────────────────────────────────────────────────────
              ЗДЕСЬ СТОЯЛА ЦЕНА, а до неё ссылка «Сколько это стоит →» на
              калькулятор `/raschet`, ради которой шесть долей слева и были
              открыты. Калькулятор снят с сайта целиком, следом снялась
              ссылка, а 22.09.2026 заказчик снял и сам абзац.

              ВЗАМЕН СТОИТ ТО, ЧЕГО ПОЛОСА НЕ ГОВОРИЛА НИ РАЗУ: для кого этот
              цех работает. Перечень отраслей проверяем (кафе, клиники,
              школы, магазины) и ничего не обещает сверх факта, а заодно
              ловит того самого читателя, который ищет себя в списке раньше,
              чем начинает читать. Полоса так и стоит без единой ссылки: зов
              в §03 сняли ещё раньше, тот и так следующий на прокрутке. */}
          <div className="col-span-4 md:col-start-1 md:row-start-1">
            <PrintReveal as="p" delay={0.28} className="t-lead fg-56">
              {DOPUSK.audience}
            </PrintReveal>
          </div>
        </Grid>

        {/* ── РЕЕСТР ──────────────────────────────────────────────────────── */}
        <div className="mt-[clamp(60px,7vw,150px)]">
          <Registry />
        </div>
      </Sheet>
    </Section>
  );
}
