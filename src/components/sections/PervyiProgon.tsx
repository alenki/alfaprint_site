import { Masthead } from '@/components/type/Masthead';
import { ClientMarks } from '@/components/print/ClientMarks';
import { StarTarget } from '@/components/print/StarTarget';
import { StampTirazh } from '@/components/print/StampTirazh';
import { Section, Sheet } from '@/components/layout/Sheet';
import { HERO, SECTIONS } from '@/content/site';

/**
 * §01 · ПЕРВЫЙ ПРОГОН
 *
 * На листе три предмета: имя фирмы во весь формат, хвост в конце имени
 * (мишень с печатью), и лента чужих знаков нижней кромкой.
 * Указатель прокрутки стоит у правого реза пятым и не в счёт: он показывает
 * направление, а не говорит.
 *
 * ЛЕНТА ТЕПЕРЬ ВНУТРИ ПОЛОСЫ. Прежде она стояла отдельным узлом СРАЗУ ПОД
 * первым экраном и на том же грунте: читатель дочитывал имя, и лист кончался
 * пустотой ровно там, где начиналось доказательство. Обещание и доказательство
 * оказывались на разных экранах, и второе приходилось искать прокруткой.
 * Теперь оба стоят на одном оттиске: имя висит на ленте, лента режется краем
 * экрана, и первый прогон читается целиком, не листая.
 *
 * ВОЗДУХ ОТ ЭТОГО НЕ ПРИБАВИЛСЯ И НЕ УБЫЛ. Он по-прежнему остаток: что не
 * заняли набор и лента, то и стоит над именем. Лента отнимает у
 * полосы свою высоту точно так же, как хвост отнимает у кегля свою долю меры,
 * и никакого числа для нового просвета не заведено.
 *
 * ЧТО ЗДЕСЬ ПЕРЕСТАВЛЕНО. Прежде лист открывался фразой «Печатаем всё, что
 * держит краску», выключенной во все двенадцать колонок, а имя фирмы стояло
 * в шапке в четырнадцать пикселей. Читатель узнавал, ЧТО ему сделают,
 * раньше, чем узнавал, КТО. Теперь во весь формат набрано имя, а обещание
 * сначала ушло в оговорку над ним, а потом было снято заказчиком совсем.
 *
 * НАБОР АФИШЕЙ, А НЕ ВЫКЛЮЧКОЙ. Обе строки идут одним кеглем, и кегль
 * подобран так, что до правого реза достаёт самая длинная из них. Короткие
 * остаются короткими, и это не рваный край, а РЕШЕНИЕ: выключать здесь было
 * бы браком, потому что пятибуквенное слово, растянутое на всю полосу,
 * теряет собственный рисунок, а имя фирмы это рисунок и есть. Прежний способ
 * никуда не делся, он живёт в `justifyLines` и ждёт полосы, где заголовок
 * снова станет фразой.
 *
 * ДО РЕЗА ДОСТАЁТ НЕ СЛОВО, А СЛОВО С ПРЕДМЕТОМ. В конце последней строки
 * стоит хвост, и в меру он входит наравне с набором (`--hero-tail`, `tailEm`
 * в `fitBlock`). Отсюда и весь воздух этой полосы: хвост отнимает у кегля
 * свою долю меры, набор садится мельче, и высвободившаяся высота становится
 * пустотой НАД именем. Пустота здесь не назначена числом, а стоит ровно
 * столько, сколько стоит предмет: назначить её значило бы завести вторую
 * правду о композиции. Остаток лежит сверху, а не снизу, потому что имя
 * висит на нижнем поле, как афиша на подрамнике.
 *
 * ЕДИНСТВЕННЫЙ ПРИЁМ. Вторая половина имени набрана второй краской. Это не
 * выделение цветом: «Альфа» лежит на форме K, «Принт» на форме R, и при
 * разгоне прокрутки имя расходится по краскам ровно так, как расходится
 * плохо приведённая машина. Тезис сайта сказан на первом экране самим именем
 * фирмы, а не примером под ним. Рубин на полосе тратится этим один раз и
 * больше нигде: ни мишень, ни печать, ни указатель его не несут.
 *
 * МИШЕНЬ ЭТО ПРИБОР, А НЕ КАРТИНКА. Звёздчатую мишень печатают на
 * контрольном поле каждого оттиска, и печатник смотрит на её середину:
 * тридцать шесть клиньев обязаны сойтись в точку. Прежде она стояла размытым
 * полем ПОД набором в треть экрана; теперь она стоит В СТРОКЕ, ростом с очко,
 * и прибор от этого впервые читается прибором. Крутится она потому, что лежит
 * на цилиндре, и быстрее тогда, когда идёт лист. См. `StarTarget`.
 *
 * ДЕЙСТВИЕ НА ПОЛОСЕ ЕСТЬ. Прежняя редакция его отсюда убирала («первый
 * экран заявляет, а не просит»); решение отменено заказчиком, и печать в
 * конце имени ведёт в §08. См. поправку v1.5 в `docs/design-spec.md`.
 */
export function PervyiProgon() {
  const S = SECTIONS[0];

  return (
    <Section
      id={S.id}
      ground="paper"
      gain={0.6}
      /* Высота полосы объявлена в CSS, на классе .hero, и объявлена ЗАДАННОЙ,
         а не минимальной: см. там же, почему min-height ломает подбор кегля.
         Шапка листа при этом липкая и стоит В ПОТОКЕ, поэтому из высоты
         экрана вычтена её собственная: иначе набор ушёл бы под сгиб. */
      className="hero flex flex-col"
    >
      <Sheet className="hero-sheet flex flex-1 flex-col">
        {/* ── ПОЛОСА ШАПКИ ─────────────────────────────────────────────────
            Вся высота листа. Её `Masthead` и меряет, прежде чем выбрать
            кегль: полоса обязана быть известна раньше набора. Оговорки над
            ней больше нет, заказчик снял её с листа целиком. */}
        <div className="hero-stage">
          <div className="hero-air-t" aria-hidden />

          <Masthead
            breaks={HERO.breaks}
            label={HERO.label}
            plateR={HERO.plateR}
            mark={HERO.mark}
          >
            {/* ХВОСТ. Два предмета, но одно место: мишень и печать приходят
                сюда ребёнком блока, который набирает имя, и отмеряют своё
                место от конца последней строки (`--hero-last-x`), не меряя
                ничего сами. На узкой мере хвост уходит под набор целиком, и
                решает это замер, а не медиазапрос: см. `Masthead`. */}
            <div className="hero-tail">
              <StarTarget className="hero-star" />
              <StampTirazh />
            </div>
          </Masthead>

          <div className="hero-air-b" aria-hidden />
        </div>
      </Sheet>

      {/* ── ЛЕНТА ЗНАКОВ ───────────────────────────────────────────────────
          Нижняя кромка первого экрана и единственное, что на нём стоит от
          реза до реза: у полосы набора поля по --edge, у ленты их нет, и
          выходит она ребёнком СЕКЦИИ, а не полосы.

          Своего §NN у неё нет намеренно: она не раздел, а доказательство,
          и стоит ровно там, где имя кончило обещать. */}
      <ClientMarks />

      {/* ── ЗАКЛАДКА У РЕЗА ────────────────────────────────────────────────
          Указатель прокрутки: слово и волосяная направляющая, по которой
          сверху вниз раз в несколько секунд проходит ракель. Прежде он стоял
          в подвале полосы; теперь это вклеенная в правый рез закладка, какой
          в книге отбивают начатую тетрадь, и набор в ней идёт сверху вниз.

          Стоит она ребёнком СЕКЦИИ, а не полосы набора: у полосы есть поля
          по `--edge`, а закладка обязана доходить ровно до реза, и `right: 0`
          на секции это буквально он.

          Нажимать здесь нечего: показано только направление, поэтому узел
          скрыт от скринридера и не берёт указатель. Показ по ширине держит
          CSS, а не утилита `hidden md:flex`: правило стоит вне @layer и
          потому перебило бы display от Tailwind, оставив закладку на
          телефоне, где нижнюю кромку занимает `MobileCta`. */}
      <div className="hero-tab" aria-hidden>
        <p className="hero-line hero-tab-word t-micro" style={{ ['--d' as string]: '1.26s' }}>
          {HERO.scroll}
        </p>
        <span className="hero-scroll-rail" />
      </div>
    </Section>
  );
}
