import { H1Justified } from '@/components/type/H1Justified';
import { Section, Sheet } from '@/components/layout/Sheet';
import { HERO, SECTIONS } from '@/content/site';

/**
 * §01 · ПЕРВЫЙ ПРОГОН
 *
 * На листе три предмета: заголовок, оговорка с действием под ней, указатель
 * прокрутки. В прежней редакции их было четырнадцать: шмуцтитул, кикер,
 * живая строка смены, спецификация листа на четыре строки, полоса
 * цветоделения из трёх панелей с шестью подписями и двенадцать направляющих
 * спуска. Всё это говорило о печати вместо того, чтобы БЫТЬ печатью,
 * и повторяло факты, которые ниже по сайту стоят на своих местах.
 *
 * Метка издания снята следующей: город и год стоят в §08, а над заголовком
 * в 150 px любая служебная строка читается как подпись к нему. Лист
 * открывается набором.
 *
 * ЕДИНСТВЕННЫЙ ПРИЁМ. Последнее слово заголовка набрано второй краской,
 * и это слово «краску». Вторую форму покупают тогда, когда есть ровно
 * одна вещь, которую чёрным не сказать; здесь такая вещь это сама краска.
 * Точка после слова осталась на форме K: знак принадлежит предложению,
 * а не выделению, поэтому при разгоне прокрутки рубиновое слово сползает,
 * а его собственная точка стоит, и между ними открывается щель.
 *
 * Из этого следует главное свойство полосы: приём работает на СТОЯЩЕЙ
 * странице и на второй загрузке. Приладка при открытии не заставка,
 * а первый и самый крупный такт того же механизма, который дальше живёт
 * всё время, пока лист листают.
 *
 * Формат прежний и не тронут: заголовок выключен во все двенадцать колонок
 * подбором ширины литеры, от левого реза до правого. Это лучшее, что было
 * на прежней полосе, и уменьшать его ради картинки не за чем: две строки
 * антиквы в 150 px на всю ширину листа и есть изображение первого экрана.
 *
 * Воздух делится 0,382 : 0,618, над заголовком меньше, под ним больше.
 * Поэтому на высоком окне оговорка не всплывает к заголовку и не проваливается
 * в подвал, а держится там же, где держится на обычном.
 *
 * ПОДВАЛ ЛИСТА. Слева столбик: оговорка и под ней единственное действие
 * страницы; справа у реза стоит указатель прокрутки. Прежде оговорка и действие
 * стояли по разным резам на одной базовой линии, и глаз проходил лист
 * поперёк, чтобы дочитать одну мысль. Теперь мысль и её кнопка стоят
 * в одной колонке, одна под другой, а правый рез отдан направлению.
 *
 * ЧЕМ ДЕЙСТВИЕ ОТЛИЧАЕТСЯ ОТ ОГОВОРКИ: ЛИНЕЙКОЙ, А НЕ КЕГЛЕМ. Прежде
 * действие набиралось ведущим кеглем (--text-lead, им же набран корпус §02)
 * начертанием 500, а линейка под ним стояла в scaleX(0) до наведения. На
 * стоящей странице это давало не ссылку, а полужирную строку со стрелкой:
 * опознать её было нечем, а сама стрелка висела за концом строки.
 *
 * Теперь линейка стоит ВСЕГДА, волосяная --rule под словами, а по ней
 * при наведении слева направо проходит ракель полной краской. Это тот же
 * предмет, что и направляющая указателя у правого реза: подвал полосы
 * держат две одинаковые линейки, и разница между оговоркой и действием
 * сведена к одной величине вместо четырёх.
 */
export function PervyiProgon() {
  const S = SECTIONS[0];

  return (
    <Section
      id={S.id}
      ground="paper"
      gain={0.6}
      /* Шапка липкая и стоит В ПОТОКЕ, поэтому 100svh дал бы полосу ровно
         на её высоту длиннее экрана, и подвал ушёл бы под сгиб. */
      className="flex min-h-[calc(100svh-var(--topbar-h))] flex-col"
    >
      <Sheet className="hero-sheet flex flex-1 flex-col">
        <div className="hero-air-t" aria-hidden />

        {/* ── ЗАГОЛОВОК ─────────────────────────────────────────────────────
            Форма K во весь формат; последнее слово это форма R. */}
        <div className="hero-strike" style={{ ['--d' as string]: '0.16s' }}>
          <H1Justified
            linesDesktop={HERO.linesDesktop}
            linesMobile={HERO.linesMobile}
            plateR={HERO.plateR}
            className="w-full"
          />
        </div>

        <div className="hero-air-b" aria-hidden />

        {/* ── ПОДВАЛ ────────────────────────────────────────────────────────
            Столбик у левого реза, указатель у правого. Оговорка снята
            с рубина и набрана чёрным: вторая краска на первом экране
            тратится ровно один раз, и уже потрачена. */}
        <div className="flex flex-col gap-8 md:flex-row md:items-end md:justify-between md:gap-[clamp(32px,5vw,120px)]">
          {/* Оговорка это придаточное к заголовку, а не второе заявление
              полосы. Отличает действие не кегль и не насыщенность,
              а линейка: она стоит в покое и потому опознаётся раньше,
              чем строка прочитана. */}
          <div className="hero-act">
            <p
              className="hero-line hero-sub fg-70 measure"
              style={{ ['--d' as string]: '1.02s' }}
            >
              {HERO.sub}
            </p>

            {/* Знака продолжения нет: направление на этом листе набирают,
                а не рисуют, см. указатель «вниз» у правого реза. Стрелка
                вправо над якорем, стоящим НИЖЕ по листу, вдобавок врала
                о направлении. Ссылку опознают по линейке под ней. */}
            <a
              href="#v-pechat"
              className="hero-line hero-cta"
              style={{ ['--d' as string]: '1.14s' }}
            >
              {HERO.link}
            </a>
          </div>

          {/* ── УКАЗАТЕЛЬ ПРОКРУТКИ ────────────────────────────────────────
              Слово у реза и волосяная направляющая справа от него, по которой
              сверху вниз раз в несколько секунд проходит ракель. Это не
              иконка и не кнопка: единственное действие полосы уже стоит
              слева, а здесь показано только направление, поэтому узел
              скрыт от скринридера и не берёт указатель.

              Показ по ширине держит CSS, а не утилита `hidden md:flex`:
              правило .hero-scroll стоит вне @layer и потому перебило бы
              display от Tailwind, оставив указатель на телефоне. */}
          <p
            className="hero-line hero-scroll t-micro fg-56"
            style={{ ['--d' as string]: '1.26s' }}
            aria-hidden
          >
            {HERO.scroll}
            <span className="hero-scroll-rail" />
          </p>
        </div>
      </Sheet>
    </Section>
  );
}
