import type { CSSProperties } from 'react';
import {
  LOGOTYPE_CAP,
  LOGOTYPE_R_SCALE,
  LOGOTYPE_R_SHIFT,
  MARK_R,
  setLogotype,
} from '@/components/chrome/Mark';

/**
 * СТРОКА, НАПЕЧАТАННАЯ ЛОГОТИПОМ, А НЕ НАБРАННАЯ ГАРНИТУРОЙ.
 *
 * Формы приходят из `Mark`: четыре буквы обведены с оригинала в 1599 px, пять
 * построены в той же системе по трём снятым с него величинам. Междубуквие
 * тоже оттуда, одним законом на всё слово. Здесь не решается ничего, кроме
 * того, каким РОСТОМ строка встаёт на полосу и что в ней печатает вторая
 * краска.
 *
 * РЕГИСТР ЗАДАЁТ ПЕЧАТЬ, А НЕ СОДЕРЖИМОЕ. В `site.ts` имя лежит как пишется,
 * «Альфа Принт», и тем же уходит в `aria-label`; логотип нарисован
 * прописными, других у него нет вовсе, и прописные тут не решение вёрстки, а
 * единственная имеющаяся форма буквы. Прежде тем же занимался
 * `text-transform`, пока строку набирала гарнитура.
 *
 * ЗАЧЕМ ЛОГОТИПУ КЕГЕЛЬ. У рисунка его не бывает, но полоса §01 меряет всё в
 * долях кегля: отбивку хвоста, поле под маску, интерлиньяж. Чтобы ни одно из
 * этих чисел не пришлось пересчитывать, слову назначено то же отношение
 * прописной к кеглю, что было у подставной гарнитуры, 0.658 (`--logo-cap`).
 * Кегль после этого остаётся ровно тем же кеглем, каким был, и хвост встаёт
 * на прежнее место сам.
 */

/** Слово ставится ровно так же, как меряется. Второго места для этого нет. */
const set = (word: string, track = 0) => setLogotype(word.toUpperCase(), track);

/**
 * ДВЕ СТРОКИ ИМЕНИ ВЫКЛЮЧАЮТСЯ В ОДНУ МЕРУ, И ПЛАТЯТ ЗА ЭТО ОБЕ СРАЗУ.
 *
 * «Альфа» и «Принт» разной длины: 468 единиц против 428, то есть короткая
 * недобирает почти десятую. Прежде эта десятая оставалась рваным краем, и
 * имя стояло на полосе лесенкой. Заказчик попросил блок, и блок этот
 * складывается ДВУМЯ рычагами сразу, а не одним.
 *
 *   ── РАЗРЯДКА растит строку, не трогая рисунка буквы. Одна она развела бы
 *      «Принт» на 13 единиц просвета при 6,5 у «Альфы», то есть вдвое: две
 *      строки одного имени читались бы набранными порознь.
 *   ── РОСТ растит букву, не трогая набора. Один он поднял бы «Принт» на
 *      девять сотых над «Альфой», и слова перестали бы быть одного кегля.
 *
 * Поэтому долг делится между ними пополам, и делится в ДОЛЯХ, а не в
 * единицах: рост берёт корень из недобора, разрядка добирает остаток. На
 * нынешнем имени это 4,6 % роста и просвет 11,4 вместо 6,5. Ни одно из двух
 * отступлений в одиночку не заметно, а вместе они дают ровный правый край.
 *
 * ВЫЧИСЛЯЕТСЯ ЭТО ПО БЛОКУ ЦЕЛИКОМ, а не по строке: пока не известна самая
 * длинная строка, ни разрядки, ни роста у остальных нет. Оттого и замер
 * шапки спрашивает ширину у блока, а не у слова (см. `BlockBox.measure`).
 */
const BLOCK_SPLIT = 0.5;

export type LogotypeSetting = {
  /** Разрядка строки: прибавка к каждому просвету, в единицах логотипа. */
  track: number;
  /** Рост строки долей прописной. Единица это прописная блока. */
  scale: number;
};

export type LogotypeBlock = {
  /** Печатная ширина ЛЮБОЙ строки блока: после выключки они равны. */
  width: number;
  lines: LogotypeSetting[];
};

/** Блок считается по строкам, а строки на полосе не меняются. */
const BLOCKS = new Map<string, LogotypeBlock>();

export function logotypeBlock(lines: readonly string[]): LogotypeBlock {
  const key = lines.join('\n');
  const known = BLOCKS.get(key);
  if (known) return known;

  const raw = lines.map((line) => set(line).width);
  const width = raw.length ? Math.max(...raw) : 0;

  const block: LogotypeBlock = {
    width,
    lines: raw.map((w, i) => {
      const gaps = lines[i].length - 1;
      const debt = w > 0 ? width / w : 1;
      /* Строку в одну букву разряжать негде, и весь недобор платит рост. */
      const scale = gaps > 0 ? debt ** BLOCK_SPLIT : debt;
      return { scale, track: gaps > 0 ? (w * (debt / scale - 1)) / gaps : 0 };
    }),
  };

  BLOCKS.set(key, block);
  return block;
}

export function LogotypeLine({
  word,
  brush = false,
  track = 0,
  scale = 1,
  className,
}: {
  word: string;
  /**
   * Рубиновый мазок на первой «А». В логотипе он стоит именно там и нигде
   * больше, поэтому и здесь это не украшение строки, а её часть: `MARK_R`
   * приходит тем же путём и тем же масштабом, что и на вылете §08.
   */
  brush?: boolean;
  /** Разрядка и рост приходят от блока, не решаются строкой. */
  track?: number;
  scale?: number;
  className?: string;
}) {
  const { glyphs, width } = set(word, track);

  return (
    <svg
      viewBox={`0 0 ${width.toFixed(3)} ${LOGOTYPE_CAP}`}
      className={className}
      /* Рост уходит в CSS долей, а не в viewBox: высоту строке отмеряет одно
         правило, `--logo-cap` на кегле, и вторая правда о ней завелась бы
         ровно в тот момент, когда рисунок начал бы считать её сам. */
      style={scale === 1 ? undefined : ({ ['--logo-rise']: `${scale}` } as CSSProperties)}
      fill="none"
      aria-hidden
    >
      {/* Форма K берёт краску от строки: `currentColor` это то, чем
          `.plate-word-r` красит «ПРИНТ» во вторую краску целиком. */}
      <g fill="currentColor">
        {glyphs.map((g, i) => (
          <path key={i} d={g.d} transform={g.transform} />
        ))}
      </g>

      {brush ? (
        <g
          transform={`translate(0 ${LOGOTYPE_R_SHIFT.toFixed(3)}) scale(${LOGOTYPE_R_SCALE.toFixed(5)})`}
        >
          <path d={MARK_R} fill="var(--color-rubine)" />
        </g>
      ) : null}
    </svg>
  );
}
