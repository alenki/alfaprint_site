'use client';

import { useCallback, useEffect, useRef, useState, type CSSProperties, type ReactNode } from 'react';
import { LOGOTYPE_CAP } from '@/components/chrome/Mark';
import { LogotypeLine, logotypeBlock } from '@/components/type/Logotype';
import { fitBlock, type BlockFit } from '@/lib/justify';
import { cn } from '@/lib/cn';

/**
 * Интерлиньяж афиши. Считается он по-прежнему в долях кегля, а прописная
 * занимает в кегле 0.658 (`--logo-cap`), поэтому на 0,84 между полосами
 * краски остаётся 0,18 кегля, а на 0,74 всего 0,08: тесно ровно настолько,
 * насколько тесно ставят строки на афише. Ниже 0,74 полосы краски начинают
 * задевать друг друга, и там подбор останавливается.
 */
const LEADING_MAX = 0.84;
const LEADING_MIN = 0.74;

/**
 * Самый короткий хвост, на котором предмет ещё стоит предметом.
 *
 * Считан от печати, а не назначен: две строки машинного набора держит круг
 * от ста четырёх пикселей (одиннадцать пунктов Martian Mono с трекингом
 * 0,13em, восемь знаков в строке). Печать это 0,7 кегля (`--tail-round`),
 * значит кегль от 149 px; хвост при этом занимает 1,62 кегля, значит 241 px.
 * Уже этого он уходит под набор целиком, где размеры у него свои и в кегле не
 * считаются.
 */
const TAIL_MIN = 241;

/** В строке или под набором. Третьего положения у хвоста нет. */
type TailMode = 'inline' | 'under';

/**
 * ШАПКА ЛИСТА: ИМЯ ФИРМЫ РОСТОМ ВО ВЕСЬ ПЕРВЫЙ ЭКРАН.
 *
 * ПЕЧАТАЕТСЯ ЛОГОТИПОМ, А НЕ НАБИРАЕТСЯ. Строки приходят сюда формами из
 * `Logotype`: обведёнными с оригинала там, где они в нём есть, и построенными
 * в его же системе там, где их нет. Гарнитуры у шапки поэтому больше нет
 * никакой, и подменного рисунка на загрузке тоже: ждать нечего.
 *
 * СТРОКИ СТОЯТ ОДНИМ БЛОКОМ, А НЕ ЛЕСЕНКОЙ. Кегль у них один, а разную
 * длину слов выбирают разрядка и рост, поровну на оба (`logotypeBlock`).
 * Правый край от этого ровный: печатная ширина у всех строк одна, и до меры
 * достают они вместе. Прежде короткая строка оставалась короткой, и имя
 * стояло на листе рваным столбиком.
 *
 * ДО РЕЗА ДОСТАЁТ НЕ СЛОВО, А СЛОВО С ПРЕДМЕТОМ. В конце последней строки
 * стоит хвост, мишень с печатью, и он входит в меру наравне с набором
 * (`tailEm` в `fitBlock`). Отсюда и воздух полосы: хвост отнимает у кегля
 * свою долю меры, набор садится мельче, и высвободившаяся высота становится
 * пустотой НАД набором. Ни одного числа для этой пустоты не заведено.
 *
 * ЧЕТЫРЕ ВЕЛИЧИНЫ НАРУЖУ, на самом блоке: `--hero-size` это найденный кегль
 * в пикселях, `--hero-lh` найденный интерлиньяж, `--hero-last-x` то место,
 * где кончилась последняя строка, `--hero-lines` число строк выигравшего
 * переноса. Дети отмеряют место от них и потому стоят верно при любом кегле
 * и на любом окне, не меряя ничего сами.
 *
 * КЕГЛЬ У РИСУНКА УСЛОВНЫЙ, И В ЭТОМ ВЕСЬ ФОКУС. Прописная логотипа занимает
 * в нём ту же долю, что занимала у подставной гарнитуры, 0.658. Оттого ни
 * одна доля кегля на полосе не поменялась при переходе с набора на формы:
 * отбивка хвоста, поле под маску, радиус мишени и печати остались теми же
 * числами, что были подобраны на глаз ещё при гарнитуре.
 *
 * ВЫСОТУ БЛОКУ ЗАДАЁТ ХОЗЯИН, А НЕ СОДЕРЖИМОЕ. Родитель обязан быть
 * контейнером с высотой извне (`flex: 1` при `min-height: 0`), и его
 * `clientHeight` это вся полоса, отведённая шапке. Иначе подбор кегля
 * замкнулся бы сам на себя: кегль задаёт высоту, высота задаёт кегль.
 *
 * До первого замера блок стоит на макетном кегле из CSS и на первом из
 * авторских переносов. Это уже верный рисунок, просто не доведённый до реза.
 */
export function Masthead({
  breaks,
  label,
  plateR,
  mark,
  className,
  children,
}: {
  /**
   * Авторские переносы, от предпочтительного к запасным. Который из них
   * встанет на полосу, решает замер, а не медиазапрос: см. `fitBlock`.
   */
  breaks: readonly (readonly string[])[];
  /**
   * Набор голосом, одной строкой и без отбивки. Читается вместо строк:
   * перенос это решение набора, а не слово, и вслух его не произносят.
   */
  label: string;
  /**
   * Строка, которая печатается ВТОРОЙ формой целиком. У имени фирмы это его
   * вторая половина: «Альфа» лежит на форме K, «Принт» на форме R, и имя
   * разложено по двум краскам ровно так, как его разложили бы на плёнки.
   */
  plateR?: string;
  /**
   * Строка, на которой стоит рубиновый мазок логотипа. В оригинале он лежит
   * на первой «А» слова «Альфа», и здесь лежит там же: это часть знака, а не
   * выделение строки.
   */
  mark?: string;
  className?: string;
  children?: ReactNode;
}) {
  const hostRef = useRef<HTMLDivElement>(null);
  const titleRef = useRef<HTMLHeadingElement>(null);
  const [fit, setFit] = useState<(BlockFit & { target: number; tail: TailMode }) | null>(null);
  const lines = fit ? fit.lines : [...breaks[0]];

  /**
   * ВЫКЛЮЧКА ИМЕНИ В БЛОК. Строки разной длины дотягиваются до одной меры
   * разрядкой и ростом сразу, поровну на оба; закон и числа разобраны у
   * `logotypeBlock`. Здесь только берётся готовое: подбор кегля меряет блок
   * тем же вызовом, а строки печатают то, что он им отвесил.
   */
  const block = logotypeBlock(lines);

  const run = useCallback(() => {
    const host = hostRef.current;
    const title = titleRef.current;
    if (!host || !title) return;

    const box = host.getBoundingClientRect().width;
    if (box < 40) return;

    const stage = host.parentElement?.clientHeight ?? 0;

    /**
     * ЧТО СТОИТ В ПОТОКЕ КРОМЕ НАБОРА, то и отнимается от полосы. Хвост под
     * набором это часть блока и часть его высоты; хвост в строке вынут из
     * потока и высоты не стоит ничего, он платит МЕРОЙ. Считаем по вёрстке,
     * а не по списку: блок не знает, кого ему передали детьми, и знать не
     * должен.
     */
    const inFlow = () => {
      let sum = 0;
      for (const el of Array.from(host.children)) {
        if (el === title || !(el instanceof HTMLElement)) continue;
        const c = getComputedStyle(el);
        if (c.position !== 'static') continue;
        sum += el.offsetHeight + (parseFloat(c.marginTop) || 0) + (parseFloat(c.marginBottom) || 0);
      }
      return sum;
    };

    // Поле под маску, длина хвоста и доля прописной в кегле объявлены в CSS,
    // на самом блоке: считать их здесь числами значит завести вторую правду
    // об одной величине.
    const hostStyle = getComputedStyle(host);
    const pad = parseFloat(hostStyle.getPropertyValue('--hero-pad')) || 0;
    const tail = parseFloat(hostStyle.getPropertyValue('--hero-tail')) || 0;
    const capEm = parseFloat(hostStyle.getPropertyValue('--logo-cap')) || 1;

    /* МЕРА У ИМЕНИ СВОЯ, и объявлена она там же, долей полосы. Набор достаёт
       до неё точно так же, как достигал прежде до реза; короче формата она
       затем, что имя во весь лист заглушало всё, что на листе сказано
       словами. Остаток справа от этого поле, а не рваный край, и число для
       него заведено одно, в CSS. */
    const target = box * (parseFloat(hostStyle.getPropertyValue('--hero-measure')) || 1);

    /* СТРОКА НЕ МЕРЯЕТСЯ, А СЧИТАЕТСЯ. Места букв в слове известны точно, и
       ширина слова это арифметика по ним; в пиксели она переводится долей
       прописной в кегле. Пробника в документе тут нет ни одного, ждать
       гарнитуру не нужно, и первый же проход попадает в меру.

       СЧИТАЕТСЯ ОНА ПО БЛОКУ, А НЕ ПО СЛОВУ, и слово сюда вообще не идёт.
       Строки имени выключены в одну меру разрядкой и ростом (см.
       `logotypeBlock`), и печатная ширина у них после этого ОДНА НА ВСЕХ.
       Спрашивать её у отдельного слова значило бы спрашивать до выключки. */
    const measure = (_line: string, basePx: number, lines: readonly string[]) =>
      (logotypeBlock(lines).width / LOGOTYPE_CAP) * capEm * basePx;

    /* Кроме кегля, от стиля заголовка не нужно ничего: рисунок у строк свой,
       и ни гарнитура, ни трекинг, ни регистр на ширину больше не влияют. */
    const style = {
      fontFamily: '',
      fontWeight: '',
      fontSize: getComputedStyle(title).fontSize,
      letterSpacing: '0px',
      textTransform: 'none',
    };

    const fitFor = (extra: number, tailEm: number) =>
      fitBlock(breaks, target, style, {
        maxHeightPx: Math.max(stage - extra, 0),
        leadingMax: LEADING_MAX,
        leadingMin: LEADING_MIN,
        padEm: pad,
        tailEm,
        measure,
      });

    /* Хвост стоит в строке только пока он в строке помещается. Мерой решает
       не окно, а сам найденный кегль: на нём хвост занимает столько-то
       пикселей, и если их меньше TAIL_MIN, предмет уходит под набор. */
    const inlineOf = (f: BlockFit) => tail * f.sizePx >= TAIL_MIN;

    /**
     * ГДЕ СТОИТ ХВОСТ, РЕШАЕТСЯ ВСЕГДА ПО ОДНОЙ И ТОЙ ЖЕ ВЁРСТКЕ. Место хвоста
     * зависит от кегля (в строке он помещается только на крупном), а кегль
     * зависит от места хвоста: в строке хвост отнимает МЕРУ, под набором
     * ВЫСОТУ. Круг разрывается так: сперва блок ставится В СТРОКУ и меряется,
     * и найденный там кегль решает. Держится на нём предмет предметом, значит
     * в строке он и остаётся; не держится, значит уходит под набор, и тогда
     * меряем ещё раз, уже по новой доле потока.
     *
     * РЕШЕНИЕ НЕ СМОТРИТ НА ТО, ГДЕ ХВОСТ СТОИТ СЕЙЧАС, и это главное. Прежде
     * первый замер шёл по текущей вёрстке, а поправочный проход держался на
     * доводе «под набором кегль всегда мельче, значит в строку хвост не
     * вернётся». Довод верен, только пока хвост отнимает у меры немного. Имя
     * стоит прописными, они шире строчных на четверть, и хвост отнимает у
     * меры треть: снятый из неё, он кегль ПОДНИМАЕТ, а не роняет. На 1280
     * пикселях замер по строке давал 143 px и отправлял предмет под набор, а
     * замер по набору возвращал 183 px, при котором предмет снова помещался в
     * строку. Ни одно из двух состояний себя не подтверждало, и вёрстка
     * ПЕРЕКЛАДЫВАЛАСЬ НА КАЖДОМ ЗАМЕРЕ: одно и то же окно давало то 143, то
     * 183, стоило сработать наблюдателю полосы.
     *
     * Оттого замер и начинается с одного и того же положения. Неподвижной
     * точки у полосы может не быть вовсе, а решение обязано быть одно.
     */
    let want: TailMode = 'inline';
    host.dataset.tail = want;
    let res = fitFor(inFlow(), tail);

    if (!inlineOf(res)) {
      want = 'under';
      host.dataset.tail = want;
      res = fitFor(inFlow(), 0);
    }

    /* Тот же результат не возвращается в состояние: замер идёт и на каждом
       изменении полосы, а лишний рендер здесь стоит перерисовки набора
       в двести пикселей. */
    setFit((prev) =>
      prev &&
      prev.target === target &&
      prev.tail === want &&
      prev.lines.length === res.lines.length &&
      prev.lines.every((line, i) => line === res.lines[i]) &&
      Math.abs(prev.sizePx - res.sizePx) < 0.5 &&
      Math.abs(prev.leading - res.leading) < 0.005
        ? prev
        : { ...res, target, tail: want }
    );
  }, [breaks]);

  useEffect(() => {
    /* Ждать больше нечего: ширина строки считается по формам, а не меряется
       гарнитурой, поэтому первый же проход после разметки верен. Прежде тут
       стояла гонка с `document.fonts.ready`, и до её конца на полосе стоял
       кегль, подобранный по чужой ширине. */
    run();

    /* Наблюдаем ПОЛОСУ, а не блок: её размер от кегля не зависит, и петли
       «кегль двигает высоту, высота двигает кегль» здесь быть не может. */
    const stage = hostRef.current?.parentElement;
    if (!stage) return;

    let t: ReturnType<typeof setTimeout>;
    const ro = new ResizeObserver(() => {
      clearTimeout(t);
      t = setTimeout(run, 120);
    });
    ro.observe(stage);

    return () => {
      clearTimeout(t);
      ro.disconnect();
    };
  }, [run]);

  /**
   * КОНЕЦ ПОСЛЕДНЕЙ СТРОКИ. Хвост отмеряет место от него и ни от чего
   * другого, поэтому и стоит верно при любом кегле. Ширина здесь по НАБОРУ:
   * сам хвост в неё не входит, иначе предмет отмерял бы место от себя же.
   */
  const lastX = fit ? (fit.widths[fit.widths.length - 1] ?? 0) : 0;

  return (
    <div
      ref={hostRef}
      className={cn('hero-block', className)}
      data-tail={fit ? fit.tail : undefined}
      style={
        fit
          ? ({
              ['--hero-size' as string]: `${fit.sizePx.toFixed(2)}px`,
              ['--hero-lh' as string]: fit.leading.toFixed(4),
              ['--hero-last-x' as string]: `${lastX.toFixed(2)}px`,
              /* Число строк выигравшего переноса: хвост стоит на ПОСЛЕДНЕЙ
                 базовой линии, а их три или четыре, и вёрстка обязана знать
                 которая, не считая ничего сама. */
              ['--hero-lines' as string]: `${fit.lines.length}`,
            } as CSSProperties)
          : undefined
      }
    >
      <h1 ref={titleRef} aria-label={label} className="t-h1 hero-title hero-strike">
        {lines.map((line, i) => (
          <span
            key={line + i}
            className={cn('hero-line-set', line === plateR && 'plate-word-r')}
          >
            <LogotypeLine
              word={line}
              brush={line === mark}
              track={block.lines[i]?.track}
              scale={block.lines[i]?.scale}
            />
          </span>
        ))}
      </h1>
      {children}
    </div>
  );
}
