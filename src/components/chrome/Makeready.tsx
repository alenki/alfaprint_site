import { RegistrationMark } from '@/components/chrome/Mark';
import { TrimMarks } from '@/components/chrome/TrimMarks';

/**
 * ЛИСТ ПРИЛАДКИ.
 *
 * Первое, что видит читатель, и единственное на сайте, что стоит ПЕРЕД
 * листом, а не на нём. Приладка это то, чем печатник занят до тиража: он
 * гоняет пробные листы и сводит краски, пока приводочные кресты обеих форм не
 * сойдутся в один. Здесь этот лист один, и прогон на нём ровно один.
 *
 * ЗАЧЕМ ОН НУЖЕН. Закон сайта в том, что форма K стоит намертво, а форма R
 * уходит из приводки, и до этой правки читатель встречал закон уже
 * ИСПОЛНЕННЫМ: §01 открывался сведённым именем, а объяснение приходило только
 * в §02, через экран. Лист приладки говорит закон первым и без единого слова:
 * крест напечатан дважды, копии приходят врозь и садятся друг в друга. Через
 * секунду читатель попадает в §01, уже зная, на что смотрит.
 *
 * НА ЛИСТЕ ЧЕТЫРЕ МЕТКИ ПЕЧАТНИКА И НИ ОДНОГО ПЯТОГО ПРЕДМЕТА: обрезные метки
 * по углам, крест посередине, слово у левого реза, отклонение у правого.
 * Полосы загрузки здесь нет намеренно. Отклонение и ЕСТЬ полоса загрузки, а
 * второй показ того же числа завёл бы о нём вторую правду.
 *
 * ТРИ ПРИВОДКИ, И КАЖДАЯ ТОЧНЕЕ ПРЕДЫДУЩЕЙ. Вылет здесь 28 на 16 пикселей,
 * ровно вчетверо против закона; в §01 форма R садится с 20 на 12
 * (`hero-register`); на ходу лист живёт вылетом 7 на 4 (`--miss`). Это самая
 * грубая приводка, которую страница себе позволяет, и дальше она только
 * точнее. Число вылета не выдумано и не подобрано на глаз: оно кратно закону.
 *
 * НИ ОДНОЙ СТРОКИ JS. Узел серверный, ход задан анимацией CSS, отсчёт
 * отклонения идёт счётчиком CSS от той же переменной, которая двигает форму.
 * Это не украшение, а условие: приладка обязана идти ДО гидратации, потому
 * что закрывает она как раз подмену гарнитуры и замер кегля в `Masthead`,
 * а и то, и другое случается раньше, чем React оживёт. Единственный
 * rAF-цикл сайта живёт в `PlateProvider` и к этому листу отношения не имеет,
 * см. первую строку того файла.
 *
 * СНИМАЕТСЯ ОН САМ. Анимация кончается доставкой листа вверх и `forwards`,
 * поэтому снять его нечему и незачем: без JS он уйдёт ровно так же, как с
 * ним. Скрипт в начале `<body>` умеет только одно, пометить сеанс как
 * виденный, и на второй заход лист не печатается вовсе.
 */
export function Makeready() {
  return (
    <div className="makeready" aria-hidden>
      <TrimMarks className="makeready-trim" />

      {/* Один крест, напечатанный двумя красками. Обе копии это один и тот же
          `RegistrationMark`, что стоит в §02 приборной наводкой: приводочный
          крест на сайте нарисован один раз и в одном месте.

          Форма R идёт через multiply, поэтому пересечение красок печатается
          настоящим оверпринтом, а не третьим цветом поверх. */}
      <div className="makeready-cross">
        <RegistrationMark className="makeready-k" hairline />
        <RegistrationMark className="makeready-r" hairline />
      </div>

      <p className="makeready-word t-micro">Приводка</p>

      {/* Показание прибора, и единственное место на сайте, где оно набрано.
          Шкала внизу листа молчит намеренно (см. `ControlStrip`): пульт
          показывает отклонение на приладке и умолкает на тираже. Само число
          печатает CSS, поэтому узел пуст. */}
      <p className="makeready-delta t-micro" />
    </div>
  );
}
