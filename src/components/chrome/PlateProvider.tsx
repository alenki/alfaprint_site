'use client';

import { useEffect } from 'react';
import Lenis from 'lenis';
import { trailAway, trailFrame, trailPointer } from '@/lib/trail';

/**
 * ЕДИНСТВЕННЫЙ rAF-ЦИКЛ НА ВЕСЬ САЙТ.
 *
 * Пишет четыре переменные, и каждую НА ТОТ УЗЕЛ, КОТОРЫЙ ЕЁ ЧИТАЕТ: --miss на
 * формы R и призраков, --progress на звезду подачи и контрольную шкалу, --run-p
 * на дорожки ленты знаков, --reg-x/--reg-y на приводочный шильд. В :root не
 * уходит НИЧЕГО, и больше цикл не делает ничего. Ноль слушателей прокрутки на
 * элементах, ноль React-ререндеров при прокрутке: весь уход приводки живёт в
 * CSS.
 *
 * ПИШЕТ ТУДА, ГДЕ ЧИТАЮТ, И ТОЛЬКО НА ИЗМЕНЕНИЕ. Все четыре объявлены
 * НЕнаследуемыми (@property, inherits: false), и потому запись ложится ровно
 * на тот узел, которому написана. Обратное стоило дорого: наследуемое число в
 * :root это недействительный стиль ВСЕГО документа, полторы тысячи узлов
 * заново выводят значение ради двух десятков, которые его читают. «Разбросаны
 * по листу» не оправдание для :root: разбросаны они по двум десяткам узлов
 * (--miss) и по двум (--progress), и цикл находит их сам.
 *
 * Цена ненаследуемости одна: КАЖДЫЙ читающий узел обязан получить число сам,
 * и новый читатель обязан попасть в MISS_READERS или PROGRESS_READERS ниже.
 * Не попал — встанет в приводке (initial-value: 0), а не сломается.
 * И ни одна строка не уходит в стиль дважды подряд: см. put ниже.
 *
 * И ВЕСЬ КАДР РАЗДЕЛЁН НАДВОЕ: сначала чтение вёрстки, потом запись стиля.
 * Обратный порядок стоит принудительного пересчёта всего листа каждый кадр,
 * см. черту в frame().
 *
 * НАВОДКА. --reg-x/--reg-y это единичный вектор от приводочного шильда к
 * курсору, где бы тот ни стоял на листе, и ноль, только пока мышь не двигали
 * или увели за край окна. Считается здесь по той же причине, по которой здесь
 * считается фаза ленты: первая строка этого файла. Сам шильд остаётся
 * серверным узлом без единой строки JS: цикл находит его по
 * data-register-mark.
 *
 * Разгон прокрутки на шильд НЕ распространяется: приводка там держится на
 * одном курсоре. --miss правит всеми прочими формами, но не этой.
 *
 * Атака быстрее отпускания: форма срывается резко, а садится медленно,
 * так ведёт себя настоящая машина.
 *
 * ПОДАЧА. --miss это МОДУЛЬ разгона, он одинаков в обе стороны: форма уходит
 * из приводки и вверх, и вниз. Ленте знаков нужен тот же разгон СО ЗНАКОМ, и
 * потому рядом копится --feed: то же число, но помнящее сторону. Из него
 * растёт --run-p, фаза ленты. Считать её здесь, а не в самой ленте, велит
 * первая строка этого файла: цикл на весь сайт один.
 *
 * При prefers-reduced-motion не запускается ничего: ни цикл, ни Lenis.
 */

/**
 * НОМЕР ПОЛОСЫ, И БОЛЬШЕ НИЧЕГО.
 *
 * Грунта и усиления здесь нет намеренно: они объявлены там же, где полоса
 * набрана, и цикл читает их с самого узла, см. ниже. Номер в разметке не
 * стоит, и только за ним цикл и ходит в реестр.
 */
export type SectionMeta = { id: string; n: string };

/* ЧИТАТЕЛИ ЖИВЫХ ПЕРЕМЕННЫХ, перечисленные ровно теми селекторами, которыми
   они объявлены в globals.css. Список здесь, а не в цикле: держать его рядом
   с правилом, которое его задаёт, дешевле, чем искать по файлу.

   --miss читают закон ухода (.plate-r), его инверсия на синем грунте
   ([data-invert='true'] .plate-k) и непрозрачность призраков (.plate-ghost).
   Шильд под селектор подпадает и живого числа не получает во вред: у него
   свой transform по --reg-x/--reg-y, и --miss там не читается вовсе.

   --progress читают звезда подачи и заполненная часть контрольной шкалы. */
const MISS_READERS = '.plate-r, .plate-ghost, [data-invert="true"] .plate-k';
const PROGRESS_READERS = '.star-plate, .strip-fill';

export function PlateProvider({ sections }: { sections: SectionMeta[] }) {
  useEffect(() => {
    const root = document.documentElement;
    const reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    const coarse = window.matchMedia('(width < 768px)').matches;

    root.dataset.motion = reduced ? 'reduced' : 'full';
    /* Полоса стоит, пока цикл не сказал иного. При отказе от движения цикла
       нет вовсе, и метка остаётся на этом значении навсегда: полоса просто
       не уезжает. */
    root.dataset.bar = 'open';

    /* ── ПОЛОСЫ ИЩУТСЯ В ДОКУМЕНТЕ, А НЕ В РЕЕСТРЕ ──────────────────────────
       Грунт и усиление ухода объявлены там, где полоса набрана: `Section`
       пишет их на сам узел (data-section-ground и --gain), и другого источника
       у этих двух чисел нет. Цикл поэтому спрашивает документ.

       Прежде он спрашивал реестр из раскладки, а тот держал ВТОРУЮ запись тех
       же грунтов. Хватило её на два листа из четырёх: «Расчёт» и «Согласие»
       свои первые полосы в реестр не отдали, наблюдатель их не видел, и хрома,
       доехав до выходных данных, оставалась вывернутой по краске до
       перезагрузки. Теперь в реестр ходят за одним НОМЕРОМ полосы: его в
       разметке нет, и он один.

       Список собирается однажды: полосы это разметка листа, а не его
       содержимое, и приходить с рендером они не умеют. */
    const els = Array.from(document.querySelectorAll<HTMLElement>('[data-section-ground]'));
    const groundOf = (el: HTMLElement) => el.dataset.sectionGround || 'paper';

    /* Грунт ГОЛОГО ЛИСТА, вне всякой полосы. Полосы стоят встык и доходят до
       нижнего края документа, поэтому голым лист бывает ровно в одном месте:
       в самом верху, над первой полосой, где в потоке стоит верхняя полоса.
       Красит его body, и красит бумагой, см. globals.css. */
    const BARE_GROUND = 'paper';

    let currentGain = 1;

    /* ЧЕРТА ПО СЕРЕДИНЕ ОКНА ОТВЕЧАЕТ НА ВОПРОС «ЧТО ЧИТАЮТ», и с неё живут
       ровно двое: указатель разделов и усиление ухода приводки. Хрома, которая
       лежит на листе, спрашивает не это, а что у неё под собой, см. ниже. */
    const io = new IntersectionObserver(
      (entries) => {
        for (const e of entries) {
          if (!e.isIntersecting) continue;
          const el = e.target as HTMLElement;
          root.dataset.ground = groundOf(el);
          /* Номера у полосы может не быть вовсе: номера принадлежат главной,
             и на чужом листе текущего раздела нет. Тогда метка снимается, а не
             пишется пустой: пустую указатель принял бы за раздел. */
          const meta = sections.find((s) => s.id === el.id);
          if (meta) root.dataset.section = meta.n;
          else delete root.dataset.section;
          currentGain = parseFloat(el.style.getPropertyValue('--gain')) || 1;
          root.style.setProperty('--gain', String(currentGain));
        }
      },
      { rootMargin: '-50% 0px -50% 0px', threshold: 0 }
    );
    els.forEach((el) => io.observe(el));

    /* ── ГРУНТ ПОД ХРОМОЙ: У КАЖДОЙ ПОЛОСЫ СВОЯ ЧЕРТА ───────────────────────
       Выворот хромы решает не тот раздел, который ЧИТАЮТ, а тот лист, на
       котором она ЛЕЖИТ, и почти всю прокрутку это разные разделы.

       Черта выше проведена по середине окна, и проведена верно: она отвечает
       на вопрос «что читают». Но верхняя полоса стоит у ВЕРХНЕГО реза, на
       полвысоты окна выше этой черты, а контрольная шкала у НИЖНЕГО, на
       столько же ниже. Пока грунт обеим давала середина, каждая красилась по
       разделу, до которого читатель ещё не доехал (полоса) или который уже
       проехал (шкала): белая форма на белой бумаге, бумажная шкала на краске,
       и та и другая по полэкрана ходу.

       У полосы это видно только на ходу ВВЕРХ: вниз она убрана под рез, и
       ошибка идёт за кадром. У шкалы видно в обе стороны, она не уезжает.

       Поэтому черта у каждой своя, и проведена она по середине её собственной
       высоты: пока форма стоит над разделом больше чем наполовину, она его
       грунтом и красится. Высота снимается с узла (offsetHeight), а не с
       токена: --topbar-h объявлен через calc, и getComputedStyle отдаёт его
       невычисленным. Прямоугольник не годится тем более: верхняя полоса на
       ходу вниз уезжает под рез трансформом, и rect уехал бы вместе с ней.

       Черта считается от высоты окна, поэтому на смене формата наблюдатели
       пересобираются. Пересборка заодно и сверяет грунт: новый наблюдатель
       докладывает сразу обо всех целях, и та единственная, что стоит под
       чертой, пишет себя снова.

       ПЕРВОГО ЭКРАНА ЧЕРТА ПОЛОСЫ НЕ ЗАСТАЁТ. Полоса стоит в потоке, первый
       раздел начинается ровно под ней, и у самого верха листа под чертой нет
       ни одного раздела вовсе. До скриптов грунт на этот случай написан в
       разметке (`layout`), а на ходу его пишет сам наблюдатель, см. разбор
       пустой пачки ниже. И тот и другой бумажный: голый лист красит body. */
    const CHROME = [
      { sel: '.topbar', mark: 'barGround', at: 'head' },
      { sel: '.controlstrip', mark: 'stripGround', at: 'foot' },
    ] as const;

    const chrome = CHROME.map((c) => ({
      ...c,
      io: null as IntersectionObserver | null,
      margin: '',
    }));

    const armChrome = () => {
      const vh = window.innerHeight;
      for (const c of chrome) {
        const h = document.querySelector<HTMLElement>(c.sel)?.offsetHeight || 0;
        const line = Math.round(c.at === 'foot' ? vh - h / 2 : h / 2);
        const rootMargin = `-${line}px 0px -${Math.max(vh - line, 0)}px 0px`;
        if (c.margin === rootMargin) continue;
        c.margin = rootMargin;
        c.io?.disconnect();
        const next = new IntersectionObserver(
          (entries) => {
            /* ПОД ЧЕРТОЙ МОЖЕТ НЕ ОКАЗАТЬСЯ НИ ОДНОЙ ПОЛОСЫ, и это не сбой, а
               верх листа: полоса стоит в потоке НАД первым разделом, и под её
               чертой там голая бумага. Пока это не считалось, метка держала
               последний грунт, и прыжок в начало листа (клавиша Home, якорь
               при отказе от движения) оставлял вывернутую плашку стоять на
               бумаге: доклада-то ни одного, черта ушла выше всех.

               Геометрия в условии не для порядка. Ушедшая полоса, которая
               осталась ВЫШЕ черты, значит, что под черту встала следующая, а
               её доклад в эту же пачку мог и не попасть: докладывают только
               те, кто пересёк. Ушедшая НИЖЕ черты значит обратное: черта
               поднялась выше неё, и вот тогда под чертой действительно
               пусто. */
            let hit = false;
            let bare = true;
            for (const e of entries) {
              if (e.isIntersecting) {
                hit = true;
                root.dataset[c.mark] = groundOf(e.target as HTMLElement);
              } else if (e.boundingClientRect.top <= line) {
                bare = false;
              }
            }
            if (!hit && bare) root.dataset[c.mark] = BARE_GROUND;
          },
          { rootMargin, threshold: 0 }
        );
        els.forEach((el) => next.observe(el));
        c.io = next;
      }
    };
    armChrome();
    window.addEventListener('resize', armChrome);

    const stopGrounds = () => {
      io.disconnect();
      for (const c of chrome) c.io?.disconnect();
      window.removeEventListener('resize', armChrome);
    };

    if (reduced) {
      /* Обнулять здесь нечего: --miss, --progress и --run-p объявлены
         ненаследуемыми с initial-value 0, и без единой записи цикла каждый их
         читатель стоит ровно в приводке. Наводка наследуемая, и ноль ей
         объявлен в :root, но написать его ещё раз дешевле, чем помнить об
         этом различии: запись однократная. */
      root.style.setProperty('--reg-x', '0');
      root.style.setProperty('--reg-y', '0');
      window.dispatchEvent(new CustomEvent('alfa:delta', { detail: { mm: 0 } }));
      return stopGrounds;
    }

    /* ── Прокрутка ────────────────────────────────────────────────────────── */
    const lenis = new Lenis({
      lerp: 0.085,
      wheelMultiplier: 1,
      syncTouch: false,
      /* ВЛОЖЕННАЯ ПРОКРУТКА ОТДАЁТСЯ ЭЛЕМЕНТУ, А ПОТОМ ВОЗВРАЩАЕТСЯ СТРАНИЦЕ.
         Такой элемент на сайте один: перечень изделий на листе §03, который
         лежит в постоянном резерве и довозится колесом. Без этого колесо над
         листом везло бы страницу, а перечень стоял. Запрет колеса
         (data-lenis-prevent) решал бы полдела и ломал вторую: дойдя до конца
         перечня, колесо упиралось бы в лист, вместо того чтобы отдать ход
         странице. Lenis считает край сам и отдаёт. */
      allowNestedScroll: true,
    });

    // Якорные ссылки ведёт Lenis, иначе он «догоняет» нативный прыжок.
    const onClick = (e: MouseEvent) => {
      const link = (e.target as HTMLElement | null)?.closest?.('a[href^="#"]');
      if (!(link instanceof HTMLAnchorElement)) return;
      const id = link.getAttribute('href');
      if (!id || id === '#') return;
      const target = document.querySelector(id);
      if (!target) return;
      e.preventDefault();
      /* Отступ читается с самой полосы, а не стоит числом. Раньше здесь было
         -48 при полосе в 68, и заголовок раздела приезжал на двадцать
         пикселей ПОД шапку. Высота полосы теперь ещё и складывается из
         вырубки и поля, так что единственный честный источник это токен. */
      const bar =
        parseFloat(
          getComputedStyle(document.documentElement).getPropertyValue('--topbar-h')
        ) || 72;
      lenis.scrollTo(target as HTMLElement, { offset: -(bar + 8) });
      history.replaceState(null, '', id);
    };
    document.addEventListener('click', onClick);

    const onScrollTo = (e: Event) => {
      const y = (e as CustomEvent<{ y: number }>).detail?.y;
      if (typeof y === 'number') lenis.scrollTo(y);
    };
    window.addEventListener('alfa:scrollto', onScrollTo);

    /* Курсор во вьюпорте нужен для наводки шильда. -1 значит «мышь ещё не
       двигалась»: до первого движения шильд стоит в приводке. */
    let px = -1;
    let py = -1;
    const onPointer = (e: PointerEvent) => {
      px = e.clientX;
      py = e.clientY;
      /* След курсора едет на ЭТОМ слушателе. Своего у него нет: движение
         мыши слушают в одном месте по той же причине, по какой в одном месте
         крутится кадр. */
      trailPointer(e);
    };

    /* ЛУПЫ НА ЛИСТЕ НЕТ, И КООРДИНАТ ЕЁ ТУТ ТОЖЕ БОЛЬШЕ НЕТ. Здесь копились
       --mx/--my и раз в кадр уходили в :root. Читателя у них не осталось ни
       одного: узла с data-loupe в разметке нет, в стилях эти две переменные
       только объявлены. Платили за них дважды. Раз кадром: каждая запись в
       :root это недействительный стиль всего листа, см. put ниже. И два
       событием: getBoundingClientRect стоял внутри pointermove, то есть
       вынуждал вёрстку считаться посреди события, мимо той самой черты,
       которая ниже разводит чтение и запись. */
    window.addEventListener('pointermove', onPointer, { passive: true });

    /* Мышь ушла за край окна: событий больше не будет, и без этого шильд
       остался бы висеть в последнем уходе, так и не сев в приводку. */
    const onPointerLeave = () => {
      px = -1;
      py = -1;
      trailAway();
    };
    document.documentElement.addEventListener('pointerleave', onPointerLeave);
    window.addEventListener('blur', onPointerLeave);
    /* Вкладку увели в фон: событий тоже больше не будет, а вернуться мышь
       может уже в другой точке. Без этого линия прочертила бы весь лист
       в первом же кадре после возврата. */
    const onHide = () => {
      if (document.hidden) onPointerLeave();
    };
    document.addEventListener('visibilitychange', onHide);

    /* ── Лента знаков: период прогона читается один раз ────────────────────
       Скорость ленты живёт там же, где список знаков, в `--run` на самой
       полосе (по ширине знаков, 63 px/с на 1440). Здесь она только считывается, чтобы цикл знал, за
       сколько секунд фаза проходит от 0 до 1. Полосы на странице может не
       быть вовсе: тогда фаза не копится и переменная не пишется. */
    const band = document.querySelector<HTMLElement>('.marks');
    const runFor = band ? parseFloat(getComputedStyle(band).getPropertyValue('--run')) : NaN;
    const runRate = runFor > 0 ? 1 / runFor : 0;

    /* ── Наводка: границы прибора ──────────────────────────────────────────
       REG_REACH это плечо, на котором вылет доходит до полного. У самого шильда
       точка стоит в приводке, за 320 px уходит на весь --reg-throw, а дальше
       только поворачивается вокруг креста, куда бы курсор ни ушёл: это прибор,
       а не погоня за мышью. REG_LERP один в обе стороны: тот же след и
       читается как посадка обратно. */
    const REG_REACH = 320;
    const REG_LERP = 0.12;

    /* ── ПОЛОСА УХОДИТ ПОД ВЕРХНИЙ РЕЗ ────────────────────────────────────
       Читают вниз, полоса уезжает за рез и отдаёт набору весь формат; ведут
       лист обратно, она возвращается. Своего слушателя прокрутки у неё
       по-прежнему нет: сторону хода знает этот цикл, и всё, что он пишет,
       это одна метка `data-bar` на :root. Ход формы объявлен в CSS.

       BAR_ARM это шапка листа: на первой сотне пикселей полоса стоит, уходить
       ей оттуда некуда. BAR_STEP это ход, который лист обязан пройти ПОСЛЕ
       разворота, прежде чем полоса ему поверит: двенадцать пикселей отсекают
       и дрожь тачпада, и докат Lenis, и не дают полосе мигать покадрово. */
    const BAR_ARM = 100;
    const BAR_STEP = 12;
    let barY = window.scrollY || 0;
    let barPivot = barY;
    let barDir = 0;
    let barGone = false;

    /* ── Цикл ─────────────────────────────────────────────────────────────── */
    let s = 0;
    let feed = 0;
    let phase = 0;
    let lastFrame = 0;
    let lastCounter = 0;
    let raf = 0;
    let markEl: HTMLElement | null = null;
    let trackEls: HTMLElement[] = [];
    let missEls: HTMLElement[] = [];
    let progEls: HTMLElement[] = [];

    /* СПИСКИ ЧИТАТЕЛЕЙ ПЕРЕСОБИРАЮТСЯ ПО РАЗМЕТКЕ, А НЕ ПО КАДРУ. Формы R
       приходят и уходят с React-рендером (§03 перебирает строки под курсором,
       §04 пересобирает ленту), и querySelectorAll шестьдесят раз в секунду
       ради этого платить незачем. Наблюдатель ставит флаг, кадр разбирает его
       не чаще раза. data-invert в фильтре потому, что от него зависит, какая
       форма уходит: узел при смене грунта остаётся тем же. */
    let stale = true;
    const readers = new MutationObserver(() => {
      stale = true;
    });
    readers.observe(document.body, {
      childList: true,
      subtree: true,
      attributeFilter: ['data-invert'],
    });
    let rx = 0;
    let ry = 0;
    let regSettled = true;

    /* ЗАПИСЬ ТОЛЬКО НА ИЗМЕНЕНИЕ.
       Переменная объявлена наследуемой, и запись в неё это не одно свойство
       одного узла, а недействительный стиль ВСЕГО документа: браузер обязан
       заново вывести значение на каждом из полутора тысяч узлов листа. Пока
       строка та же, писать её значит платить этот пересчёт ни за что, а
       именно так цикл и работал: `--miss` уходил в :root каждый кадр, в том
       числе все те кадры, когда он равен нулю и лист стоит.

       Здесь помнится ПОСЛЕДНЯЯ ЗАПИСАННАЯ СТРОКА, а не число: сравнивать
       следует ровно то, что уйдёт в стиль, иначе округление до четвёртого
       знака пропустит мимо памяти шевеление в шестом. */
    const written = new Map<string, string>();
    const put = (host: HTMLElement | null, name: string, value: string) => {
      if (!host || written.get(name) === value) return;
      written.set(name, value);
      host.style.setProperty(name, value);
    };

    /* ТО ЖЕ, НО НА ВСЕХ ЧИТАТЕЛЕЙ РАЗОМ. Двадцать пять записей в стиль дешевле
       одной записи в :root, и дешевле не на проценты. Замерено на собранном
       листе, две секунды после одного поворота колеса: из :root это 311
       пересчётов стиля и 1305 мс работы, то есть восемьдесят шесть процентов
       времени; теми же кадрами на сами формы R это 140 пересчётов и 16 мс.
       Ровно в эти две секунды и попадает наведение на строку §03, и опаздывало
       оно не из-за §03. */
    const putAll = (hosts: HTMLElement[], name: string, value: string) => {
      if (written.get(name) === value) return;
      written.set(name, value);
      for (const host of hosts) host.style.setProperty(name, value);
    };

    const frame = (t: number) => {
      /* Шаг кадра нужен ЛЕНТЕ: фаза это интеграл, и на 144 Гц она обязана
         набегать та же, что на 60. Потолок в 50 мс стоит на возврат из фоновой
         вкладки: там кадра не было секундами, и без него лента телепортируется. */
      const dt = lastFrame ? Math.min((t - lastFrame) / 1000, 0.05) : 0;
      lastFrame = t;

      lenis.raf(t);

      /* Полоса. Разворот запоминается точкой, от которой считается ход, и
         только пройденный ход переключает метку: сторона сама по себе ничего
         не решает, иначе полоса дёргалась бы на каждой смене знака. */
      const y = lenis.scroll;
      const dir = y > barY ? 1 : y < barY ? -1 : barDir;
      if (dir !== barDir) {
        barDir = dir;
        barPivot = barY;
      }
      barY = y;

      let gone = barGone;
      if (y <= BAR_ARM) gone = false;
      else if (dir > 0 && y - barPivot > BAR_STEP) gone = true;
      else if (dir < 0 && barPivot - y > BAR_STEP) gone = false;

      /* След курсора считается и рисуется здесь и только здесь. Холста может
         не быть вовсе (палец, отказ от движения, ещё не смонтировано): тогда
         вызов возвращается сразу, ничего не считая и ничего не рисуя.
         Берёт метку кадра, а не его длину: длина линии это отрезок ВРЕМЕНИ
         на записанном пути, и пересчёт кадров ей не нужен. */
      trailFrame(t);

      /* ── СНАЧАЛА ЧИТАЕМ ВЁРСТКУ, ПОТОМ ПИШЕМ СТИЛЬ ─────────────────────────
         Порядок здесь не вкус, а цена кадра.

         Прямоугольник шильда это ЧТЕНИЕ вёрстки, и отдать его браузер обязан
         свежим: всё, что записано в стиль выше по кадру, он пересчитывает
         немедленно и синхронно, на всём документе. Запись `--miss` стояла
         ровно строкой выше этого чтения, и потому КАЖДЫЙ кадр после
         прокрутки стоил принудительного пересчёта вёрстки целого листа.
         Замерено на этой странице: 85 таких пересчётов и 0,94 с работы за
         две секунды после одного поворота колеса, кадр 24 мс вместо 13.
         Наведение на строку §03 вставало в очередь за ними и опаздывало
         настолько, что это было видно глазом.

         Поэтому кадр разделён надвое: ВЫШЕ этой черты только чтение, НИЖЕ
         только запись. На чтении вёрстка заведомо чистая, она осталась такой
         с прошлого кадра, а пересчёт возвращается туда, где ему и место: в
         конец кадра, один раз. Поднять любую запись в стиль выше черты
         значит вернуть ту же цену.

         Шильд ищется заново, только если его нет в документе: Dopusk ставит
         его после разной строки на телефоне и на столе, и на смене формата
         узел пересоздаётся. На листах без шильда весь блок пропускается. */
      /* Память записи сбрасывается вместе со списком: новый узел с той же
         строкой не получил бы ничего и застыл бы в приводке. Та же причина,
         по которой сбрасывается --run-p при пересборке ленты. */
      if (stale) {
        stale = false;
        missEls = Array.from(document.querySelectorAll<HTMLElement>(MISS_READERS));
        progEls = Array.from(document.querySelectorAll<HTMLElement>(PROGRESS_READERS));
        written.delete('--miss');
        written.delete('--progress');
      }

      if (!coarse && !markEl?.isConnected) {
        markEl = document.querySelector('[data-register-mark]');
        /* Память записи держит СТРОКУ, а не узел: на новый шильд с той же
           строкой не ушло бы ничего, и точка застыла бы в приводке. Та же
           причина, по которой сбрасывается --run-p при пересборке ленты. */
        written.delete('--reg-x');
        written.delete('--reg-y');
      }

      let tx = 0;
      let ty = 0;
      if (!coarse && markEl && px >= 0) {
        /* Границ у наводки нет: где бы курсор ни стоял, хоть в подвале,
           точка смотрит на него. Прибор не выключается оттого, что от
           него отвели взгляд.

           Прямоугольник читается каждый кадр намеренно: лист едет под
           неподвижной мышью, и вектор обязан это видеть. */
        const m = markEl.getBoundingClientRect();
        const dx = px - (m.left + m.width / 2);
        const dy = py - (m.top + m.height / 2);
        const d = Math.hypot(dx, dy);
        // Половина пикселя: курсор ровно на кресте, направления нет.
        if (d > 0.5) {
          const k = Math.min(d / REG_REACH, 1) / d;
          tx = dx * k;
          ty = dy * k;
        }
      }

      /* ── Ниже черты только запись ─────────────────────────────────────── */

      if (gone !== barGone) {
        barGone = gone;
        root.dataset.bar = gone ? 'gone' : 'open';
      }

      if (!coarse) {
        const v = Math.min(Math.abs(lenis.velocity) / 42, 1);
        // Атака 0.35, отпускание 0.055: срывается быстрее, чем садится.
        s += (v - s) * (v > s ? 0.35 : 0.055);

        /* ХВОСТ ОБРЫВАЕТСЯ, А НЕ ТАЕТ. Отпускание экспоненциально и до нуля
           не доходит никогда: от полного разгона до четвёртого знака это под
           две сотни кадров, то есть до трёх секунд, в которые лист уже стоит,
           а строка всё ещё меняется каждый кадр и заново обесценивает стиль
           всего документа. Порог 0,005 это 0,056 px ухода при самом сильном
           усилении (0,005 × 1,6 × 7 px) и три тысячных непрозрачности
           призрака: ни того, ни другого не видно ни на одном экране. Хвост
           от этого не только короче вдвое, он ЗАКАНЧИВАЕТСЯ: дальше строка
           не меняется, а неизменную строка запись не трогает. */
        if (s < 0.005) s = 0;
        putAll(missEls, '--miss', s.toFixed(4));

        if (markEl) {
          rx += (tx - rx) * REG_LERP;
          ry += (ty - ry) * REG_LERP;

          /* ВЕКТОР ПИШЕТСЯ НА САМ ШИЛЬД, А НЕ В :root, и это тот же перенос,
             что уже сделан фазе ленты. Читатель у наводки ровно один селектор
             и ровно один узел на листе: [data-register-mark] .plate-r. В :root
             эти две строки стоили полного пересчёта стиля ВСЕГО документа,
             и стоили его НА КАЖДОЕ ДВИЖЕНИЕ МЫШИ, потому что вектор считается
             от курсора и меняется каждый кадр, пока мышь идёт. Замерено на
             собранном листе: 1351 узел за пересчёт, 17-22 мс на каждый, до
             девяноста пересчётов за секунду ведения мыши. Наведение на любую
             строку §03 из-за этого запаздывало на кадры, а виновата была не
             §03. На шильде тот же вектор стоит 24 узла.

             Село в приводку, писать перестаём. Последний кадр всё же пишем,
             иначе точка замрёт в сотой доле от нуля. */
          const moving = Math.abs(tx - rx) > 1e-4 || Math.abs(ty - ry) > 1e-4;
          if (moving || !regSettled) {
            put(markEl, '--reg-x', rx.toFixed(4));
            put(markEl, '--reg-y', ry.toFixed(4));
            regSettled = !moving;
          }
        }
      }

      if (runRate) {
        /* Подача со знаком. Тот же разгон, что у --miss, и та же нормировка
           на 42, но без Math.abs: у Lenis velocity положительна, когда лист
           уходит ВВЕРХ, то есть когда читают ВНИЗ.

           Атака здесь срабатывает ещё и на СМЕНЕ СТОРОНЫ (feed * nv < 0):
           по модулю прокрутка в обратную сторону может быть не сильнее
           прежней, но машину при этом реверсируют, и отрабатывать это
           отпусканием в 0,055 значило бы, что лента думает полсекунды.
           Возврат к нулю остаётся медленным: лента накатом садится на
           свой ход, а не тормозит колодкой. */
        const nv = Math.max(-1, Math.min(lenis.velocity / 42, 1));
        const attack = nv !== 0 && (Math.abs(nv) > Math.abs(feed) || feed * nv < 0);
        feed += (nv - feed) * (attack ? 0.35 : 0.055);

        /* Разгон в девять: на спокойном чтении (подача ≈ 0,15) лента идёт
           вдвое с лишним быстрее, на разгоне всемеро. Он же задаёт точку
           разворота: подача -1/9, и ход обнуляется, дальше лента едет назад.
           Это ≈ 4,7 px за кадр вверх, то есть настоящая прокрутка вверх,
           а не дрожание пальца на тачпаде. */
        phase = (phase + runRate * (1 + feed * 9) * dt) % 1;
        if (phase < 0) phase += 1;
        /* Пять знаков, а не четыре, как у --miss: дорожка вдесятеро длиннее
           полосы, и шаг в 1e-4 дал бы на широком экране полпикселя дребезга. */

        /* ФАЗА ПИШЕТСЯ НА САМИ ДОРОЖКИ, А НЕ НА ЛЕНТУ И НЕ В :root. Читают её
           ровно два узла, .marks-track и .marks-back, и больше никто, а лента
           идёт ВСЕГДА: это единственное число цикла, которое меняется каждый
           кадр и на стоящем листе.

           Дорога сюда шла в два шага, и первый был половинчатым. Из :root фаза
           уехала на .marks, и это сняло с кадра около девяти миллисекунд: в
           :root она обесценивала стиль всех полутора тысяч узлов. Но на .marks
           она обесценивала 434 узла ленты, то есть все знаки до единого, ради
           тех же двух трансформов, и делала это шестьдесят раз в секунду на
           любой полосе сайта. Замерено на собранном листе: пересчёт стиля на
           657 узлов, из них 434 это лента.

           Наследование сюда фазу больше не доносит и не должно: переменная
           объявлена inherits: false (см. @property в globals.css), потому
           запись ложится ровно на тот узел, который её читает, и ни один знак
           внутри дорожки от неё не грязнится. Отсюда же и цикл по узлам: две
           ветви получают одно и то же число порознь, а не через общего предка.

           Узлы перепроверяются по той же причине, что и шильд: лента живёт в
           своей секции и переживает пересборку. Память записи при этом
           сбрасывается, иначе на новые узлы не ушло бы ничего. */
        if (!trackEls.length || !trackEls[0].isConnected) {
          trackEls = Array.from(document.querySelectorAll<HTMLElement>('.marks-track'));
          written.delete('--run-p');
        }
        putAll(trackEls, '--run-p', phase.toFixed(5));
      }

      putAll(progEls, '--progress', (lenis.progress || 0).toFixed(4));


      // 12 Гц: чаще, и цифры начинают мельтешить.
      if (t - lastCounter > 83) {
        const mm = (0.007 * s * currentGain * 1000) / 3.7795;
        window.dispatchEvent(new CustomEvent('alfa:delta', { detail: { mm } }));
        lastCounter = t;
      }

      raf = requestAnimationFrame(frame);
    };
    raf = requestAnimationFrame(frame);

    return () => {
      cancelAnimationFrame(raf);
      document.removeEventListener('click', onClick);
      window.removeEventListener('alfa:scrollto', onScrollTo);
      window.removeEventListener('pointermove', onPointer);
      document.documentElement.removeEventListener('pointerleave', onPointerLeave);
      window.removeEventListener('blur', onPointerLeave);
      document.removeEventListener('visibilitychange', onHide);
      lenis.destroy();
      stopGrounds();
      readers.disconnect();
    };
  }, [sections]);

  return null;
}
