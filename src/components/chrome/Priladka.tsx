/**
 * ПРИЛАДОЧНЫЙ ЛИСТ
 *
 * Лист, который печатник прогоняет ПЕРЕД тиражом. Машина под током, формы
 * встали, но приводка ещё не сведена и краска ещё не вышла: такие оттиски
 * идут в макулатуру, и печатник считает их по счётчику, пока лист не станет
 * годным. Ровно это и делает загрузка, поэтому у неё здесь имя ремесла, а не
 * «прелоадер».
 *
 * НА ЛИСТЕ ОДИН ПРЕДМЕТ: счёт до ста. Ни имени фирмы, ни знака, ни слова, ни
 * второй краски. Приладочный лист ничего не сообщает, он показывает состояние
 * машины, и предмет на нём поэтому ровно один, а не один плюс приём.
 *
 * ПОЧЕМУ ГОЛОС ЗНАКА, А НЕ ГОЛОС ПОЛОСЫ. Довод в порядке чтения: лист стоит
 * ПЕРЕД §01, и первое, что читатель видит на сайте, обязано быть именем
 * фирмы. Имени на листе нет — на нём один предмет, счёт, — значит именем
 * должен звучать сам счёт. Это единственное место на сайте, где так, и
 * единственное, ради которого в сборке держат четвёртую гарнитуру.
 *
 * Машинку (Martian Mono) сюда не ставят по-прежнему: она голос ПОКАЗАНИЙ и
 * живёт там, где печатать нечего — шильды, счёт шагов §07, подписи под
 * формами §03. Антикву полосы сняли уже этой правкой: она голос НАБОРА, а
 * лист не набран, он оттиснут знаком.
 *
 * НАБРАТЬ ЭТО ФОРМАМИ ЛОГОТИПА НЕЛЬЗЯ, и это не оговорка, а предел: в
 * `ALPHABET` (`Mark.tsx`) девять букв, А Л Ь Ф Р П И Н Т, и цифр среди них
 * нет ни одной; `setLogotype` на всём прочем бросает. Поэтому здесь
 * ПОХОЖЕСТЬ, и она заявлена похожестью: Montserrat 700, тяжёлый
 * геометрический гротеск той же породы, что строка «АЛЬФА», и с той же
 * толщиной штриха — 22,41 % прописной против 22,9 у знака. Вес выбран этим
 * обмером, а не глазом, и обмер решил против глаза: на 900 полоса казалась
 * «в тон», а штрих был толще знака в полтора раза. Таблица в `fonts.ts`.
 *
 * ТРИ РАЗРЯДА, ВСЕ В КРАСКЕ, и это отмена прежнего приёма. Ведущие нули
 * стояли бумагой в 14 % и краснели на своём переходе — приём верный на
 * антикве, где ведущий ноль тонкий и в 14 % честно уходит в бумагу. На
 * тяжёлом геометрическом гротеске тот же ноль это широкое кольцо, 14 % от
 * него дают не бумагу, а крупное серое пятно, и «000» читалось двумя серыми
 * бубликами рядом с чёрным нулём, то есть поломкой, а не счётом.
 *
 * Силуэт теперь постоянный от первого кадра до последнего, счётчик читается
 * барабанным, и ПОД СЧЁТОМ НЕ ИДЁТ НИ ОДНОГО ПЕРЕХОДА ЦВЕТА. Кадровый цикл
 * от этого стал чистым `textContent`: ни атрибутов, ни стилей, ни одной
 * инвалидации за прогон, а идёт он ровно поверх гидратации и раскладки §01.
 *
 * ДО ГАРНИТУР ЛИСТ ПУСТ, и это то же самое правило: печатать нечем, пока не
 * пришли формы. Счёт начинается по `document.fonts.ready`, и пусто бывает
 * ровно столько, сколько идут гарнитуры: на своей машине и на любом втором
 * заходе это ноль, потому что они в кэше.
 *
 * ЖДЁТ ОН ПРИ ЭТОМ НЕ ДОЛЬШЕ 250 мс. Чистый лист без единого знака на плохом
 * канале не говорит ничего вообще, и молчать ему позволено четверть секунды,
 * не дольше. Считать в запасной не страшно, и цена подмены здесь НЕ в раскладке:
 * блок центрован, ширина у него меняется симметрично, и средний разряд не
 * ездит вовсе. Цена вертикальная: оптическая середина у Montserrat 700
 * −0,0067 кегля, у запасной Arial Black −0,035, то есть разница 0,0283, и на
 * полном кегле запасная стоит на 3,85 px ниже своей. Осадка эта одна, она
 * приходится на первые 250 мс и проходит ПОД затуханием в 220 мс, которым
 * число выходит на краску. Поправлять её отдельным правилом нельзя: это
 * обменяло бы невидимую осадку под затуханием на видимый скачок в полной
 * краске.
 *
 * ЗАПАСНАЯ ВЫБРАНА ПО ПОРОДЕ, а не по тому, что стоит в системе: Arial Black
 * это тяжёлый гротеск, то есть промах по рисунку, а не по жанру. Обычный
 * системный `sans-serif` на весе 700 дал бы вместо знака обычный жирный
 * текст.
 *
 * ГОТОВНОСТЬ ПОДНИМАЕТ ПОТОЛОК И СКОРОСТЬ СРАЗУ, и это главная переделка
 * против прежней версии. Устройство потолка верное и оставлено целиком: веха
 * поднимает его ступенью, готовность — пандусом REL, к потолку счёт подходит
 * через демпфер по остатку хода (BAND), а у демпфера есть НИЖНИЙ УПОР
 * (FLOOR), без которого он подползал бы к потолку вечно и вставал бы на
 * девяноста девяти, а «затухание врёт»: за счётчиком смотрят.
 *
 * ЧЕГО ПОТОЛОК НЕ УМЕЕТ — ТАК ЭТО ТОРОПИТЬ, и прежде вся честность лежала в
 * нём одном. Множитель демпфера обрезан единицей сверху, то есть потолок
 * может счёт только придержать, и обогнать свой пробег счётчик не мог ни при
 * какой готовности. Пробег был ПОЛОМ, и замер показал цену этого пола: load
 * приходил на 214 мс, а лист уходил на 1785-й — полторы секунды счёта поверх
 * давно готовой страницы. Лист, который считает, когда считать уже нечего,
 * это не загрузка, а заставка.
 *
 * Поэтому по тому же пандусу REL идёт теперь и СКОРОСТЬ, от VMIN к VRDY.
 * Прежний порок был не в двух скоростях, а в СКЛЕЙКЕ: затухающий ползок
 * обрывался линейным рывком, и шов читался заклинившей машиной, которую
 * пнули. Пандус в 200 мс с демпфером поверх шва не даёт — счёт не прыгает,
 * он разгоняется, и разгон приходится на начало прогона, а не на середину.
 *
 * Посадка при этом осталась конечной: на готовом пробеге последний счёт
 * занимает 28 мс, на ожидающем — около 150, и это самая долгая пауза за
 * весь прогон.
 *
 * ВСТАТЬ СОВСЕМ ОН НЕ МОЖЕТ НИ ПРИ КАКОМ КАНАЛЕ. Потолок ползёт к сроку сам,
 * и даже упёршись в него намертво счётчик идёт 7,3 счёта в секунду — реже
 * домового предела в 12 Гц (см. `PlateProvider`), но не стоит. Стоящий
 * счётчик читается поломкой, а не ожиданием, и это худшее, что лист может
 * показать.
 *
 * СОТНЮ ОН ПОКАЗЫВАЕТ ТОЛЬКО ПО ГОТОВНОСТИ, то есть после DOMContentLoaded и
 * load, и ни кадром раньше: до готовности потолок обрезан на 99. Отсюда и
 * поведение по крайнему сроку — он снимает лист поправкой в ОДИН счёт, а не
 * прыжком с середины.
 *
 * ПОСЛЕ ГОТОВНОСТИ ЖЕ ОН НЕ МЕДЛИТ, и это вторая половина той же честности.
 * Прогон по модели на всех каналах: load на 600 мс — сотня через 383, load на
 * 1500 — через 250, load на 3000 — через 250. То есть срок листа задаёт
 * страница, а не константа: сколько грузится, столько он и считает, и уходит
 * четвертью секунды позже. Не пришёл load вовсе — лист стоит на 99 до
 * крайнего срока MAX.
 *
 * УХОД ЛИСТА ЭТО УХОД ЧИСЛА, А НЕ БУМАГИ, и дошли до этого через две
 * отвергнутые попытки — обе записаны в `globals.css`, потому что обе казались
 * верными. Коротко: лист набран краской `--color-paper` и полоса под ним той
 * же самой, поэтому НИ ОДИН ход самой бумаги на экране не виден. Съезд вверх
 * (560 мс) читался только тем, что число улетало за рез. Срез снизу вверх
 * (340 мс, `hero-strike` наоборот) держался на том, как срезается число, — и
 * замер показал, что не держится: `--ease-blade` быстрее всего идёт в
 * середине, число стоит ровно в середине, и кромка проходит его за два кадра
 * (на +80 мс целое, на +105 мс его нет).
 *
 * Поэтому число просто ГАСНЕТ за 220 мс. На листе один предмет, и уйти он
 * может только одним способом — перестать быть напечатанным.
 *
 * ОТКРЫВАЕТ ПОЛОСУ НЕ ЛИСТ, А §01. Ракель по имени фирмы это и есть настоящее
 * открытие, оно на полторы секунды и оно уже нарисовано; листу остаётся не
 * мешать ему и не спорить с ним вторым жестом. `data-press="run"` встаёт в
 * тот же кадр, что и затухание, так что к моменту, когда бумага сойдёт, имя
 * уже пошло в печать.
 *
 * ДЕРЖАТ НА СОТНЕ 120 мс. Прежде держали 260, и держали не ради паузы, а
 * ради перехода: старший разряд выходил на краску за 240 мс, и трогать лист
 * раньше значило увозить его с недопечатанным разрядом. Переходов под счётом
 * больше нет, ждать нечего, и пауза оставлена ровно такой, чтобы сотня
 * прочиталась.
 *
 * КТО ПРОСИЛ НЕ ДВИГАТЬ, получает тот же счёт короче и реже: оба пробега
 * укорочены (0,8 с вместо 1,2 на ожидании, 0,46 вместо 0,56 на готовой), а
 * перерисовка разрядов идёт не чаще 12 Гц, то есть около десяти шагов вместо
 * ста. Сам счёт не убран: без него лист молчит, а молчащий лист поверх сайта
 * хуже мелькающего. Остальное снимает CSS.
 *
 * СКРИПТ ГОЛЫЙ И СТОИТ В РАЗМЕТКЕ, а не в компоненте с 'use client'. Довод:
 * он обязан идти ДО гидратации и до разбора `<main>`. Он ставит
 * `data-press="load"` раньше, чем в дереве появится первая строка §01,
 * поэтому её анимация встаёт на паузу с первого своего кадра, а не с первого
 * кадра React. Из того же следует и обратное, и это здесь главная страховка:
 * пока скрипт не выполнился, атрибута НЕТ и §01 идёт как шёл. Отказом этого
 * листа сайт сломать нельзя ни при каком раскладе, а сам лист снимает с себя
 * ещё и чистый CSS на двенадцатой секунде, см. `mk-abort` в `globals.css`.
 *
 * ЗАМОК ПРОКРУТКИ СНИМАЕТСЯ НА ЛЮБОМ ВЫХОДЕ, и это не педантизм, а починка:
 * прежде обработчики снимались только штатным `snyat()`, и любой бросок после
 * их установки оставлял страницу неподвижной навсегда — лист при этом уже
 * снят, и причины на экране нет. Теперь их снимает общий `pusti()`, который
 * зовут обе двери, штатная и аварийная.
 *
 * АВАРИЙНАЯ ДВЕРЬ ЗАКРЫВАЕТСЯ НАСОВСЕМ, и это вторая половина той же починки.
 * Пуск заведён дважды (по гарнитурам и по сроку в 250 мс), обе заявки стоят
 * РАНЬШЕ возможного броска, и снять их бросок не может. Сторожил пуск при
 * этом только собственное `t0`, поэтому после аварийного выхода он заново
 * выставлял листу `data-mk="ink"` — лист возвращался на экран со стоящим
 * счётчиком и висел так до чистого CSS на двенадцатой секунде. Отсюда `done`
 * в стороже: закрытую дверь не открывает ни одна из двух заявок.
 *
 * ЧЕГО ЛИСТ НЕ ЧИНИТ. Он `aria-hidden` поверх живой страницы, и Tab в эти
 * 0,7 с уводит фокус за непрозрачное поле. Клавиатурную прокрутку он тоже не
 * держит, только колесо и палец. Обе оговорки оставлены сознательно: лист
 * декоративный и на готовой странице живёт меньше секунды, а перехват фокуса
 * и клавиш стоил бы ловушки фокуса на объекте, которого через эту секунду
 * нет.
 */

const PROGON = `
(function () {
  if (window.__mk) return;
  window.__mk = 1;
  var D = document, H = D.documentElement, mk = D.querySelector('.mk');
  if (!mk) return;

  var hold = null, done = false;

  function pusti() {
    if (!hold) return;
    window.removeEventListener('wheel', hold);
    window.removeEventListener('touchmove', hold);
    hold = null;
  }

  function off() {
    done = true;
    try {
      pusti();
      mk.setAttribute('data-mk', 'done');
      H.setAttribute('data-press', 'run');
    } catch (e2) {}
  }

  try {
    if (!window.requestAnimationFrame) { off(); return; }
    H.setAttribute('data-press', 'load');

    var R = mk.querySelectorAll('.mk-num > span');
    if (R.length !== 3) { off(); return; }

    var calm = window.matchMedia && matchMedia('(prefers-reduced-motion: reduce)').matches;
    // ПРОБЕГОВ ДВА, И ВЫБИРАЕТ МЕЖДУ НИМИ НЕ ВЕХА, А ГОТОВНОСТЬ СТРАНИЦЫ.
    // MIN — пробег, пока грузить ещё есть чего; RDY — когда грузить уже
    // нечего. Замер на этой полосе до правки: load приходил на 214 мс, а
    // счёт кончался на 1518-й, то есть лист полторы секунды лежал на ГОТОВОЙ
    // странице и считал вхолостую. Чинится ровно это.
    //
    // ПОЛНОТА СЧЁТА НЕ ЧИТАЕТСЯ НИ ПРИ ОДНОМ ИЗ ДВУХ, и выбор между скоростью
    // и полнотой сделан в пользу скорости. Показать все сто значений можно
    // только по одному в кадр, то есть при 60 Гц сотня стоит 1667 мс, не
    // меньше. Замер по значениям:
    //    560 → 31 значение из ста, шаг до 7
    //   1200 → 66 из ста, шаг до 4
    //   2000 → 101, шаг 1
    // На восьмидесяти с лишним значениях в секунду единицы идут смазом и при
    // 1200, поэтому разница между пробегами не в дробности, а в длине.
    // Пропуск при этом ровный, а не разрывом: разрывом был прежний порок —
    // стоячий счётчик и прыжок с середины, — и его нет ни при каком пробеге.
    // Хотите enumerate вместо sample — ставьте 2000 в оба.
    var MIN = calm ? 800 : 1200, RDY = calm ? 460 : 560, STEP = calm ? 83 : 0;
    var MAX = 5200, HOLD = 120, WAIT = 250, REL = 200;
    var BAND = 0.06, FLOOR = 0.18;
    // Пробег ровно MIN (соответственно RDY), с демпфером и упором вместе:
    // (1 - BAND) + BAND * (1 + ln(1 / FLOOR)) = 1.103
    var VMIN = 1.103 / MIN, VRDY = 1.103 / RDY;

    var t0 = 0, last = 0, tPaint = 0, tLoad = 0, base = 0.34;
    var p = 0, shown = -1;

    hold = function (e) { if (!done) e.preventDefault(); };
    window.addEventListener('wheel', hold, { passive: false });
    window.addEventListener('touchmove', hold, { passive: false });

    function paint(n) {
      if (n === shown) return;
      shown = n;
      var s = n > 99 ? '100' : n > 9 ? '0' + n : '00' + n;
      for (var i = 0; i < 3; i++) {
        if (R[i].textContent !== s.charAt(i)) R[i].textContent = s.charAt(i);
      }
    }

    function snyat() {
      if (done) return;
      done = true;
      paint(100);
      pusti();
      setTimeout(function () {
        H.setAttribute('data-press', 'run');
        mk.setAttribute('data-mk', 'lift');
        setTimeout(function () { mk.setAttribute('data-mk', 'done'); }, 260);
      }, HOLD);
    }

    function frame(now) {
      if (done) return;
      var el = now - t0;
      if (el >= MAX) { snyat(); return; }

      // ОДИН ПАНДУС ПОДНИМАЕТ И ПОТОЛОК, И СКОРОСТЬ. Потолок без скорости
      // умеет только задержать счёт: множитель демпфера обрезан единицей
      // сверху, и обогнать VMIN счётчик не мог ни при какой готовности.
      var rel = tLoad ? Math.min(1, (now - tLoad) / REL) : 0;
      var creep = Math.min(0.99, base + (1 - base) * el / MAX);
      var ceil = creep + (1 - creep) * rel;
      var v = VMIN + (VRDY - VMIN) * rel;

      var dt = Math.min(50, now - last);
      last = now;
      p = Math.min(ceil, p + v * Math.min(1, Math.max(FLOOR, (ceil - p) / BAND)) * dt);

      if (!STEP || now - tPaint >= STEP) {
        tPaint = now;
        paint(Math.min(100, Math.floor(p * 100)));
      }
      if (p > 0.9999) { snyat(); return; }
      requestAnimationFrame(frame);
    }

    function pusk() {
      if (t0 || done) return;
      t0 = last = tPaint = performance.now();
      mk.setAttribute('data-mk', 'ink');
      requestAnimationFrame(frame);
      setTimeout(snyat, MAX + 600);
    }
    if (D.fonts && D.fonts.ready && D.fonts.ready.then) D.fonts.ready.then(pusk, pusk);
    else pusk();
    setTimeout(pusk, WAIT);

    function vekha() { base = 0.62; }
    if (D.readyState === 'loading') D.addEventListener('DOMContentLoaded', vekha);
    else vekha();
    function gotov() { if (!tLoad) tLoad = performance.now(); }
    if (D.readyState === 'complete') gotov();
    else window.addEventListener('load', gotov);
  } catch (e) { off(); }
})();
`;

/**
 * Три разряда, все в краске с первого кадра. Разряд это один узел, а не одна
 * строка на всё число, потому что прогон переписывает их поразрядно и потому
 * что последнему нужна своя отбивка (см. `:last-child` в `globals.css`).
 *
 * `suppressHydrationWarning` стоит на каждом узле, который трогает скрипт, и
 * ни на одном лишнем. Скрипт успевает отсчитать до гидратации, React видит в
 * разметке не тот текст, который отрисовал сам, и без этой пометки он либо
 * ругается, либо возвращает «000» обратно на один кадр. На обёртке пометка
 * закрывает один `data-mk`: инлайновых стилей прогон больше не пишет.
 */
export function Priladka() {
  return (
    <>
      <div className="mk" data-mk="load" aria-hidden="true" suppressHydrationWarning>
        <div className="mk-num">
          <span suppressHydrationWarning>0</span>
          <span suppressHydrationWarning>0</span>
          <span suppressHydrationWarning>0</span>
        </div>
      </div>
      <script dangerouslySetInnerHTML={{ __html: PROGON }} />
    </>
  );
}
