/** Полоса набора: y=0 это верх краски, y=100 её низ. */
export const LOGOTYPE_CAP = 100;

/** Линия шрифта прямых букв: «L» и «k» стоят на ней, овалы свисают ниже. */
export const LOGOTYPE_BASELINE = 98.07;

/**
 * АЛФАВИТ ЛОГОТИПА. Пять букв, и все пять обведены: других у рисунка нет, и
 * достраивать их незачем, потому что имя фирмы короче не бывает и длиннее
 * тоже.
 */
type Glyph = {
  /** Контур в системе логотипа, от левого края своей краски. */
  d: string;
  /** Габарит по горизонтали, от левого края краски до правого. */
  w: number;
};

const G = { d: GL_G, w: 76.85 };

/**
 * Ключи алфавита это буквы ИМЕНИ, как оно пишется в тексте: «Legko». Третья
 * буква в тексте строчная «g», а в логотипе нарисована капительной «G»; обе
 * записи ведут к одной форме, чтобы ни одна из них не роняла набор.
 */
const ALPHABET: Readonly<Record<string, Glyph>> = {
  L: { d: GL_L, w: 77.66 },
  e: { d: GL_E, w: 79.68 },
  g: G,
  G,
  k: { d: GL_K, w: 84.09 },
  o: { d: GL_O, w: 86.89 },
};

/**
 * Просвет по умолчанию для пары, которой в оригинале нет. Взят как среднее
 * трёх настоящих просветов между рамками («Le», «eG», «Gk»): 4.76 единицы.
 * Пара «ko» в оригинале НАЛЕЗАЕТ рамками (ветвь «k» заходит над овалом «o»),
 * и это тоже рисунок, поэтому места букв оригинала приходят готовыми, а не
 * правилом.
 */
export const LOGOTYPE_CLEARANCE = 4.76;

/** Слово оригинала и места его букв, снятые с растра вместе с контурами. */
const TRACED_WORD = 'Legko';
const TRACED_X = [0, 81.47, 165.97, 248.48, 330.19];

/**
 * ПРОСВЕТЫ ПАР ВЫВЕДЕНЫ, А НЕ ВПИСАНЫ: таблица считается из тех же
 * `TRACED_X`, которыми стоит слово оригинала. Разъехаться ей не с чем.
 */
const PAIR_GAP: Readonly<Record<string, number>> = Object.fromEntries(
  TRACED_X.slice(1).map((x, i) => [
    TRACED_WORD.slice(i, i + 2),
    x - TRACED_X[i] - ALPHABET[TRACED_WORD[i]].w,
  ])
);

export type SetGlyph = {
  d: string;
  /** Место буквы в слове, готовым атрибутом. */
  transform: string;
};

/**
 * НАБИРАЕТ СЛОВО ЛОГОТИПОМ. Отдаёт формы с местами и общий габарит.
 *
 * Регистр НЕ меняется: логотип набран смешанным регистром, «L» прописная,
 * «G» капитель, остальные строчные, и `toUpperCase` сломал бы само имя.
 * Буквы вне алфавита не подставляются молча: набор падает громко, и промах
 * виден на первом же обновлении страницы.
 *
 * `track` это РАЗРЯДКА сверх положенного просвета; она прибавляется к
 * парному просвету, а не заменяет его. Зачем она вообще нужна, разобрано у
 * `logotypeBlock`.
 */
export function setLogotype(word: string, track = 0): { glyphs: SetGlyph[]; width: number } {
  const glyphs: SetGlyph[] = [];
  let x = 0;

  for (let i = 0; i < word.length; i++) {
    const ch = word[i];
    const g = ALPHABET[ch];
    if (!g) throw new Error(`В логотипе нет буквы «${ch}»: слово «${word}» набрать нечем.`);

    const prev = word[i - 1];
    if (prev) x += ALPHABET[prev].w + (PAIR_GAP[prev + ch] ?? LOGOTYPE_CLEARANCE) + track;

    glyphs.push({ d: g.d, transform: `translate(${x.toFixed(3)} 0)` });
  }

  const last = ALPHABET[word[word.length - 1]];
  return { glyphs, width: x + (last ? last.w : 0) };
}

const TRACED_SET = setLogotype(TRACED_WORD);

export const LOGOTYPE_GLYPHS = TRACED_SET.glyphs;
