/**
 * Ширина «А». Стоит тут, а не у мазка ниже, потому что это метрика буквы:
 * от неё считается и место в слове, и масштаб галочки.
 */
export const LOGOTYPE_A_WIDTH = 98.594;

/**
 * АЛФАВИТ ЛОГОТИПА. Четыре буквы обведены с оригинала, пять построены, и
 * различие это не оформительское: обведённое правится только новым обмером
 * растра, построенное правится тремя величинами выше.
 */
type Glyph = {
  /** Контур в системе логотипа: прописная 100, y=0 верх, y=100 линия шрифта. */
  d: string;
  /** Габарит по горизонтали, от левого края краски до правого. */
  w: number;
  /** Печатается перевёрнутой через линию шрифта. Только «Р». */
  flip?: true;
};

const ALPHABET: Readonly<Record<string, Glyph>> = {
  А: { d: A, w: LOGOTYPE_A_WIDTH },
  Л: { d: L, w: 91.33 },
  Ь: { d: SOFT, w: 68.6 },
  Ф: { d: F, w: 106.71 },
  Р: { d: SOFT, w: 68.6, flip: true },
  П: { d: P, w: W_P },
  И: { d: I, w: W_I },
  Н: { d: N, w: W_N },
  Т: { d: T, w: W_T },
};

/**
 * НАБОР ПЛОТНЕЕ ОРИГИНАЛА, и это единственное отступление от него во всём
 * слове.
 *
 * СЧИТАЕТСЯ ПО ПРОСВЕТУ, А НЕ ПО РАМКАМ. Первая редакция сдвигала буквы на
 * одну и ту же величину и тем сохраняла рисунок оригинала — вместе с его
 * бедой: междубуквия там разные, и по рамкам этого не видно. Ниже стоят
 * НАСТОЯЩИЕ просветы, наименьшее расстояние между соседними буквами, снятое
 * построчно с исходника: у «А»—«Л» это 16,1 у самой линии шрифта, где ноги
 * сходятся, у «Ф»—«А» 28,2 на середине роста, где круг стоит против
 * диагонали. Разница почти вдвое, и на плотном наборе она читается как
 * провал в конце слова.
 *
 * Поэтому каждая пара поджимается на своё: из просвета вычитается столько,
 * чтобы у ВСЕХ ЧЕТЫРЁХ пар остался один и тот же `LOGOTYPE_CLEARANCE`.
 * Слово выходит и теснее, и ровнее, а число остаётся одно.
 *
 * Шесть с половиной сотых прописной это предел, за которым уже не просвет:
 * на 5 «Ь» и «Ф» начинают слипаться на глаз, хотя касания ещё нет.
 */
const PAIR_CLEARANCE = [16.08, 24.37, 21.32, 28.25] as const;
export const LOGOTYPE_CLEARANCE = 6.5;

const SHIFT = PAIR_CLEARANCE.reduce<number[]>(
  (a, c) => [...a, a[a.length - 1] + (c - LOGOTYPE_CLEARANCE)],
  [0]
);

/** Слово оригинала и места его букв: сюда сходится весь обмер выше. */
const TRACED_WORD = 'АЛЬФА';
const TRACED_X = [0, 113.042, 227.872, 315.696, 433.621].map((x, i) => x - SHIFT[i]);

/**
 * ЗАКОН НАБОРА ОДИН НА ВСЕ ДЕВЯТЬ БУКВ: между соседними остаётся
 * `LOGOTYPE_CLEARANCE` краски, и меряется он построчно, а не по рамкам.
 *
 * У пар «ПРИНТА» это одно и то же: с обеих сторон стоят прямые стойки, и
 * построчный просвет равен просвету между рамками. У пар оригинала он другой
 * у каждой, потому что там сходятся то две диагонали, то круг с диагональю,
 * и рамки при этом могут даже налезать друг на друга («Ф» и «А» налезают на
 * 10.5, а краски между ними всё те же 6.5). Поэтому четыре пары оригинала
 * приходят сюда готовыми местами, а не правилом.
 *
 * ВЫВЕДЕНО, А НЕ ВПИСАНО: таблица считается из тех же `TRACED_X`, которыми
 * набран вылет §08. Разъехаться ей не с чем.
 */
const PAIR_GAP: Readonly<Record<string, number>> = Object.fromEntries(
  TRACED_X.slice(1).map((x, i) => [
    TRACED_WORD.slice(i, i + 2),
    x - TRACED_X[i] - ALPHABET[TRACED_WORD[i]].w,
  ])
);

export type SetGlyph = {
  d: string;
  /** Место буквы в слове, готовым атрибутом: «Р» приходит ещё и перевёрнутой. */
  transform: string;
};

/**
 * НАБИРАЕТ СЛОВО ЛОГОТИПОМ. Отдаёт формы с местами и общий габарит.
 *
 * Буквы вне алфавита логотипа не набираются молча: их там нет и подставить
 * нечего, поэтому набор падает громко. Строки на лист приходят из `site.ts`,
 * то есть промах виден на первом же обновлении страницы, а не в макете.
 *
 * `track` это РАЗРЯДКА, лишняя краска между соседями сверх того, что им
 * положено по закону набора. Она ПРИБАВЛЯЕТСЯ к парному просвету, а не заменяет
 * его: разные места оригинала обязаны оставаться разными и в разрядке. Зачем она
 * вообще нужна, разобрано у `logotypeBlock`.
 */
export function setLogotype(word: string, track = 0): { glyphs: SetGlyph[]; width: number } {
  const glyphs: SetGlyph[] = [];
  let x = 0;

  for (let i = 0; i < word.length; i++) {
    const ch = word[i];
    const g = ALPHABET[ch];
    if (!g) throw new Error(`В логотипе нет буквы «${ch}»: слово «${word}» набрать нечем.`);

    const prev = word[i - 1];
    if (prev) x += ALPHABET[prev].w + (PAIR_GAP[prev + ch] ?? LOGOTYPE_CLEARANCE) + track;

    glyphs.push({
      d: g.d,
      transform: g.flip
        ? `translate(${x.toFixed(3)} ${LOGOTYPE_CAP}) scale(1 -1)`
        : `translate(${x.toFixed(3)} 0)`,
    });
  }

  const last = ALPHABET[word[word.length - 1]];
  return { glyphs, width: x + (last ? last.w : 0) };
}

const TRACED_SET = setLogotype(TRACED_WORD);

export const LOGOTYPE_GLYPHS = TRACED_SET.glyphs;
