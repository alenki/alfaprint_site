import { cn } from '@/lib/cn';

/**
 * ПРИВОДОЧНЫЙ ШИЛЬД: метка печатника, вставленная прямо в строку набора.
 *
 * На контрольном поле оттиска печатают такую же мишень: чёрный крест это форма
 * K, рубиновая точка это форма R. Если краски сошлись, точка стоит ровно в
 * перекрестье. Если разошлись, она выходит на штрих, и это видно с одного
 * взгляда, без линейки.
 *
 * Здесь шильд стоит в конце первой фразы заявления и живёт по одному закону,
 * наводке: точка сползает с креста в сторону курсора ровно на --reg-throw и
 * ни на волос дальше, где бы курсор ни стоял, хоть двумя разделами ниже.
 * Мышь не двигали или увели за край окна: точка садится в приводку.
 *
 * РАЗГОН ПРОКРУТКИ НА ШИЛЬД НЕ ДЕЙСТВУЕТ. Общий --miss правит всеми прочими
 * формами листа, но не этой: прибор обязан показывать одно и то же и на ходу,
 * и на остановленной машине, иначе по нему нечего проверять. Отсюда же нет и
 * усиления: --gain здесь нечего усиливать.
 *
 * Считает наводку тот же единственный rAF-цикл, что и всё остальное на этом
 * листе, поэтому здесь по-прежнему ни своей анимации, ни своего JS: только
 * data-register-mark, за который цикл шильд и находит.
 *
 * ГРУНТА У ШИЛЬДА НЕТ. Плашка цветопробы делала из метки карточку, наклеенную
 * на лист, белый квадрат посреди бумаги. Мишень печатают НА листе, а не
 * поверх него, поэтому короб прозрачен и берёт грунт секции, каким бы он ни
 * был. Скруглений и теней на этом сайте не бывает.
 */
export function RegisterPatch({ className }: { className?: string }) {
  return (
    <span
      aria-hidden
      // Метка для единственного rAF-цикла: по ней он находит шильд. Ничего,
      // кроме адреса, этот атрибут не значит.
      data-register-mark
      className={cn(
        // Кегль наследуется от строки: шильд всегда одной высоты с очком
        // литеры, на любом формате и при любом clamp().
        'relative inline-block h-[0.7em] w-[0.7em] shrink-0 select-none align-baseline',
        className
      )}
    >
      <svg viewBox="0 0 40 40" className="absolute inset-0 h-full w-full overflow-visible" fill="none">
        {/* Форма K это крест. Стоит намертво. */}
        <g stroke="var(--color-ink)" strokeWidth="2.6" strokeLinecap="butt">
          <path d="M0 20 H12 M28 20 H40 M20 0 V12 M20 28 V40" />
        </g>

        {/* Форма R это точка в перекрестье. Единственная краска. */}
        <circle className="plate-r" cx="20" cy="20" r="6" fill="var(--color-rubine)" />
      </svg>
    </span>
  );
}
