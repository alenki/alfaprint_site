import {
  BLOCKS,
  PLAN_DOOR,
  PLAN_PER_M,
  PLAN_ROUTE,
  PLAN_STREET_LABEL,
  PLAN_TURN,
  PLAN_VIEWBOX,
  ROADS_A,
  ROADS_C,
  ROADS_D,
} from '@/content/plan';
import { K_PLAN } from '@/content/kontakty';

/**
 * ПЛЁНКА ПОДХОДА.
 *
 * Печатная плёнка, а не карта: ни тайла, ни чужого скрипта, ни единого
 * запроса наружу. Но в отличие от плёнки города в §08 главной, ЗДЕСЬ НАРИСОВАН
 * НАСТОЯЩИЙ КВАРТАЛ. Каждая линия снята с OpenStreetMap и спроецирована на
 * сборке, см. `content/plan.ts`; точка двери подтверждена карточкой агентства
 * на Яндекс.Картах и контуром дома 4 в OSM, и два источника сошлись.
 *
 * ДВЕ ФОРМЫ И ЗДЕСЬ. Форма K печатает город: улицы тремя рангами и контуры
 * домов. Форма R печатает ОДНУ линию, путь от улицы Толстого по Кузнечному
 * переулку до двери, поверх той же линии формы K, и две точки на её концах.
 * Весь смысл плёнки в этих двух красках: мел это то, что есть у всех, синее
 * это то, что нужно вам. Синяя здесь светлая, `--accent` тёмного грунта
 * (3,20:1 к тёмно-синему): синяя с логотипа по нему не читается вовсе.
 *
 * НИ ОДНОЙ СТРОКИ JS, и это требование, а не вкус. Прецедент записан при
 * `CityFilm`: ход прорисовки стоял на whileInView, на iPhone наблюдатель не
 * срабатывал, и от карты оставались одни подписи. Здесь появляться нечему:
 * плёнка нарисована сразу и целиком, а единственное движение (кольцо и
 * строка «Открыть в Яндекс.Картах») живёт на :hover, то есть в CSS.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ТРИ КАДРА ОДНОЙ ПЛЁНКИ, И НИ ОДИН НЕ СЖАТ, ВСЕ ОБРЕЗАНЫ
 * ═══════════════════════════════════════════════════════════════════════════
 * Лежачий кадр 1200 x 540 на телефоне даёт полосу в полторы сотни пунктов
 * высоты: улицу в ней видно, а куда идти, уже нет. Сжимать карту нельзя,
 * карту можно только кадрировать, и `preserveAspectRatio="slice"` кадрирует
 * её сам: узкая мера получает стоячий кадр 4:5, внутри которого видна
 * средняя вертикальная полоса того же рисунка шириной 432 единицы, то есть
 * 135 метров, а промежуточная мера кадр 3:2 на 810 единиц (253 метра).
 * Отношения и границы между ними считает CSS листа, здесь только рисунок.
 *
 * ВЕСЬ СИНИЙ ПУТЬ ЦЕЛИКОМ СТОИТ ВО ВСЕХ ТРЁХ ОКНАХ, и это требование к
 * кадру, а не счастливое совпадение. Путь занимает по ширине 421…732, то
 * есть 311 единиц, и самое узкое окно (384…816) держит его с запасом в обе
 * стороны. Никакое кадрирование не имеет права отрезать у пути конец:
 * дорога, уходящая за рез, читается продолжением, а ПУТЬ, уходящий за рез,
 * читается потерей цели.
 *
 * ПОДПИСИ ЗНАЮТ ПРО ОБРЕЗКУ. Они стоят снаружи вьюбокса (кегль внутри него
 * считается в единицах рисунка и уезжал бы вместе с ним), а место берут
 * вычислением из четырёх чисел видимого окна: `--vx --vy --vw --vh` на самой
 * рамке. Сменился кадр, сменились четыре числа, и все подписи переехали
 * сами. Второй правды о координатах при этом не заводится: каждая подпись
 * по-прежнему знает про себя только `--x` и `--y` в единицах рисунка.
 *
 * ЛИНЕЙКА И СЕВЕР ПРИ КАЖДОМ КАДРЕ СВОИ, потому что они стоят В ПОЛЕ
 * рисунка, а поле у кадров разное: сто метров в стоячий кадр не влезают
 * вместе с путём, и мерная линейка обязана быть короче. Это тот редкий
 * случай, когда две записи честнее одной: линейка, наполовину ушедшая за
 * обрез, врёт про масштаб.
 */

const { w: W, h: H } = PLAN_VIEWBOX;

/** Сто метров теми же единицами, которыми нарисованы улицы. */
const M100 = 100 * PLAN_PER_M;
const M50 = 50 * PLAN_PER_M;

/** Рост стрелки севера в единицах рисунка: остриё и стойка вместе. */
const NORTH_H = 64;

/**
 * Мерная линейка и север, по набору на кадр.
 *
 * ЛЕЖАЧИЙ КАДР держит их по углам левого края, как у карты: север в левом
 * верхнем, линейка в левом нижнем. Правее им места нет: через всё поле
 * наискось идёт Толстого, в середине стоит путь, а справа кадр занимают
 * большие корпуса, и линейка, положенная на заливку дома, читалась бы его
 * стеной. У левого края линейка пересекает одну тропу и одну стену, обе
 * поперёк, а не вдоль: поперёк волосяной линии читается пересечением, вдоль
 * неё сливается.
 *
 * СТОЯЧИЙ КАДР (384…816) ДЕРЖИТ ИХ ГРУППОЙ, ЛЕВЕЕ ПЕРЕУЛКА, и это не
 * прихоть, а единственное чистое место. Низ окна занят Толстого и домами за
 * ней, верх корпусами над переулком; слева от переулка, между ними, стоит
 * пустое поле, и линейка на пятьдесят метров ложится в него, не задев ни
 * одной линии. Север стоит над серединой линейки: у левого края окна ему
 * мешает угол соседнего дома, и подпись «С» садилась прямо на его стену.
 * Оба места проверены по контурам на 320, 390, 559, 560 и 767 точках: ни
 * линейка, ни её подпись, ни стрелка не задевают ни стены, ни улицы, ни
 * пути, ни подписей «Вход» и «Поворот с Толстого».
 */
const LEGEND = {
  wide: { x: 22, len: M100, y: H - 30, label: K_PLAN.marks.scale, north: { x: 24, top: 36 } },
  narrow: { x: 404, len: M50, y: 228, label: K_PLAN.marks.scaleNarrow, north: { x: 484, top: 112 } },
} as const;

/** Ранги линий. Толщина в пикселях: штрих не масштабируется вместе с кадром. */
function Roads({ d, width, opacity }: { d: readonly string[]; width: number; opacity: number }) {
  return (
    <g
      stroke="currentColor"
      strokeWidth={width}
      opacity={opacity}
      fill="none"
      strokeLinecap="round"
      strokeLinejoin="round"
    >
      {d.map((path, i) => (
        <path key={i} d={path} vectorEffect="non-scaling-stroke" />
      ))}
    </g>
  );
}

/** Линейка и север одного кадра. Обе метки печатника, обе волосяные. */
function Legend({
  x,
  len,
  y,
  north,
  className,
}: {
  x: number;
  len: number;
  y: number;
  north: { x: number; top: number };
  className: string;
}) {
  return (
    <g className={className} opacity="0.7">
      <g stroke="currentColor" strokeWidth="1" fill="none">
        <path d={`M${x} ${y}H${x + len}`} vectorEffect="non-scaling-stroke" />
        <path
          d={`M${x} ${y - 7}v14M${x + len} ${y - 7}v14`}
          vectorEffect="non-scaling-stroke"
        />
        <path
          d={`M${north.x} ${north.top + NORTH_H}V${north.top + 12}`}
          vectorEffect="non-scaling-stroke"
        />
      </g>
      <path d={`M${north.x} ${north.top}l6 14h-12z`} fill="currentColor" stroke="none" />
    </g>
  );
}

/** Подпись на плёнке: место берётся вычислением из видимого окна кадра. */
function Mark({
  x,
  y,
  angle,
  className,
  children,
}: {
  x: number;
  y: number;
  angle?: number;
  className?: string;
  children: React.ReactNode;
}) {
  return (
    <span
      className={`cp-mark t-micro ${className ?? ''}`}
      style={{
        ['--x' as string]: String(x),
        ['--y' as string]: String(y),
        ...(angle === undefined ? null : { ['--cp-angle' as string]: `${angle}deg` }),
      }}
    >
      {children}
    </span>
  );
}

export function CityPlan() {
  return (
    <a
      href={K_PLAN.mapsHref}
      target="_blank"
      rel="noreferrer"
      className="cp"
      aria-label={`${K_PLAN.mapsLink}: Нальчик, Кузнечный переулок, 4`}
    >
      <span className="cp-frame">
        <svg
          viewBox={`0 0 ${W} ${H}`}
          preserveAspectRatio="xMidYMid slice"
          className="cp-film"
          aria-hidden
          fill="none"
        >
          {/* КВАРТАЛЫ, И ЗАЛИВКА У НИХ ВИДНАЯ, А НЕ СИМВОЛИЧЕСКАЯ.
              При одной обводке дом и двор отличаются только линией, и
              любой дом из нескольких колец читается несколькими домами,
              налезшими друг на друга, а пустой двор между ними выглядит
              точно так же, как сами дома. Заливка отвечает за то, чтобы дом
              стал плоскостью, а двор дыркой в ней.

              Заливка вытащена из-под общей непрозрачности и задана краской
              сама: обводка идёт мелом в 36 %, а внутренность дома в 9 %.
              Этого хватает, чтобы дом читался плоскостью, и мало, чтобы он
              полез вперёд: он по-прежнему фон, по которому читается путь. */}
          <g
            stroke="color-mix(in srgb, currentColor 36%, transparent)"
            strokeWidth="1"
            fill="color-mix(in srgb, currentColor 9%, transparent)"
          >
            {BLOCKS.map((d, i) => (
              <path key={i} d={d} vectorEffect="non-scaling-stroke" />
            ))}
          </g>

          {/* Три ранга дорог, от тропы к улице с именем. Четвёртого нет:
              см. `content/plan.ts`, в кадр не попало ни одной его линии. */}
          <Roads d={ROADS_D} width={1} opacity={0.22} />
          <Roads d={ROADS_C} width={1} opacity={0.52} />
          <Roads d={ROADS_A} width={2.4} opacity={0.92} />

          {/* ФОРМА R. Единственная синяя линия плёнки, и лежит она поверх
              своей же линии формы K: переулок напечатан обеими формами.
              Краска берётся из `--accent`, то есть от грунта: на тёмно-синем
              это светлая синяя, и отдельной записи цвета здесь нет. */}
          <path
            d={PLAN_ROUTE}
            stroke="var(--accent)"
            strokeWidth="3"
            strokeLinecap="butt"
            strokeLinejoin="miter"
            vectorEffect="non-scaling-stroke"
          />

          {/* ДВА КОНЦА ОДНОГО ПУТИ, ОДНОЙ КРАСКОЙ И ОДНОГО РОСТА. Начало
              на улице, конец у двери, и обе метки одинаковы, потому что
              обе говорят одно и то же: остановись здесь. Разметить конец
              иначе значило бы заявить, что про дверь известно больше, чем
              про поворот.

              ПРИВОДОЧНОГО КРЕСТА ЗДЕСЬ НЕТ, и по двум причинам сразу.
              Механическая: его луч ходит на десятки единиц рисунка, а
              отбивка подписи считается в пикселях, и «Вход» садился прямо
              на луч, на узкой мере закрывая его целиком. Честная: крест это
              метка ПРИВОДКИ, то есть обещание попасть в микрон, а под ним
              стоит булавка карточки, а не порог двери. Точка обещает ровно
              столько, сколько знает.

              ОБЕ ТОЧКИ СЧИТАЮТСЯ В ПИКСЕЛЯХ, а не в единицах рисунка, и
              потому нарисованы штрихом нулевой длины с круглым концом:
              `h0` при `non-scaling-stroke` даёт круг ровно в толщину
              штриха при любом кадре. Залитый `circle` брал бы радиус из
              единиц и ехал бы вместе с кадром: на 768 пикселях точка
              выходила в три пикселя радиусом при той же подписи в
              тринадцать, то есть метка теряла вес как раз там, где
              рисунок и без того мельчает. Закон здесь общий с дорогами и
              записан при `Roads`: штрих не масштабируется вместе с
              кадром. */}
          <g
            stroke="var(--accent)"
            strokeWidth="10"
            strokeLinecap="round"
            fill="none"
            vectorEffect="non-scaling-stroke"
          >
            <path d={`M${PLAN_TURN.x} ${PLAN_TURN.y}h0`} vectorEffect="non-scaling-stroke" />
            <path d={`M${PLAN_DOOR.x} ${PLAN_DOOR.y}h0`} vectorEffect="non-scaling-stroke" />
          </g>

          {/* Кольцо приходит только под курсором, как у плёнки города. Его
              радиус остался В ЕДИНИЦАХ РИСУНКА, и это не недосмотр: точка
              это МЕТКА, она обязана читаться при любом кадре, а кольцо это
              жест под курсором, и обводит он место на местности: вход и
              тот отрезок переулка, с которого к нему сходят. 32 единицы это
              десять метров, а от переулка до двери их 6,6. */}
          <circle
            className="cp-ring"
            cx={PLAN_DOOR.x}
            cy={PLAN_DOOR.y}
            r="32"
            fill="none"
            stroke="var(--accent)"
            strokeWidth="1"
            vectorEffect="non-scaling-stroke"
          />

          <Legend {...LEGEND.wide} className="cp-wide" />
          <Legend {...LEGEND.narrow} className="cp-narrow" />
        </svg>

        {/* ── Подписи: набор, а не рисунок ───────────────────────────────── */}
        <Mark x={PLAN_DOOR.x} y={PLAN_DOOR.y} className="cp-mark-door">
          {K_PLAN.marks.door}
        </Mark>

        <Mark x={PLAN_TURN.x} y={PLAN_TURN.y} className="cp-mark-turn">
          {K_PLAN.marks.turn}
        </Mark>

        <Mark
          x={PLAN_STREET_LABEL.x}
          y={PLAN_STREET_LABEL.y}
          angle={PLAN_STREET_LABEL.angle}
          className="cp-mark-street cp-wide fg-56"
        >
          {K_PLAN.marks.street}
        </Mark>

        <Mark x={LEGEND.wide.x} y={LEGEND.wide.y - 13} className="cp-mark-scale cp-wide fg-56">
          {LEGEND.wide.label}
        </Mark>
        <Mark x={LEGEND.narrow.x} y={LEGEND.narrow.y - 13} className="cp-mark-scale cp-narrow fg-56">
          {LEGEND.narrow.label}
        </Mark>

        <Mark
          x={LEGEND.wide.north.x}
          y={LEGEND.wide.north.top}
          className="cp-mark-north cp-wide fg-56"
        >
          {K_PLAN.marks.north}
        </Mark>
        <Mark
          x={LEGEND.narrow.north.x}
          y={LEGEND.narrow.north.top}
          className="cp-mark-north cp-narrow fg-56"
        >
          {K_PLAN.marks.north}
        </Mark>
      </span>

      <span className="cp-foot">
        <span className="cp-cta t-micro">{K_PLAN.mapsLink} →</span>
      </span>
    </a>
  );
}
