/**
 * ПЛЁНКА ПОДХОДА.
 *
 * Печатная плёнка, а не карта: ни тайла, ни чужого скрипта, ни единого
 * запроса наружу. Но в отличие от плёнки города в §08 главной, ЗДЕСЬ НАРИСОВАН
 * НАСТОЯЩИЙ КВАРТАЛ. Каждая линия снята с OpenStreetMap и спроецирована на
 * сборке, см. `content/plan.ts`; точка цеха подтверждена карточкой фирмы на
 * Яндекс.Картах и геокодером OSM, и два источника сошлись.
 *
 * ДВЕ ФОРМЫ И ЗДЕСЬ. Форма K печатает город: улицы тремя рангами и контуры
 * домов. Форма R печатает ОДНУ линию, проезд во двор, поверх той же линии
 * чёрной формы, и две точки на её концах. Весь смысл плёнки в этих двух
 * красках: чёрное это то, что есть у всех, красное это то, что нужно вам.
 *
 * НИ ОДНОЙ СТРОКИ JS, и это требование, а не вкус. Прецедент записан при
 * `CityFilm`: ход прорисовки стоял на whileInView, на iPhone наблюдатель не
 * срабатывал, и от карты оставались одни подписи. Здесь появляться нечему:
 * плёнка нарисована сразу и целиком, а единственное движение (кольцо и
 * строка «Построить маршрут») живёт на :hover, то есть в CSS.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ТРИ КАДРА ОДНОЙ ПЛЁНКИ, И НИ ОДИН НЕ СЖАТ, ВСЕ ОБРЕЗАНЫ
 * ═══════════════════════════════════════════════════════════════════════════
 * Лежачий кадр 1200 x 540 на телефоне даёт полосу в полторы сотни пунктов
 * высоты: улицу в ней видно, а куда идти, уже нет. Сжимать карту нельзя,
 * карту можно только кадрировать, и `preserveAspectRatio="slice"` кадрирует
 * её сам: узкая мера получает стоячий кадр 4:5, внутри которого видна
 * средняя вертикальная полоса того же рисунка шириной 432 единицы, то есть
 * 94 метра, а промежуточная мера кадр 3:2 на 810 единиц. Отношения и
 * границы между ними считает CSS листа, здесь только рисунок.
 *
 * ВЕСЬ КРАСНЫЙ ПУТЬ ЦЕЛИКОМ СТОИТ ВО ВСЕХ ТРЁХ ОКНАХ, и это требование к
 * кадру, а не счастливое совпадение. Путь занимает по ширине 426.9…655.4,
 * то есть 229 единиц, и самое узкое окно (384…816) держит его с запасом в
 * обе стороны. Никакое кадрирование не имеет права отрезать у пути конец:
 * дорога, уходящая за рез, читается продолжением, а ПУТЬ, уходящий за рез,
 * читается потерей цели.
 *
 * ПОДПИСИ ЗНАЮТ ПРО ОБРЕЗКУ. Они стоят снаружи вьюбокса (кегль внутри него
 * считается в единицах рисунка и уезжал бы вместе с ним), а место берут
 * вычислением из четырёх чисел видимого окна: `--vx --vy --vw --vh` на самой
 * рамке. Сменился кадр, сменились четыре числа, и все подписи переехали
 * сами. Второй правды о координатах при этом не заводится: каждая подпись
 * по-прежнему знает про себя только `--x` и `--y` в единицах рисунка.
 *
 * ЛИНЕЙКА И СЕВЕР ПРИ КАЖДОМ КАДРЕ СВОИ, потому что они стоят В ПОЛЕ
 * рисунка, а поле у кадров разное: сто метров в стоячий кадр не влезают
 * (94 метра во всю ширину), и мерная линейка обязана быть короче. Это тот
 * редкий случай, когда две записи честнее одной: линейка, наполовину ушедшая
 * за обрез, врёт про масштаб.
 */

const { w: W, h: H } = PLAN_VIEWBOX;

/** Сто метров теми же единицами, которыми нарисованы улицы. */
const M100 = 100 * PLAN_PER_M;
const M50 = 50 * PLAN_PER_M;

/**
 * Мерная линейка и север, по набору на кадр.
 *
 * Лежачий кадр держит их в левой части поля: справа наискось идёт
 * Тарчокова, и линейка ложилась поперёк улицы, то есть читалась её частью.
 * Стоячий кадр ставит их внутри видимого окна (384…816), иначе они окажутся
 * за обрезом.
 *
 * ЛИНЕЙКА УШЛА СО СТЕНЫ ДОМА 29, И УШЛА ПО ДВУМ ОСЯМ. На высоте 500 она
 * ложилась ВДОЛЬ стены: у контура дома три звена подряд идут по высоте
 * 492…500, и семьдесят единиц линейки совпадали со стеной, так что стена
 * продолжала линейку до самого обреза. Линейка, продлённая чужой линией,
 * врёт про масштаб ровно так же, как линейка, ушедшая за обрез, и хуже
 * того, врёт незаметно.
 *
 * Отойти по одной оси не хватало. Опустить линейку мало: при начале в
 * 52-й единице стена упирается ей в левый конец и читается её
 * продолжением через зазор. Отойти вправо тоже мало: стена остаётся на
 * той же высоте и продолжает линейку на расстоянии. Поэтому линейка
 * отошла и вниз, и вправо, и оба числа посчитаны по контурам: 136 это
 * первая единица за концом стены (127), а 510 это десять единиц ниже
 * неё, то есть вдвое больше зазора, при котором звенья ещё сходятся
 * (сходятся до 505). Пересекать рисунок линейке при этом можно и нужно:
 * поперёк волосяной линии читается пересечением, вдоль неё сливается.
 */
const LEGEND = {
  wide: { x: 136, len: M100, y: H - 30, label: K_PLAN.marks.scale },
  narrow: { x: 404, len: M50, y: H - 30, label: K_PLAN.marks.scaleNarrow },
} as const;

/** Стрелка севера: остриё, стойка. У карты обязана быть сторона света. */
const NORTH = { top: 40, bottom: 104 } as const;

/** Ранги линий. Толщина в пикселях: штрих не масштабируется вместе с кадром. */
function Roads({ d, width, opacity }: { d: readonly string[]; width: number; opacity: number }) {
  return (
    <g
      stroke="currentColor"
      strokeWidth={width}
      opacity={opacity}
      fill="none"
      strokeLinecap="round"
      strokeLinejoin="round"
    >
      {d.map((path, i) => (
        <path key={i} d={path} vectorEffect="non-scaling-stroke" />
      ))}
    </g>
  );
}

/** Линейка и север одного кадра. Обе метки печатника, обе волосяные. */
function Legend({ x, len, y, className }: { x: number; len: number; y: number; className: string }) {
  return (
    <g className={className} opacity="0.7">
      <g stroke="currentColor" strokeWidth="1" fill="none">
        <path d={`M${x} ${y}H${x + len}`} vectorEffect="non-scaling-stroke" />
        <path
          d={`M${x} ${y - 7}v14M${x + len} ${y - 7}v14`}
          vectorEffect="non-scaling-stroke"
        />
        <path
          d={`M${x + 2} ${NORTH.bottom}V${NORTH.top + 12}`}
          vectorEffect="non-scaling-stroke"
        />
      </g>
      <path d={`M${x + 2} ${NORTH.top}l6 14h-12z`} fill="currentColor" stroke="none" />
    </g>
  );
}

/** Подпись на плёнке: место берётся вычислением из видимого окна кадра. */
function Mark({
  x,
  y,
  angle,
  className,
  children,
}: {
  x: number;
  y: number;
  angle?: number;
  className?: string;
  children: React.ReactNode;
}) {
  return (
    <span
      className={`cp-mark t-micro ${className ?? ''}`}
      style={{
        ['--x' as string]: String(x),
        ['--y' as string]: String(y),
        ...(angle === undefined ? null : { ['--cp-angle' as string]: `${angle}deg` }),
      }}
    >
      {children}
    </span>
  );
}

