'use client';

import { useEffect, useRef, useState } from 'react';
import { motion } from 'motion/react';
import { ROUTE, type Frame } from '@/content/route';
import { asset } from '@/lib/base';

/**
 * ПРОГОН: ПЯТЬ КАДРОВ ОДНОЙ ПОЛОСОЙ ОТ РЕЗА ДО РЕЗА.
 *
 * Полоса идёт край в край и никогда не меняет ни ширины, ни высоты. Открытый
 * кадр занимает половину формата, остальные четыре делят вторую половину
 * поровну; открывается другой, и доли переезжают ВНУТРИ той же полосы. Это
 * тот же инвариант, на котором стоит гармошка §03: панель раскрывается, а
 * высота раздела не двигается ни на пиксель. Раздел с фотографиями обязан
 * держать его строже всех: тут под гармошкой лежит ещё половина листа.
 *
 * ОТКРЫТЫЙ КАДР ПЕЧАТАЕТСЯ ЦЕЛИКОМ, И ЭТО СЧИТАНО, А НЕ ПОДОБРАНО. Половина
 * формата при высоте 37,5 vw даёт ровно 4:3, а 4:3 и есть пропорция снимка
 * (1200 × 903). Замерено: с 800 до 2180 пикселей окна открытый кадр держит
 * 1,32:1, то есть свой кадр без обрезки. Упоры нужны только по краям
 * диапазона: ниже 300 полоса перестала бы быть полосой, выше 820 она съела
 * бы экран целиком, и там снимок теряет небо. Обрезаются поэтому только
 * закрытые кадры, и обрезаются они так и должны: узкая вертикаль на светлом
 * столе это и есть плёнка, отложенная в сторону. Номер на ней стоит затем,
 * чтобы её всё равно можно было назвать.
 *
 * ПОЛОСА НЕ ХОДИТ САМА. Прежде она, войдя в экран, один раз прокручивала
 * путь от ориентира до двери; этот прогон снят. Раздел открывается сразу на
 * двери, то есть на том кадре, за которым сюда и пришли, и дальше не
 * двигается, пока его не двинет читатель. Движение здесь было подсказкой
 * «наведите курсор», а подсказка, которую нельзя не смотреть, дороже того,
 * что она объясняет.
 *
 * НАВЕДЕНИЕ ПЕРЕСАЖИВАЕТ, и уведённый курсор ничего не возвращает обратно:
 * где читателя оставили, там кадр и стоит. Тот же закон, что у ленты знаков
 * в §01.
 *
 * НА УЗКОЙ МЕРЕ ГАРМОШКИ НЕТ ВОВСЕ. Пять долек на 390 пикселях это пять
 * полосок по сорок, то есть ничего. Там полоса становится лентой с
 * прилипанием: один кадр на свайп, своя подпись под каждым, и ни одного
 * состояния, которое надо было бы держать в голове, стоя на Тарчокова с
 * телефоном в руке.
 *
 * ЛЕНТА ОБЯЗАНА БЫТЬ ЗАГРУЖЕНА ЦЕЛИКОМ РАНЬШЕ, ЧЕМ ПО НЕЙ ПРОВЕДУТ ПАЛЬЦЕМ,
 * и это не роскошь. Ленивая загрузка считает кадр, уехавший вправо за край
 * экрана, невидимым: замерено на 390 × 844, к разделу приезжают четыре
 * снимка из пяти, и ПЯТЫЙ, то есть сама дверь, догружается уже под пальцем.
 * Поэтому вошедшая в экран лента переводит свои снимки на `eager` разом
 * (`warm`): дальше свайп идёт по готовым кадрам, и белых прямоугольников на
 * ходу не остаётся ни одного.
 *
 * ГРЕЕТСЯ ТОЛЬКО ЛЕНТА И ТОЛЬКО НА УЗКОЙ МЕРЕ. На настольном она
 * `display: none`, но `eager` грузит и скрытое, а ряд `sizes` у неё другой:
 * поленившись проверить ширину, мы скачали бы весь маршрут вторым
 * комплектом файлов.
 */

/** Во сколько раз открытый кадр шире закрытого. Четыре дают ровно половину. */
const OPEN = 4;

/** Ход доли: полоса переливается, а не перещёлкивается. */
const SEAT_MS = 520;

/** Длина пути. Печатается с нулём, как и номера кадров. */
const TOTAL = ROUTE.length.toString().padStart(2, '0');

export function RouteRun() {
  /** Открыта дверь: она и есть то, за чем в этот раздел приходят. */
  const [open, setOpen] = useState(ROUTE.length - 1);
  /** Лента на телефоне догружена вперёд и больше не ленится. */
  const [warm, setWarm] = useState(false);
  const hostRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const host = hostRef.current;
    if (!host) return;

    const io = new IntersectionObserver(
      (entries) => {
        if (!entries.some((e) => e.isIntersecting)) return;
        io.disconnect();

        /* МЕДИАЗАПРОС СПРАШИВАЕТСЯ ЗДЕСЬ, А НЕ ХУКОМ НАВЕРХУ. `useMediaQuery`
           честно отдаёт false на первом рендере, иначе разъехалась бы
           гидратация, и наблюдатель, заведённый в том же коммите, прочитал бы
           эту ложь: настольный лист ушёл бы греть ленту, которой у него нет.
           В обработчике события врать нечему, там окно уже настоящее. */
        if (!window.matchMedia('(width >= 768px)').matches) setWarm(true);
      },
      { threshold: 0.35 }
    );

    io.observe(host);
    return () => io.disconnect();
  }, []);

  const active = ROUTE[open] ?? ROUTE[0];

  return (
    <div ref={hostRef}>
      {/* ── Настольная гармошка ────────────────────────────────────────── */}
      <div
        className="hidden h-[clamp(300px,37.5vw,820px)] w-full md:flex"
        role="group"
        aria-label="Маршрут до входа: пять кадров"
      >
        {ROUTE.map((frame, i) => (
          <Pane
            key={frame.n}
            frame={frame}
            open={i === open}
            onSeat={() => setOpen(i)}
            /* Закрытая долька это узкая вертикаль, открытая половина формата:
               одному элементу приходится обслуживать оба, и большего из двух
               довольно. */
            sizes="(width < 768px) 0px, 50vw"
          />
        ))}
      </div>

      {/* ── Подписная планка ─────────────────────────────────────────────
          Единственная линейка раздела. Слева шаг, справа место в пути:
          номер, уже стоящий на самом кадре, здесь становится счётом, и
          читателю не приходится пересчитывать дольки глазами. */}
      <div className="rule-t hidden items-baseline justify-between gap-[clamp(12px,1.6vw,40px)] px-[var(--edge)] py-[clamp(9px,0.8vw,16px)] md:flex">
        <motion.p
          key={active.n}
          className="t-micro fg"
          initial={{ opacity: 0 }}
          animate={{ opacity: 1 }}
          transition={{ duration: 0.22, ease: 'linear' }}
        >
          {active.n} · {active.title}
        </motion.p>
        <p className="t-micro fg-56 shrink-0 tabular-nums">
          {active.n} / {ROUTE.length.toString().padStart(2, '0')}
        </p>
      </div>

      {/* ── Узкая мера: лента с прилипанием ──────────────────────────────
          Ни гармошки, ни состояния: кадры просто идут подряд и листаются
          пальцем. Последний край уходит в вылет, и это же показывает, что
          лента длиннее экрана.

          ОДИН МАХ ПАЛЬЦЕМ ЭТО РОВНО ОДИН ШАГ ПУТИ (`snap-always`). Без
          упора беглый мах перелистывал через два кадра и через три: для
          карусели с картинками это пустяк, а здесь пропущенный кадр это
          пропущенный поворот.

          ПОЛОСЫ ПРОКРУТКИ У ЛЕНТЫ НЕТ. Служебный ползунок поперёк снимков
          это единственная деталь интерфейса, которая на этом листе вообще
          нигде не показана, и показывать её незачем: о том, что лента
          длиннее экрана, говорит выглядывающий справа следующий кадр, а
          счёт на плашке говорит, сколько их всего. Прятать приходится
          двумя записями, старой вебкитовской и нынешней: Safari до сих пор
          знает только первую. */}
      <ul className="flex snap-x snap-mandatory overflow-x-auto overscroll-x-contain px-[var(--edge)] scroll-px-[var(--edge)] [scrollbar-width:none] [&::-webkit-scrollbar]:hidden md:hidden">
        {ROUTE.map((frame) => (
          <li
            key={frame.n}
            className="rule-r w-[78vw] shrink-0 snap-start snap-always last:border-r-0"
          >
            <figure>
              <div className="relative aspect-[4/3] overflow-hidden">
                {/* Счёт стоит НА ПЛАШКЕ, а не в подписи. Подписной планки
                    на всю ленту тут нет, каждый кадр отвечает за себя, и
                    длину пути ему приходится называть самому: пальцем её не
                    видно, а знать, что дверь пятая, надо до того, как начал
                    листать. В подписи же счёт съедал полста пунктов из
                    двухсот девяноста, и «РЕСТОРАН HISTORY» обрывался на
                    «HISTO…»: обрезать в этом разделе можно что угодно, кроме
                    имени ориентира. */}
                <Plate n={frame.n} of={TOTAL} open />
                <Shot frame={frame} sizes="78vw" eager={warm} />
              </div>
              {/* Номера в подписи нет: он стоит на плашке в двадцати знаках
                  отсюда, и повторённый занял бы единственную строку. */}
              <figcaption className="rule-t t-micro fg truncate px-[clamp(8px,2vw,14px)] py-2.5">
                {frame.title}
              </figcaption>
            </figure>
          </li>
        ))}
      </ul>
    </div>
  );
}

/**
 * ОДНА ДОЛЬКА ПОЛОСЫ.
 *
 * Кнопка, а не ссылка и не картинка с обработчиком: она меняет состояние
 * этой же полосы и никуда не ведёт. Садится кадр от наведения, от фокуса и
 * от нажатия одинаково, поэтому путь проходится и клавиатурой: Tab идёт по
 * шагам маршрута в том же порядке, в каком по нему идут ногами.
 *
 * ИМЯ КНОПКИ НЕСЁТ ОПИСАНИЕ СНИМКА, а у самого снимка alt пустой. Иначе
 * описание пришлось бы читать дважды: один раз как имя кнопки, второй как
 * содержимое. Ничего при этом не теряется: описание у всех пяти кадров
 * стоит в разметке всегда, открыт кадр или нет.
 */
function Pane({
  frame,
  open,
  onSeat,
  sizes,
}: {
  frame: Frame;
  open: boolean;
  onSeat: () => void;
  sizes: string;
}) {
  return (
    <button
      type="button"
      aria-pressed={open}
      aria-label={`Кадр ${frame.n} из ${ROUTE.length}. ${frame.alt}`}
      onMouseEnter={onSeat}
      onFocus={onSeat}
      onClick={onSeat}
      className="relative block h-full min-w-0 cursor-pointer overflow-hidden border-r border-[var(--rule)] last:border-r-0"
      style={{
        flex: `${open ? OPEN : 1} 1 0%`,
        transition: `flex-grow ${SEAT_MS}ms var(--ease-blade)`,
      }}
    >
      <Plate n={frame.n} open={open} />
      <Shot frame={frame} sizes={sizes} />
    </button>
  );
}

/**
 * СНИМОК В ТРЁХ НАБОРАХ И НИ В ОДНОМ БОЛЬШЕ ТЫСЯЧИ ТОЧЕК: дальше это уже
 * не карта, а разглядывание, и на эту работу его никто не звал.
 *
 * СРЕДНИЙ НАБОР ЗАВЕДЁН ПОД ТЕЛЕФОН, и заведён по замеру. Кадр занимает у
 * ленты 78 vw, на 390 пикселях это 304 точки вёрстки; экран у телефона
 * двойной плотности, то есть просит 608 настоящих, и между 560 и 1000
 * браузер честно берёт тысячу. Весь маршрут выходил тогда в 426 КБ по
 * мобильной сети ради снимка забора. Набор в 720 закрывает эту дыру: тот же
 * телефон берёт 242 КБ, а настольный лист на 1440 без плотности берёт их же
 * вместо прежних 426.
 */
function Shot({ frame, sizes, eager }: { frame: Frame; sizes: string; eager?: boolean }) {
  const url = (suffix: string) => asset(`/route/${frame.n}${suffix}.webp`);

  return (
    // eslint-disable-next-line @next/next/no-img-element
    <img
      src={url('')}
      srcSet={`${url('-560')} 560w, ${url('-720')} 720w, ${url('')} 1000w`}
      sizes={sizes}
      alt=""
      width={1000}
      height={753}
      loading={eager ? 'eager' : 'lazy'}
      decoding="async"
      className="absolute inset-0 h-full w-full object-cover"
      style={{ objectPosition: frame.focus ?? 'center' }}
    />
  );
}

/**
 * НОМЕР КАДРА.
 *
 * Плашка вырублена в углу снимка, и краску она меняет вместе с состоянием:
 * закрытый кадр держит форму K, открытый форму R. Это единственная хрома
 * во всей полосе, и работу она делает ровно одну: говорит, где читатель
 * сейчас стоит.
 *
 * ЗНАМЕНАТЕЛЬ ПРИХОДИТ ТОЛЬКО НА ЛЕНТЕ. В гармошке длину пути называет
 * подписная планка внизу, одна на все пять кадров; на ленте такой планки
 * нет, и счёт некуда девать, кроме как на сам кадр.
 */
function Plate({ n, of, open }: { n: string; of?: string; open: boolean }) {
  return (
    <span
      aria-hidden
      className="t-micro absolute left-0 top-0 z-1 px-[clamp(7px,0.62vw,13px)] py-[clamp(5px,0.44vw,9px)] leading-none tabular-nums"
      style={{
        backgroundColor: open ? 'var(--color-rubine)' : 'var(--color-ink)',
        color: 'var(--color-chalk)',
        transition: 'background-color 260ms var(--ease-ink)',
      }}
    >
      {of ? `${n}/${of}` : n}
    </span>
  );
}
