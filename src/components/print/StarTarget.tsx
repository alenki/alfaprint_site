import { cn } from '@/lib/cn';

/**
 * ЗВЁЗДЧАТАЯ МИШЕНЬ: второй прибор печатника на этом листе.
 *
 * Её печатают на контрольном поле каждого оттиска рядом с приводочным
 * крестом, и она отвечает на другой вопрос. Крест показывает, СОШЛИСЬ ЛИ
 * ФОРМЫ; мишень показывает, ЧИСТО ЛИ ЛЁГ РАСТР. Клинья сходятся в одну
 * точку, и в этой точке краска обязана оставаться точкой: расплылась в
 * пятно, значит растискивание; вытянулась в эллипс, значит смаз;
 * раздвоилась, значит машина бьёт.
 *
 * ПОЭТОМУ ОНА ЗДЕСЬ И СТОИТ. Разгон прокрутки на этом сайте это ход машины,
 * а мишень лежит на форме и ходит вместе с ней. Прибор не украшение: он
 * показывает состояние листа, на котором стоит.
 *
 * НАРИСОВАНЫ КЛИНЬЯ, А НЕ ИХ ГРАНИЦЫ, И КЛИН СУЖАЕТСЯ К ЦЕНТРУ. Это главное
 * свойство прибора, и ровно из-за него мишень и работает. Пока луч шёл
 * палкой одной толщины от обода до самой точки, в середине набиралось пятно:
 * двадцать четыре луча по два пикселя занимают в сумме сорок восемь пикселей
 * краски, а окружность радиусом в восемь пикселей всего пятьдесят, и ближе
 * восьми пикселей от центра лучам просто некуда встать. Они смыкались, и на
 * приборе, который показывает растискивание, стояла чёрная клякса
 * растискивания. Настоящий клин от этого избавлен природой: он треугольный,
 * и к вершине у него ширины нет.
 *
 * ЗОНА СХОДА СЧИТАЕТСЯ, А НЕ ПОДБИРАЕТСЯ. У самой вершины луч сужается
 * линейно, поэтому доля краски там постоянна на любом радиусе и равна
 * RAYS × RAY_W / (2π × KNOT), то есть примерно пятой части. Пятая часть это
 * ровный серый ход к точке: пятна нет, дырки нет, и середина остаётся
 * серединой.
 *
 * НО ИЗЛОМА НА ВЫХОДЕ ИЗ ЗОНЫ НЕТ. Прямой клин выходил на полную ширину
 * углом, и угол этот было видно: по мишени шло кольцо из двадцати четырёх
 * переломов, и оно читалось как вторая, ложная окружность прибора. Поэтому
 * бок клина не прямая, а квадратичная кривая: она выходит из вершины по той
 * же линии, что задаёт KNOT (значит счёт краски в середине держится), и
 * ложится на полную ширину КАСАТЕЛЬНО на радиусе R_FULL. Перелома нет ни
 * одного, ширина набирается всей длиной луча, и прибор набухает к ободу так
 * же плавно, как настоящий клин.
 *
 * ЛУЧЕЙ МЕНЬШЕ, И КАЖДЫЙ ТОЛЩЕ. Прежде их было тридцать шесть, по канону
 * GATF, и все волосяные в 1 px. На экране такой набор сливался в серую
 * пелену: тридцать шесть волосяных на четверти экрана стоят теснее, чем
 * глаз их различает, и прибор снова читался фактурой, а не прибором.
 * Двадцать четыре клина по пятнадцать градусов дают ту же фигуру и ту же
 * меру, но каждый луч в ней виден поодиночке.
 *
 * ШИРИНА ТЕПЕРЬ В ЕДИНИЦАХ КАРТИНКИ, А НЕ В ПИКСЕЛЯХ. Сужать обводку нельзя,
 * поэтому луч стал заливкой, а вместе с обводкой ушёл и non-scaling-stroke.
 * Мишень живёт в узком диапазоне (около 135 пикселей в строке, от 133 до 178
 * в подвале), и на нём RAY_W даёт от 1,4 до 1,9 пикселя на ободе.
 * Разброс в полпикселя на краях диапазона это цена клина, и она уплачена:
 * палка одной толщины сходиться в точку не умеет.
 *
 * КРАСКА ЧЁРНАЯ. Мишень стоит в одной строке с печатью, и краска у них
 * теперь одна: полная форма K, а не волосяная линейка в треть силы. Прибор
 * печатают той же краской, что и лист, и в паре с соседним кругом он обязан
 * держать тот же вес.
 *
 * ВСЕ ДВАДЦАТЬ ЧЕТЫРЕ ЛУЧА РАВНЫ, И ЭТО ГЛАВНОЕ В ПРИБОРЕ. Прежде сквозь
 * мишень шёл волосяной крест длиннее обода, а в середине стоял вырез с
 * пятном под ним. И то и другое было лишним и обоим было чем помешать:
 * крест ложился поверх четырёх лучей и делал их вдвое чернее и длиннее
 * прочих, а вырез обрывал все лучи на полпути, и середина, ради которой
 * мишень и печатают, читалась колечком с точкой внутри. Осталось ровно то,
 * чем прибор и является: двадцать четыре одинаковых луча, сходящихся в одну
 * точку из одного центра.
 *
 * ВРАЩЕНИЕ ЕСТЬ ХОД ЦИЛИНДРА. Мишень лежит на форме, форма надета на цилиндр,
 * цилиндр крутится всё время, пока машина под током, и быстрее, когда идёт
 * лист. Отсюда два поворота на разных узлах: холостой ход на обойме
 * (бесконечный) и подача на самой форме (читается из --progress, то есть
 * ровно столько, сколько прокрутили). Сложить их в один rotate нельзя,
 * поэтому и узла два.
 *
 * НИ ОДНОЙ СТРОКИ JS. Лучи считаются один раз при загрузке модуля и
 * одинаковы на сервере и в браузере; всё движение живёт в CSS и читает те же
 * переменные, что и остальной лист. Своего rAF у мишени нет, как и у всего
 * прочего на этом сайте.
 */

/** Двадцать четыре клина по пятнадцать градусов. */
const RAYS = 24;
/**
 * Ширина луча на ободе, в единицах viewBox. Мишень растёт (см. --tail-round),
 * луч вместе с ней худеет, и на нынешнем росте это полтора пикселя краски:
 * волосяная линия, как обрезные метки листа. Прибор от этого читается
 * прибором, а не вертушкой: лучей мало, они длинные, и вес им даёт длина, а
 * не толщина.
 */
const RAY_W = 2.1;
/**
 * Угол схода: по этой линии клин выходит из вершины. Число не на глаз, при
 * нём RAYS × RAY_W / (2π × KNOT) даёт около пятой части, то есть краски в
 * середине ровно столько, чтобы она читалась серым ходом лучей, а не пятном.
 * Меньше KNOT и середина чернеет, больше и лучи истончаются раньше времени.
 */
const KNOT = 42;
/**
 * Радиус, на котором клин выходит на полную ширину, и выходит касательно.
 * Держится далеко от KNOT нарочно: ширина обязана набираться всей длиной
 * луча, иначе на месте перехода читается кольцо из двадцати четырёх углов.
 */
const R_FULL = 78;
/**
 * Обод, и он же край бокса. Выреза в середине нет: луч идёт из самого центра.
 *
 * Раньше здесь стояло 98, то есть обод не доходил до края картинки на два
 * процента радиуса. Пока мишень и печать были разного роста, эти два процента
 * никому не мешали; теперь у них ОДИН РАДИУС (`--tail-round`), и доля в CSS
 * одна на оба предмета. При ободе в 98 сотых круги снова разошлись бы, только
 * уже не долей, а геометрией картинки, и разницу пришлось бы вписывать в CSS
 * вторым числом. Луч кончается точно на границе viewBox: конец у него прямой,
 * за точку он не выступает, и обрезать нечего.
 */
const R_OUT = 100;

const CENTER = 100;
const HALF = RAY_W / 2;

/**
 * Клин: вершина в центре, два бока квадратичными кривыми до полной ширины,
 * прямой торец на ободе. `r` идёт вдоль оси луча, `p` поперёк неё; узел
 * (KNOT, ±HALF) это управляющая точка обеих кривых, она же и задаёт наклон
 * бока у самой вершины.
 */
const WEDGES = Array.from({ length: RAYS }, (_, i) => {
  const rad = ((360 / RAYS) * i * Math.PI) / 180;
  const cos = Math.cos(rad);
  const sin = Math.sin(rad);
  const at = (r: number, p: number) =>
    `${(CENTER + r * cos - p * sin).toFixed(2)} ${(CENTER + r * sin + p * cos).toFixed(2)}`;
  return [
    `M${at(0, 0)}`,
    `Q${at(KNOT, HALF)} ${at(R_FULL, HALF)}`,
    `L${at(R_OUT, HALF)}`,
    `L${at(R_OUT, -HALF)}`,
    `L${at(R_FULL, -HALF)}`,
    `Q${at(KNOT, -HALF)} ${at(0, 0)}`,
    'Z',
  ].join(' ');
});

export function StarTarget({ className }: { className?: string }) {
  return (
    <span aria-hidden className={cn('star', className)}>
      {/* Обойма: холостой ход. */}
      <span className="star-idle">
        {/* Форма: подача. Крутится ровно на столько, на сколько прокрутили. */}
        <svg viewBox="0 0 200 200" className="star-plate" fill="none">
          <g fill="var(--fg)" shapeRendering="geometricPrecision">
            {WEDGES.map((d) => (
              <path key={d} d={d} />
            ))}
          </g>
        </svg>
      </span>
    </span>
  );
}
