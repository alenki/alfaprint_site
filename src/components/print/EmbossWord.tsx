import { LOGOTYPE_CAP, LOGOTYPE_GLYPHS, LOGOTYPE_WIDTH } from '@/components/chrome/Mark';

/**
 * СЛЕПОЕ (БЛИНТОВОЕ) ТИСНЕНИЕ С ОБВОДКОЙ ВТОРОЙ ФОРМОЙ.
 *
 * Слово во весь вылет, мелом на восьми процентах, почти не видно. В полную
 * краску стоит только его ОБВОДКА, синяя. Последнее, что остаётся на экране,
 * это марка.
 *
 * ОТКУДА ОБВОДКА. На круглом бейдже агентства слово стоит белым и обведено
 * синей линией: заливка и контур там две разные краски. Здесь они и
 * разложены на две формы. Заливка ложится формой K, и ложится блинтом, то
 * есть без краски; контур печатается формой R. Ни одной линии, которой нет в
 * самом логотипе, сюда не добавлено: контур это те же пути `LOGOTYPE_GLYPHS`,
 * что и заливка, только обведённые, а не залитые.
 *
 * ПОЧЕМУ КОНТУР УХОДИТ, А ЗАЛИВКА СТОИТ. Закон ухода приводки двигает форму
 * R, и на стоящем листе обводка сидит на букве точно. На разгоне прокрутки
 * она съезжает с тиснения на пиксели, как съехала бы плёнка второй краски.
 * Имени это не ломает: буквы остаются на месте, уходит только линия вокруг.
 *
 * ТОЛЩИНА ОБВОДКИ в единицах логотипа, а не в пикселях: линия растёт вместе
 * со словом, как растёт и на бейдже. 2.4 единицы это две с половиной сотых
 * высоты слова, тоньше бейджевой: там обводка отбивает буквы от синего поля,
 * здесь ей отбивать нечего, она только очерчивает блинт.
 *
 * Восемь процентов задаются ЦВЕТОМ буквы, а не opacity на контейнере: внутри
 * полупрозрачного элемента обводка не смогла бы стать ярче фона, а она
 * обязана быть в полную краску.
 *
 * Терминология: это блинт, углублённое слепое тиснение. Конгрев это рельеф
 * наружу, другой процесс.
 */
const OUTLINE = 2.4;

/**
 * ПОЛЕ ПОД ОБВОДКУ. Рамка логотипа обнимает краску вплотную, а обводка
 * ложится по краю буквы серединой, то есть половиной толщины НАРУЖУ. У
 * рамки вплотную эта половина срезалась бы везде, где буква касается края:
 * низ овалов, верх «L» и «k», левый край «L», правый край «o». Поэтому обе
 * формы стоят в одной рамке, раздвинутой на половину обводки с запасом;
 * слово от этого мельче на семь десятых процента по ширине, чего глазу не
 * видно, а обводка остаётся целой по всему контуру.
 */
const PAD = OUTLINE / 2 + 0.4;
const VIEWBOX = `${-PAD} ${-PAD} ${(LOGOTYPE_WIDTH + 2 * PAD).toFixed(2)} ${LOGOTYPE_CAP + 2 * PAD}`;

export function EmbossWord() {
  return (
    <div className="relative select-none overflow-hidden" aria-hidden>
      <div className="relative mx-auto w-full md:w-fit">
        {/* ФОРМА K, блинт. Рост слова взят от прежнего набора: 0,675 от кегля
            `--text-emboss`, и полоса держит ровно ту же высоту, что держала.
            Ширина считается сама, из отношения сторон формы.

            НА ТЕЛЕФОНЕ СЧЁТ ОБРАТНЫЙ: слово встаёт от реза до реза, во всю
            ширину экрана, а высоту берёт из отношения сторон.

            Множитель 1.032 возвращает буквам прежний рост: рамка выше краски
            на поле под обводку, 103.2 единицы против 100. */}
        <svg
          viewBox={VIEWBOX}
          className="block h-auto w-full md:h-[calc(var(--text-emboss)*0.675*1.032)] md:w-auto"
          fill="none"
        >
          <g fill="rgba(237, 235, 230, 0.08)">
            {LOGOTYPE_GLYPHS.map((g, i) => (
              <path key={i} d={g.d} transform={g.transform} />
            ))}
          </g>
        </svg>

        {/* ФОРМА R, единственное, что напечатано в полную краску.
            Лежит ВТОРЫМ полем поверх первого, а не группой внутри него: закон
            ухода приводки сдвигает форму на пиксели, и пиксели эти обязаны
            быть экранными. Внутри вьюбокса `px` считались бы в единицах
            рисунка, то есть уход рос бы вместе с кеглем. Рамка у обеих форм
            одна, `VIEWBOX` с полем под обводку, поэтому они совпадают точно. */}
        <svg
          viewBox={VIEWBOX}
          className="plate-r absolute inset-0 h-full w-full"
          style={{ ['--gain' as string]: 0.5 }}
          fill="none"
        >
          <g
            stroke="var(--accent, var(--color-rubine-deep))"
            strokeWidth={OUTLINE}
            strokeLinejoin="round"
          >
            {LOGOTYPE_GLYPHS.map((g, i) => (
              <path key={i} d={g.d} transform={g.transform} />
            ))}
          </g>
        </svg>
      </div>
    </div>
  );
}
