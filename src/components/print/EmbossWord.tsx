import {
  LOGOTYPE_GLYPHS,
  LOGOTYPE_R_SCALE,
  LOGOTYPE_R_SHIFT,
  LOGOTYPE_VIEWBOX,
  MARK_R,
} from '@/components/chrome/Mark';

/**
 * СЛЕПОЕ (БЛИНТОВОЕ) ТИСНЕНИЕ.
 *
 * Слово во весь вылет, мелом на восьми процентах, почти не видно. В полную
 * краску виден только рубиновый мазок на первой «А». Последнее, что остаётся
 * на экране, это знак.
 *
 * ── ЧТО ИСПРАВЛЕНО ────────────────────────────────────────────────────────
 * Здесь стояли ДВЕ ПОДДЕЛКИ разом, и обе выдавали себя рядом с оригиналом.
 *
 * Первая: слово НАБИРАЛОСЬ. Гарнитура бралась похожая (Ysabeau Infant 850,
 * подобранная замером по букве «Л»), кегль и трекинг подгонялись руками. Но
 * имя фирмы во весь вылет это логотип, а не набор, и логотип обводят с
 * оригинала. Теперь слово печатается формами `LOGOTYPE_GLYPHS`, обведёнными
 * с того же файла в 1599 px, с которого сняты `MARK_K` и `MARK_R`, и
 * совпадающими с ним с точностью до одного процента прописной. Ни гарнитуры,
 * ни кегля здесь больше нет: у рисунка их не бывает. Осталось одно
 * междубуквие, `LOGOTYPE_CLEARANCE`, и оно тоже не подгоняется здесь: буквы
 * приходят уже расставленными.
 *
 * Вторая: галочка РИСОВАЛАСЬ НА МЕСТЕ. Это была обводка постоянной толщины
 * по трём точкам, взятым долями от габарита литеры. У настоящего знака
 * галочка не обводка, а МАЗОК с переменной толщиной, широкий у пятки и
 * сходящий в остриё; постоянная толщина читается галочкой из формы обратной
 * связи, а не краской агентства. Теперь сюда встаёт `MARK_R`, тот самый
 * мазок из шапки, без единой правки формы: только масштаб и сдвиг, оба
 * посчитанные в `Mark`.
 *
 * Восемь процентов задаются ЦВЕТОМ буквы, а не opacity на контейнере: внутри
 * полупрозрачного элемента мазок никогда не смог бы стать ярче фона, а он
 * обязан быть в полную краску.
 *
 * ЗАМЕРА ЗДЕСЬ БОЛЬШЕ НЕТ НИ ОДНОГО, и компонент перестал быть клиентским.
 * Прежняя редакция ловила габарит литеры через ResizeObserver и ждала
 * `document.fonts.ready`, потому что место галочки зависело от того, как
 * гарнитура отрисует «А». Буква и мазок лежат теперь в ОДНОЙ системе
 * координат, и попасть друг в друга они не могут иначе как точно.
 *
 * Терминология: это блинт, углублённое слепое тиснение. Конгрев это рельеф
 * наружу, другой процесс; на сайте типографии такую ошибку заметит их же
 * печатник.
 */
export function EmbossWord() {
  return (
    <div className="relative select-none overflow-hidden" aria-hidden>
      <div className="relative mx-auto w-full md:w-fit">
        {/* ФОРМА K. Рост слова взят от прежнего набора: прописная у него
            выходила в 0,675 от кегля `--text-emboss`, и полоса §08 держит
            ровно ту же высоту, что держала. Ширина считается сама, из
            отношения сторон формы, и подгонять её нечем и незачем.

            НА ТЕЛЕФОНЕ СЧЁТ ОБРАТНЫЙ: слово встаёт от реза до реза, во всю
            ширину экрана, а высоту берёт из отношения сторон. Кегль там
            больше ничего не решает. */}
        <svg
          viewBox={LOGOTYPE_VIEWBOX}
          className="block h-auto w-full md:h-[calc(var(--text-emboss)*0.675)] md:w-auto"
          fill="none"
        >
          <g fill="rgba(237, 235, 230, 0.08)">
            {LOGOTYPE_GLYPHS.map((g, i) => (
              <path key={i} d={g.d} transform={g.transform} />
            ))}
          </g>
        </svg>

        {/* ФОРМА R, единственное, что напечатано в полную краску.
            Лежит ВТОРЫМ полем поверх первого, а не группой внутри него: закон
            ухода приводки сдвигает форму на пиксели, и пиксели эти обязаны
            быть экранными. Внутри вьюбокса `px` считались бы в единицах
            рисунка, то есть уход рос бы вместе с кеглем. */}
        <svg
          viewBox={LOGOTYPE_VIEWBOX}
          className="plate-r absolute inset-0 h-full w-full"
          style={{ ['--gain' as string]: 0.5 }}
          fill="none"
        >
          <g
            transform={`translate(0 ${LOGOTYPE_R_SHIFT.toFixed(3)}) scale(${LOGOTYPE_R_SCALE.toFixed(5)})`}
          >
            <path d={MARK_R} fill="var(--color-rubine)" />
          </g>
        </svg>
      </div>
    </div>
  );
}
