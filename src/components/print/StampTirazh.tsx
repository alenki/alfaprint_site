import { HERO } from '@/content/site';

/**
 * ПЕЧАТЬ В КОНЦЕ ИМЕНИ.
 *
 * Круглый штамп, каким на оттиске отмечают лист, ушедший в работу. Стоит он
 * в самом конце последней строки набора, вместе со звёздчатой мишенью, и
 * место в мере берёт наравне с набором: см. `tailEm` в `fitBlock` и
 * `--hero-tail` в вёрстке. Строка имени на полосе одна, «Legko», она же
 * последняя и самая длинная, поэтому до реза достаёт слово ВМЕСТЕ с хвостом.
 *
 * КРАСКА ЧЁРНАЯ. Вторая краска на этой полосе потрачена один раз и уже
 * потрачена, на имени фирмы; кнопки второй краской на сайте нет ни одной, и
 * печать её не заводит. От бумаги её отделяет волосяная, от остального
 * набора машинный голос.
 *
 * ПОВОРОТ РАЗРЕШЁН ЕЙ ОДНОЙ. Печать кладут рукой, и ровно она не ложится
 * никогда; на всех остальных предметах листа поворота нет.
 *
 * Круг нарисован радиусом, а не картинкой: `border-radius` вместо `<svg>`,
 * потому что внутри стоит НАБОР, и он обязан остаться набором, то есть
 * выделяться, масштабироваться с кеглем читателя и брать фокусную рамку
 * из `@layer base` без единой строки на это.
 */
export function StampTirazh() {
  return (
    <a href={HERO.stampHref} className="hero-stamp hero-line" aria-label={HERO.stampLabel}>
      {/* Две строки это решение НАБОРА, а не речи: вслух они одна фраза,
          и её несёт подпись на самой ссылке. */}
      <span className="hero-stamp-set t-micro" aria-hidden>
        {HERO.stamp.map((word) => (
          <span key={word} className="hero-stamp-line">
            {word}
          </span>
        ))}
      </span>
    </a>
  );
}
