import { CLIENTS, CLIENT_MARKS } from '@/content/clients';

/**
 * ЛЕНТА ЗНАКОВ: единственное место на сайте, где стоят чужие марки.
 *
 * ГДЕ ОНА СТОИТ. Внутри §01 и последней в его потоке: лента это нижняя кромка
 * первого экрана, а не узел под ним. Отсюда и её поля: своей отбивки у ленты
 * нет вовсе, `--marks-pad` работает интерлиньяжем между именем и знаками, а
 * снизу к нему прибавлена высота контрольной шкалы. См. `PervyiProgon`.
 *
 * ЧТО ЭТО ТАКОЕ. Не «карусель логотипов» и не «нам доверяют». Это ПРОГОН:
 * лист идёт через машину, и мимо проходят те знаки, которые через неё уже
 * прошли. Отсюда все решения ниже.
 *
 *   ── Ход линейный, но скорость НЕ постоянная: её задаёт подача. Машина не
 *      разгоняется сама к середине прогона: её разгоняет печатник, и здесь
 *      печатник это читатель. Листаете вниз, лента идёт быстрее; листаете
 *      вверх, лист пошёл обратно, и знаки едут назад вместе с ним. Внутри
 *      любого мгновения ход всё так же ровный: ни одной пружины, ни одного
 *      easing: меняется скорость, а не характер движения.
 *   ── Ленту не обрезает градиент. На этом сайте край экрана это ЛИНИЯ
 *      РЕЗА, а не туман: знак, доехавший до края, просто отрезан. Растяжка
 *      в прозрачность нарисовала бы третью краску там, где их две.
 *   ── Полосу не отбивают ни линейки, ни подпись: её отбивает воздух.
 *   ── Знаки печатаются формой K и несут рубинового двойника. При спокойном
 *      чтении его нет; на разгоне прокрутки из-под каждой марки выезжает
 *      рубиновый след, тот же уход приводки, что и у знака «Альфа Принт»
 *      в шапке. Лента живёт по общему закону листа, а не рядом с ним.
 *
 * ПОДПИСИ НАД ЛЕНТОЙ НЕТ. «Печатали для» называло то, что и так читается:
 * чужие знаки на нашем листе других значений не имеют. Слово осталось
 * ДОСТУПНЫМ ИМЕНЕМ полосы: глазу оно не нужно, а скринридеру нужно, иначе
 * список марок приходит без повода.
 *
 * ПОЧЕМУ ДВЕ СТРОКИ. Это не две ленты и не две карусели. Это ОДНА лента,
 * замкнутая в кольцо: у всякого транспортёра есть рабочая ветвь и обратная,
 * и в кадре стоят обе. Верхняя идёт вперёд, нижняя возвращается, с той же
 * скоростью и по тому же периоду, потому что ремень один. Разные скорости
 * были бы враньём про механику, а одинаковый ход в одну сторону был бы
 * враньём про кольцо. Отбивки между строками нет, есть ИНТЕРЛИНЬЯЖ: ветви стоят
 * теснее, чем знаки внутри строки, и читаются одной полосой, а не двумя.
 *
 * СПИСОК ПОДЕЛЁН МЕЖДУ ВЕТВЯМИ. Верхняя несёт первые одиннадцать марок, нижняя
 * последние двенадцать; ни один знак не стоит в обеих строках, и за круг мимо
 * читателя проходит ровно двадцать три марки. Прежде обе ветви несли весь
 * список целиком, и каждый знак показывался за круг дважды: сначала в одной
 * строке, потом в другой.
 *
 * МЕХАНИКА. Ход обеих строк считает ОДНА фаза: нижняя берёт её с обратным
 * знаком (`.marks-back` в globals.css). Второго счётчика нет намеренно:
 * лентой правит прокрутка, и на развороте обе ветви обязаны развернуться в
 * одном и том же кадре.
 *
 * ПОЧЕМУ РЕЗ ИМЕННО ПО ОДИННАДЦАТОЙ. Марки приведены по ОПТИЧЕСКОМУ ВЕСУ, но
 * поровну краски само по себе не даёт поровну длины: за длину прогона отвечают
 * ещё и просветы, а их в двенадцати марках на один больше, чем в одиннадцати.
 * Поэтому место реза не берётся из середины списка, а ПОДБИРАЕТСЯ вместе с
 * порядком: суммы `ar` до реза и после стоят так, что лишний просвет ровно
 * выкуплен лишней шириной. На 2160 и выше прогоны выходят в 2977 и 2979 px,
 * полтора пикселя разницы; на 1440 это 2242 против 2218. Здесь это несущее:
 * фаза у ветвей ОДНА, и разойдись прогоны в длине, разошлись бы и скорости.
 * Самый большой разбег остаётся на телефоне: 1328 против 1297, два с половиной
 * процента, которые глазу не с чем сравнить. Порядок при этом не пострадал ни
 * в одной паре: рез прошёл между марками, а не сквозь ритм «широкий,
 * компактный», которым набран список.
 *
 * ЧЕМ ЗА РАЗДЕЛ ПЛАЧЕНО. Прогон вдвое короче списка, а он обязан быть длиннее
 * кадра: иначе знак и его собственный дубль попадают в кадр одновременно.
 * Двадцать три знака этот запас выкупают: прогон держит от 1,16 формата на
 * 2560 до 3,4 на телефоне, и кончается он только на сверхшироких, где кадр
 * перерастает сами 2977 px. Прежде, на семнадцати знаках, тот же предел стоял
 * на 2198 px и первая марка выходила у правого края уже на 2560.
 *
 * ПОЧЕМУ ТРИ ОДИНАКОВЫХ ПРОГОНА В ДОРОЖКЕ. Повтор в разметке это единственный
 * способ зациклить ленту: на фазе 1 дорожка уехала ровно на один прогон, и
 * второй прогон стоит там же, где стоял первый. Шва нет, и фазу можно
 * сбрасывать в ноль незаметно. Двух прогонов мало: к концу фазы впереди
 * остаётся ровно один, и на экране шире прогона ОБНАЖАЕТСЯ ПРАВЫЙ КРАЙ,
 * пустое поле, схлопывающееся рывком на сбросе фазы. Третий прогон отодвигает
 * этот предел с 2977 px до 5954, то есть за любой существующий монитор.
 * Всё, кроме первого прогона каждой строки, несёт `aria-hidden`: для чтения
 * этого нет.
 *
 * ПОЧЕМУ ДОРОЖКА ОТДЕЛЬНО ОТ ОБЁРТКИ. Закон приводки пишет `transform`, и ход
 * ленты пишет `transform` же. Свойство одно, и второй перебил бы первый.
 * Поэтому уход живёт на обёртке, ход на дорожках внутри: два трансформа на
 * двух узлах не спорят.
 *
 * ДОСТУПНОСТЬ. Паузы по наведению больше нет: лента отзывается на прокрутку,
 * и курсор, останавливающий то, чем правит колесо, врал бы про управление.
 * Требование WCAG 2.2.2 закрывает `prefers-reduced-motion`: там не стартует
 * ни цикл, ни Lenis, лента не едет вовсе и становится двумя обычными
 * прокручиваемыми строками. Снять вторую, как было до раздела списка, больше
 * нельзя: вместе с ней ушли бы двенадцать марок из двадцати трёх. Все знаки
 * остаются достижимы. Имя каждой марки лежит текстом: маска картинкой не
 * читается.
 */
export function ClientMarks() {
  if (CLIENT_MARKS.length === 0) return null;

  /* Ход задан временем на один знак, а не общей длительностью: список
     правится, а скорость ленты обязана остаться прежней. Это период ПОКОЯ:
     за столько фаза проходит от 0 до 1, когда лист стоит. Число уезжает в
     `--run` и оттуда его один раз считывает rAF-цикл: скорость ленты обязана
     жить рядом со списком знаков, а не в чужом файле.

     Знаков в прогоне ПОЛОВИНА списка, и делитель здесь ровно за этим: фаза
     проходит вдвое меньший путь, значит и времени ей нужно вдвое меньше. Без
     него лента поехала бы вдвое медленнее. Половина берётся дробной (11,5), а
     не по числу марок в строке: прогоны у ветвей одинаковы по ДЛИНЕ, а не по
     счёту, и одиннадцать против двенадцати здесь ничего не значат. */
  const duration = `${((CLIENT_MARKS.length / 2) * 3.1).toFixed(1)}s`;

  return (
    <section
      aria-label={CLIENTS.label}
      className="ground-paper marks-band relative isolate"
      style={{ ['--run' as string]: duration, ['--run-copies' as string]: String(RUNS) }}
    >
      <div className="marks">
        {/* Форма R: тот же набор под чёрным, невидимый на стоящем листе. */}
        <div className="marks-ghost plate-r plate-ghost" aria-hidden>
          <Lines />
        </div>

        {/* Форма K: знаки, которые читает глаз. */}
        <Lines read />
      </div>
    </section>
  );
}

/* Рез по одиннадцатой марке: половина ДЛИНЫ прогона, а не половина счёта, см.
   «ПОЧЕМУ РЕЗ ИМЕННО ПО ОДИННАДЦАТОЙ» выше. Число ходит в паре с порядком
   списка в `clients.ts`: сдвинуть одно, не пересчитав другое, значит развести
   ветви по скорости. Каждая ветвь несёт СВОЮ половину и только её. */
const HEAD = CLIENT_MARKS.slice(0, 11);
const TAIL = CLIENT_MARKS.slice(11);

/** Прогонов в дорожке. Число уезжает в `--run-copies` и оттуда его берёт шаг
    хода в CSS: разметка и трансформ обязаны считать прогоны одинаково, иначе
    цикл размыкается молча. */
const RUNS = 3;

/** Две ветви одной ленты. `read` достаётся только форме K. */
function Lines({ read }: { read?: boolean }) {
  return (
    <div className="marks-lines">
      <Line marks={HEAD} read={read} />
      {/* Обратная ветвь: вторая половина списка, ходом навстречу. */}
      <Line marks={TAIL} read={read} back />
    </div>
  );
}

/** Одна строка. Прогоны со второго нужны только чтобы сомкнуть цикл, и для
    чтения их нет: список в них тот же, что и в первом. */
function Line({
  marks,
  read,
  back,
}: {
  marks: typeof CLIENT_MARKS;
  read?: boolean;
  back?: boolean;
}) {
  return (
    <div className={back ? 'marks-track marks-back' : 'marks-track'}>
      {Array.from({ length: RUNS }, (_, i) => (
        <Run key={i} marks={marks} read={read && i === 0} />
      ))}
    </div>
  );
}

/** Один прогон списка. */
function Run({ marks, read }: { marks: typeof CLIENT_MARKS; read?: boolean }) {
  return (
    <ul className="marks-run" {...(read ? null : { 'aria-hidden': true })}>
      {marks.map((m) => (
        <li key={m.slug} className="marks-item">
          <span
            className="marks-mark"
            style={{
              ['--mask' as string]: `url(/logos/${m.slug}.png)`,
              ['--ar' as string]: m.ar,
            }}
            aria-hidden
          />
          <span className="sr-only">{m.name}</span>
        </li>
      ))}
    </ul>
  );
}
