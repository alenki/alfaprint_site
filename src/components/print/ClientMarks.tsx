import { CLIENTS, CLIENT_MARKS } from '@/content/clients';
import { asset } from '@/lib/base';

/**
 * ЛЕНТА ЗНАКОВ: единственное место на сайте, где стоят чужие марки.
 *
 * ЗНАКИ ПОКА ЗАГЛУШКИ. Все марки в `clients.ts` вымышлены и нарисованы для
 * макета: списка заказчиков у агентства в открытом доступе нет. Механика
 * ленты от этого не зависит ни в чём. Настоящие знаки встанут на место
 * заглушек тем же путём, через `scripts/marks.py`, и в этом файле не
 * изменится ни строки: длина прогона и время хода считаются от списка.
 *
 * ГДЕ ОНА СТОИТ. Внутри §01 и последней в его потоке: лента это нижняя кромка
 * первого экрана, а не узел под ним. Отсюда и её поля: своей отбивки у ленты
 * нет вовсе, `--marks-pad` работает интерлиньяжем между именем и знаками, а
 * снизу к нему прибавлена высота контрольной шкалы. См. `PervyiProgon`.
 *
 * ЧТО ЭТО ТАКОЕ. Не «карусель логотипов» и не «нам доверяют». Это ПРОГОН:
 * лист идёт через машину, и мимо проходят те знаки, которые через неё уже
 * прошли. Отсюда все решения ниже.
 *
 *   ── Ход линейный, но скорость НЕ постоянная: её задаёт подача. Машина не
 *      разгоняется сама к середине прогона: её разгоняет печатник, и здесь
 *      печатник это читатель. Листаете вниз, лента идёт быстрее; листаете
 *      вверх, лист пошёл обратно, и знаки едут назад вместе с ним. Внутри
 *      любого мгновения ход всё так же ровный: ни одной пружины, ни одного
 *      easing: меняется скорость, а не характер движения.
 *   ── Ленту не обрезает градиент. На этом сайте край экрана это ЛИНИЯ
 *      РЕЗА, а не туман: знак, доехавший до края, просто отрезан.
 *   ── Полосу не отбивают ни линейки, ни подпись: её отбивает воздух.
 *   ── Знаки печатаются формой K и несут двойника формы R. При спокойном
 *      чтении его нет; на разгоне прокрутки из-под каждой марки выезжает
 *      синий след, тот же уход приводки, что и у всего листа. Лента живёт
 *      по общему закону листа, а не рядом с ним.
 *
 * ПОДПИСИ НАД ЛЕНТОЙ НЕТ. Чужие знаки на нашем листе других значений не
 * имеют. «Наши клиенты» осталось ДОСТУПНЫМ ИМЕНЕМ полосы: глазу оно не
 * нужно, а скринридеру нужно, иначе список марок приходит без повода.
 *
 * ПОЧЕМУ ДВЕ СТРОКИ. Это не две ленты и не две карусели. Это ОДНА лента,
 * замкнутая в кольцо: у всякого транспортёра есть рабочая ветвь и обратная,
 * и в кадре стоят обе. Верхняя идёт вперёд, нижняя возвращается, с той же
 * скоростью и по тому же периоду, потому что ремень один. Отбивки между
 * строками нет, есть ИНТЕРЛИНЬЯЖ: ветви стоят теснее, чем знаки внутри
 * строки, и читаются одной полосой, а не двумя.
 *
 * ОБЕ ВЕТВИ НЕСУТ ВЕСЬ СПИСОК. На ленте услуг, которая стояла здесь до
 * заглушек, так было заведено ради одного: прогоны ветвей равны по длине по
 * построению, на любом формате и при любом наборе, и подбирать нечего. Пока
 * список делился между ветвями, рез подбирался вручную так, чтобы суммы
 * ширин двух половин сошлись до пикселя (фаза у ветвей одна, и разойдись
 * прогоны в длине, разошлись бы и скорости), и каждая новая марка ломала
 * этот подбор. Заглушки сменятся настоящими знаками, и подбор сломался бы
 * снова.
 *
 * ОБРАТНАЯ ВЕТВЬ НЕСЁТ СПИСОК ЗАДОМ НАПЕРЁД, как настоящий ремень: знак,
 * ушедший с рабочей ветви за шкив, возвращается по обратной в обратном
 * порядке. Это не украшение, а единственная раскладка, при которой строки не
 * показывают один и тот же знак друг над другом. Ветви идут навстречу, и
 * каждый знак дважды за круг проходит над своим двойником. При том же
 * порядке в обеих ветвях (хоть со сдвигом на полсписка) это случается со
 * ВСЕМИ знаками разом: дважды за круг обе строки на миг совпадают целиком.
 * При обратном порядке встречи идут не разом, а в двух неподвижных точках
 * ленты, как у шкивов, и точки эти можно вынести за кадр.
 *
 * ВЫНОСИТ ИХ ПОСЛЕДНИЙ ЗНАК, оставленный на своём месте. Середины двойников
 * сходятся в точке x ≡ (X − g) / 2 по модулю половины прогона, где X это
 * длина всего, что стоит в списке перед знаком, с которого начат обратный
 * порядок, а g просвет. Начав обратный порядок с предпоследнего знака и
 * оставив последний последним, получаем X = L − (последний знак + просвет),
 * и точки встреч стоят за левым резом на ползнака и просвет и в половине
 * прогона от него. Первая за кадром при любой ширине экрана. Вторая уходит
 * за правый рез, пока прогон длиннее двух экранов с запасом на два знака и
 * два просвета: у нынешнего набора это держится до 2350 px, а на 2560
 * встреча стоит у правого реза.
 *
 * МЕХАНИКА. Ход обеих строк считает ОДНА фаза: нижняя берёт её с обратным
 * знаком (`.marks-back` в globals.css). Второго счётчика нет намеренно:
 * лентой правит прокрутка, и на развороте обе ветви обязаны развернуться в
 * одном и том же кадре.
 *
 * ПОЧЕМУ ТРИ ОДИНАКОВЫХ ПРОГОНА В ДОРОЖКЕ. Повтор в разметке это единственный
 * способ зациклить ленту: на фазе 1 дорожка уехала ровно на один прогон, и
 * второй прогон стоит там же, где стоял первый. Шва нет, и фазу можно
 * сбрасывать в ноль незаметно. Двух прогонов мало на экране шире прогона:
 * к концу фазы впереди остаётся ровно один и обнажается правый край. Прогон
 * знаков длинный (на 1440 около 4100 px, на телефоне больше шести экранов),
 * и третий прогон держится ради одного закона со всеми форматами и с любым
 * набором, а не ради запаса. Всё, кроме первого прогона рабочей ветви, несёт
 * `aria-hidden`: для чтения этого нет, а обратная ветвь повторяет тот же
 * список.
 *
 * ПОЧЕМУ ДОРОЖКА ОТДЕЛЬНО ОТ ОБЁРТКИ. Закон приводки пишет `transform`, и ход
 * ленты пишет `transform` же. Свойство одно, и второй перебил бы первый.
 * Поэтому уход живёт на обёртке, ход на дорожках внутри: два трансформа на
 * двух узлах не спорят.
 *
 * ДОСТУПНОСТЬ. Паузы по наведению нет: лента отзывается на прокрутку, и
 * курсор, останавливающий то, чем правит колесо, врал бы про управление.
 * Требование WCAG 2.2.2 закрывает `prefers-reduced-motion`: там не стартует
 * ни цикл, ни Lenis, лента не едет вовсе и становится двумя обычными
 * прокручиваемыми строками. Маска картинкой не читается, поэтому каждая
 * марка первого прогона стоит изображением с именем (`role="img"`).
 */
export function ClientMarks() {
  if (CLIENT_MARKS.length === 0) return null;

  /* Ход задан скоростью, а не общей длительностью: список правится, а
     скорость ленты обязана остаться прежней. Это период ПОКОЯ: за столько
     фаза проходит от 0 до 1, когда лист стоит. Число уезжает в `--run` и
     оттуда его один раз считывает rAF-цикл: скорость ленты обязана жить
     рядом со списком знаков, а не в чужом файле.

     ПОЧЕМУ ВРЕМЯ СЧИТАЕТСЯ ПО ШИРИНЕ ЗНАКОВ, А НЕ ПО ИХ ЧИСЛУ. Скорость
     прежней ленты держится в пикселях в секунду: 63 px/с на 1440. Там знак
     занимает ar × 77,76 px (`--mark-h`, 5,4vw) и просвет 95,04 px
     (`--mark-gap`, 6,6vw), и прогон проходит за сумму этих длин, делённую
     на 63. Прежде время бралось на знак, 3,1 с, от средней ширины прежнего
     набора; у заглушек средняя ширина на треть больше, и то же правило
     ускорило бы ленту на треть. По ширине скорость та же при любом наборе:
     у заглушек прогон на 1440 выходит в 4095 px и 65 с, на 360 это 38 px/с,
     на 2560 это 83, как и у прежней ленты. */
  const duration = `${CLIENT_MARKS.reduce((t, m) => t + (m.ar * 77.76 + 95.04) / 63, 0).toFixed(1)}s`;

  return (
    <section
      aria-label={CLIENTS.label}
      className="ground-paper marks-band relative isolate"
      style={{ ['--run' as string]: duration, ['--run-copies' as string]: String(RUNS) }}
    >
      <div className="marks">
        {/* Форма R: тот же набор под чёрным, невидимый на стоящем листе. */}
        <div className="marks-ghost plate-r plate-ghost" aria-hidden>
          <Lines />
        </div>

        {/* Форма K: знаки, которые читает глаз. */}
        <Lines read />
      </div>
    </section>
  );
}

/* Обратная ветвь: список задом наперёд, начатый с предпоследнего знака, и
   последний знак на своём месте. Почему именно так, см. «ВЫНОСИТ ИХ
   ПОСЛЕДНИЙ ЗНАК» выше. Длина прогона у ветвей одна по построению: знаки
   те же, переставлен только порядок. */
const BACK = [...CLIENT_MARKS.slice(0, -1).reverse(), ...CLIENT_MARKS.slice(-1)];

/** Прогонов в дорожке. Число уезжает в `--run-copies` и оттуда его берёт шаг
    хода в CSS: разметка и трансформ обязаны считать прогоны одинаково, иначе
    цикл размыкается молча. */
const RUNS = 3;

/** Две ветви одной ленты. `read` достаётся только форме K. */
function Lines({ read }: { read?: boolean }) {
  return (
    <div className="marks-lines">
      <Line marks={CLIENT_MARKS} read={read} />
      {/* Обратная ветвь: тот же список задом наперёд, ходом навстречу. Для
          чтения её нет вовсе: список уже прочитан в рабочей. */}
      <Line marks={BACK} back />
    </div>
  );
}

/** Одна строка. Прогоны со второго нужны только чтобы сомкнуть цикл, и для
    чтения их нет: список в них тот же, что и в первом. */
function Line({
  marks,
  read,
  back,
}: {
  marks: typeof CLIENT_MARKS;
  read?: boolean;
  back?: boolean;
}) {
  return (
    <div className={back ? 'marks-track marks-back' : 'marks-track'}>
      {Array.from({ length: RUNS }, (_, i) => (
        <Run key={i} marks={marks} read={read && i === 0} />
      ))}
    </div>
  );
}

/** Один прогон списка. */
function Run({ marks, read }: { marks: typeof CLIENT_MARKS; read?: boolean }) {
  return (
    <ul className="marks-run" {...(read ? null : { 'aria-hidden': true })}>
      {marks.map((m) => (
        <li key={m.slug} className="marks-item">
          <span
            className="marks-mark"
            style={{
              ['--mask' as string]: `url(${asset(`/logos/${m.slug}.png`)})`,
              ['--ar' as string]: m.ar,
            }}
            {...(read ? { role: 'img', 'aria-label': m.name } : null)}
          />
        </li>
      ))}
    </ul>
  );
}
