import { CONSENT } from '@/content/site';
import { cn } from '@/lib/cn';

/**
 * СТРОКА СОГЛАСИЯ ПОД ФОРМОЙ.
 *
 * ОДИН КОМПОНЕНТ НА ДВА ЛИСТА, И ЛИСТ ТЕПЕРЬ ОДИН. Фраза стояла под бланком
 * `/kontakty` и под парой действий калькулятора; калькулятор снят с сайта
 * целиком, и форма на сайте осталась одна. Компонент не сворачивается обратно
 * в разметку бланка: это заявление о том, на что человек соглашается, и жить
 * оно обязано в одном месте, чтобы не разойтись при первой же правке текста,
 * когда форм снова станет две.
 *
 * ССЫЛКА НЕ СИНЯЯ. Хрома на сайте одна, рубин, и ради юридической строки
 * вторая не заводится. В образце, с которого снята фраза, ссылка была синей
 * по умолчанию браузера; здесь она набрана на разряд темнее окружающего
 * серого и подчёркнута волосяной, а рубин берёт по наведению.
 *
 * ВОЛОСЯНАЯ СТОИТ В ПОКОЕ, А НЕ ПОЯВЛЯЕТСЯ ПО НАВЕДЕНИЮ. Соседние ссылки
 * листа («Скопировать текст», разделы подвала) живут на `link-rule`, где
 * черта рисуется только под курсором: там это законно, потому что они стоят
 * особняком и читаются действием по одному своему месту. Здесь ссылка сидит
 * ВНУТРИ серой фразы, и без черты в покое она не отличима от набора вокруг:
 * пять слов из десяти оказались бы кликабельны втайне. На телефоне наведения
 * нет вовсе, и это довод тот же, только сильнее.
 *
 * ОТКРЫВАЕТСЯ В НОВОЙ ВКЛАДКЕ, И ЭТО ЕДИНСТВЕННОЕ МЕСТО НА САЙТЕ, ГДЕ ВНУТРЕННЯЯ
 * ССЫЛКА ВЕДЁТ СЕБЯ ТАК. Довод механический: строка стоит под НЕОТПРАВЛЕННОЙ
 * формой. Набранное в бланке живёт в состоянии React и в документе нигде не
 * записано; уйди читатель с листа, чтобы свериться с документом, и вернись
 * назад, он вернётся к пустым полям. Заставлять человека выбирать между
 * «прочитать, на что соглашаюсь» и «не набирать заново» это ровно то, из-за
 * чего таких документов не читают.
 *

 * Тот же довод держал строку и на снятом калькуляторе: набранного там не было,
 * но выбранные девять параметров жили тем же состоянием и терялись так же.
 *
 * Ссылки на тот же лист из подвала при этом остаются обычными: там терять
 * нечего, и `target` на них был бы жестом, а не починкой.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Ни галочки, ни состояния, ни `useState`: см. `CONSENT` в
 * `content/site.ts`. Компонент печатает строку и больше не умеет ничего.
 */
export function Soglasie({ className }: { className?: string }) {
  return (
    <p className={cn('soglasie', className)}>
      {CONSENT.before}
      <a href={CONSENT.href} target="_blank" rel="noreferrer" className="soglasie-link">
        {CONSENT.link}
      </a>
      {CONSENT.after}
    </p>
  );
}
